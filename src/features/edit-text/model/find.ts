import { resolveAnchor } from 'entities/anchor'
import { entryStore } from 'entities/entry'
import type { Entry } from 'shared/model/format'
import { APPLIED_ATTRIBUTE } from 'shared/config/constants'
import { createLogger } from 'shared/lib/log'
import { currentRoute } from 'shared/lib/route'

const log = createLogger('edit-text:find')

/**
 * Уже существующая правка на месте клика — или `null`, если место ещё не правили.
 *
 * Возвращается ПАРА: запись и элемент, которому она принадлежит. До вехи
 * «правка текста в кнопках и ссылках» кликнутый узел и элемент записи совпадали
 * всегда — подъём доводил цель до того же элемента, на котором висит правка, —
 * и отдавать одну запись было довольно. Граница правки это ломает: в
 * `<p>Смотри <a>прайс</a> здесь</p>` с уже внесённой правкой АБЗАЦА клик
 * по ссылке находит запись абзаца, а кликнутый узел — ссылка. Меряй окно
 * по нему, бери у него шрифт, считай по нему простой текст — и получишь
 * половинки от разных элементов.
 *
 * Два шага и именно в этом порядке (решение 7).
 *
 * Шаг 1 — метка `data-kalka-applied` на элементе или его предке. Движок ставит
 * её только после успешного наложения, поэтому шаг самый дешёвый и самый точный.
 * Предок проверяется тоже: правка накладывается на элемент целиком, а кликнуть
 * рецензент может по строчному узлу внутри него.
 *
 * Шаг 2 — перебор записей текущего маршрута с разрешением якоря. Он ОБЯЗАТЕЛЕН,
 * потому что метки законно нет в трёх случаях: запись типа `style-wish` в DOM
 * не применяется вовсе, страница показана в оригинале (FR-21), и запись
 * помечена `lost`. Без второго шага повторный клик по такому месту создал бы
 * ВТОРУЮ запись на тот же элемент — прямое нарушение FR-10.
 */
export interface FoundEntry {
  entry: Entry
  /**
   * Элемент, которому запись ПРИНАДЛЕЖИТ, — не обязательно кликнутый узел.
   *
   * По нему меряется окно правки, берётся шрифт носителя и считается признак
   * простого текста. Все трое обязаны считаться по ОДНОМУ элементу.
   */
  element: Element
}

export function findEntryFor(el: Element): FoundEntry | null {
  const marked = el.closest(`[${APPLIED_ATTRIBUTE}]`)
  const markedId = marked?.getAttribute(APPLIED_ATTRIBUTE)
  if (markedId && marked) {
    const byMark = entryStore.get(markedId)
    if (byMark) {
      log.debug('правка найдена', {
        id: byMark.id,
        шаг: 'метка наложения',
        // Кликнули не по тому элементу, на котором висит правка: клик пришёлся
        // на ссылку внутри правленого абзаца. Текст страницы не логируется.
        внутриЗаписи: marked !== el,
      })
      return { entry: byMark, element: marked }
    }
  }

  // Документ берётся у самого элемента, а не из глобали: слайс инструмента
  // к чужому DOM не обращается — он лишь передаёт дальше то, что ему дали
  // (ARCHITECTURE.md, решение 1).
  const root = el.ownerDocument
  const route = currentRoute()
  for (const entry of entryStore.list()) {
    if (entry.route !== route) continue

    const found = resolveAnchor(entry.anchor, entry.was, root)
    if ('status' in found) continue
    /*
     * Совпадением считается и «разрешённый элемент СОДЕРЖИТ кликнутый»:
     * клик по ссылке внутри правленого абзаца обязан открыть правку абзаца,
     * а не завести вторую запись поверх первой (FR-10). Именно этот шаг
     * работает в трёх случаях, где метки законно нет: режим «оригинал»
     * (FR-21), запись `style-wish` и статус `lost`.
     *
     * Обратного послабления НЕТ и не будет: правка на ссылке не имеет права
     * перехватывать клик по абзацу вокруг неё — там правка ещё не вносилась,
     * и человек ждёт новую запись.
     */
    if (found.element !== el && !found.element.contains(el)) continue

    log.debug('правка найдена', {
      id: entry.id,
      шаг: 'разрешение якоря',
      внутриЗаписи: found.element !== el,
    })
    return { entry, element: found.element }
  }

  log.debug('место ещё не правили')
  return null
}
