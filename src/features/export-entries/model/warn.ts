import { entryStore } from 'entities/entry'
import { createLogger } from 'shared/lib/log'
import { safely } from 'shared/lib/safe'

const log = createLogger('export:guard')

/*
 * Предупреждение при закрытии вкладки с неэкспортированными правками (FR-26).
 *
 * ЭТО ЕДИНСТВЕННОЕ МЕСТО, где «Калька» намеренно меняет поведение чужой
 * страницы. Всё остальное виджет либо читает, либо рисует у себя в теневом
 * корне; здесь он вмешивается в то, как носитель закрывается.
 *
 * Отсюда два жёстких условия. Первое: слушатель висит ТОЛЬКО пока есть что
 * терять — набор непуст и `exportedAt() === null`. Постоянно висящий
 * `beforeunload` ломает заказчику обычную навигацию по прототипу и мешает
 * bfcache, то есть портит ровно тот прототип, который рецензент пришёл смотреть.
 * Второе: снятие обязательно и полное — иначе после `window.__kalka.unmount()`
 * страница продолжает переспрашивать при закрытии, и обещание «неотличима
 * от исходной» нарушено.
 */

/**
 * Надо ли сейчас переспрашивать при закрытии.
 *
 * Считаются ТОЛЬКО СВОИ правки — те, у которых нет записи о происхождении
 * (решение 19 плана вехи). Импортированные уже лежат файлом на диске
 * у разработчика: терять при закрытии вкладки нечего, а переспрашивать после
 * каждого разбора чужого файла значит приучить человека жать «уйти» не читая, —
 * и тогда предупреждение перестанет работать там, где оно действительно нужно.
 *
 * Со строкой счётчика (FR-25) расхождения нет: она продолжает считать ВСЕ
 * записи и сбрасывать состояние на «не экспортировано» при импорте. Это разные
 * вопросы — счётчик про файл, вопрос браузера про потерянную работу.
 */
function hasUnsaved(): boolean {
  return entryStore.localCount() > 0 && entryStore.exportedAt() === null
}

/**
 * Поднимает предупреждение при закрытии вкладки. Возвращает полное снятие.
 *
 * Собственный текст вопроса показать нельзя: браузеры давно игнорируют его
 * и показывают своё сообщение. Пытаться не надо — единственное, что они
 * принимают, это `preventDefault()` вместе с `returnValue`.
 */
export function startUnsavedGuard(): () => void {
  let attached = false

  const onBeforeUnload = safely(log, 'вопрос при закрытии вкладки', (event: BeforeUnloadEvent) => {
    event.preventDefault()
    // Старая форма всё ещё нужна: часть браузеров реагирует только на неё.
    event.returnValue = ''
  })

  function sync(): void {
    const needed = hasUnsaved()
    if (needed === attached) return

    attached = needed
    if (needed) window.addEventListener('beforeunload', onBeforeUnload)
    else window.removeEventListener('beforeunload', onBeforeUnload)

    log.debug(needed ? 'вопрос при закрытии включён' : 'вопрос при закрытии снят', {
      своих: entryStore.localCount(),
      всего: entryStore.list().length,
    })
  }

  // Снимок берётся сразу: набор восстанавливается из хранилища ДО подъёма
  // guard, и ждать первого уведомления значило бы не переспрашивать про
  // правки прошлой сессии до первого же изменения набора.
  sync()
  const stopStore = entryStore.subscribe(sync)

  return (): void => {
    stopStore()
    if (attached) {
      window.removeEventListener('beforeunload', onBeforeUnload)
      attached = false
      log.debug('вопрос при закрытии снят вместе с виджетом')
    }
  }
}
