import { sanitizeFileName } from 'shared/api/files'

/*
 * Имя файла выгрузки (FR-29): `kalka-<хост>-<ГГГГ-ММ-ДД-ЧЧММ>.json`.
 *
 * `Date` и `Location` приходят ПАРАМЕТРАМИ, а не берутся глобальными: функция
 * остаётся проверяемой без браузера и без подмены системного времени.
 */

/** Двузначное число с ведущим нулём. */
function two(value: number): string {
  return String(value).padStart(2, '0')
}

/**
 * Собирает имя файла выгрузки.
 *
 * Хост берётся с ПОРТОМ (`location.host`, а не `hostname`): прототипы живут
 * на адресах вида `example.internal:3711`, и без порта два стенда на одной машине
 * дают одинаковые имена файлов.
 *
 * Время в имени сверх требуемой FR-29 даты — потому что рецензент за день
 * экспортирует несколько раз, а браузер иначе выдаёт `kalka-... (1).json`,
 * и в переписке невозможно понять, какой из файлов свежее.
 *
 * Дата и время ЛОКАЛЬНЫЕ, не UTC: рецензент сопоставляет файл со своим днём,
 * а не с Гринвичем.
 *
 * Расширение осталось ПАРАМЕТРОМ, хотя значение у него теперь одно.
 * Не ради будущего второго файла — его не будет, — а ради места вызова:
 * `exportFileName('json', …)` в отчёте прямо говорит, ИМЯ ЧЕГО он собирает,
 * тогда как `exportFileName(…)` пришлось бы читать, идя сюда. Тип сузился
 * до `'json'`, поэтому лишнего значения не подставить.
 */
export function exportFileName(ext: 'json', now: Date, loc: Location): string {
  // Запасное значение нужно на `file://` и на адресах, от которых после чистки
  // не осталось ни одного разрешённого знака: имя файла без хоста собрать можно,
  // а имя, начинающееся с двух дефисов подряд, — уже мусор.
  const host = sanitizeFileName(loc.host) || 'site'
  const stamp =
    `${now.getFullYear()}-${two(now.getMonth() + 1)}-${two(now.getDate())}` +
    `-${two(now.getHours())}${two(now.getMinutes())}`

  return `kalka-${host}-${stamp}.${ext}`
}
