import { buildExchangeFile, entryStore, toJsonText } from 'entities/entry'
import { downloadText } from 'shared/api/files'
import { createLogger } from 'shared/lib/log'
import { exportFileName } from './name'

const log = createLogger('export')

const JSON_MIME = 'application/json;charset=utf-8'

/**
 * Выгружает набор правок ОДНИМ файлом — файлом обмена (FR-27).
 *
 * ── Почему одним, а не двумя ────────────────────────────────────────────────
 *
 * Вторым файлом была читаемая таблица для человека. Её заменил печатный отчёт:
 * он показывает не только «было/стало» строками, но и КАРТИНКУ места каждой
 * правки, чего таблица не умела и уметь не могла. Держать оба значило бы
 * держать два человекочитаемых вывода из одних данных — и однажды получить
 * между ними расхождение, о котором никто не узнает, потому что читают
 * обычно один.
 *
 * `parent` — узел внутри теневого корня «Кальки»: временный якорь скачивания
 * добавляется ТУДА, а не в `document.body` (см. шапку `shared/api/files.ts`).
 * Панель предпросмотра передаёт сюда `ref` на собственный корневой узел.
 *
 * Возвращает `true`, когда загрузка поставлена. Наружу не бросает ничего.
 */
export function exportEntries(parent: Element): boolean {
  const entries = entryStore.list()

  if (entries.length === 0) {
    // До этого места доходить не должно: кнопка «Экспорт» при пустом наборе
    // неактивна. Файл из нуля записей формально валиден и практически
    // бессмысленен — он выглядит как «рецензент ничего не нашёл», хотя
    // означает «рецензент промахнулся мимо кнопки».
    log.warn('экспорт пустого набора отклонён')
    return false
  }

  const exportedAt = new Date()
  const iso = exportedAt.toISOString()

  const file = buildExchangeFile({
    entries,
    // `origin`, а не полный адрес: файл описывает САЙТ, а не ту страницу,
    // на которой рецензент нажал кнопку. Страница у каждой записи своя, в поле
    // `route`.
    site: location.origin,
    /*
     * Имя рецензента ПУСТО ВСЕГДА, и это не заглушка.
     *
     * Поля у продукта больше нет: правки снимает один человек, сценария,
     * в котором над ними работает группа, нет, и различать авторов незачем.
     * Вопрос перед каждой выгрузкой стоил внимания и не давал ничего.
     *
     * Само поле из файла НЕ убрано, хотя и не заполняется. Имена полей —
     * часть контракта `format: 1`, и удаление потребовало бы `format: 2`:
     * разбор чужой версии отказывает целиком, то есть все уже выгруженные
     * файлы перестали бы загружаться ради вычеркнутой строки. Пустое значение
     * контракт допускает прямо — обязательность там про наличие поля,
     * а не про непустоту.
     */
    author: '',
    exportedAt: iso,
  })

  const jsonName = exportFileName('json', exportedAt, location)

  const jsonOk = downloadText({
    name: jsonName,
    text: toJsonText(file),
    mime: JSON_MIME,
    parent,
  })

  /*
   * Уровень `debug`, а не `info`, и это существенно: имя содержит хост
   * прототипа, а строка `info` ниже намеренно не называет ни адрес сайта,
   * ни автора, ни тексты правок. Отладочный вывод выключен по умолчанию
   * и вырезается production-сборкой (RULES.md), так что за пределы машины
   * разработчика хост отсюда не уходит.
   */
  log.debug('готова загрузка файла обмена', { файлОбмена: jsonName })

  if (!jsonOk) {
    // Набор НЕ помечается экспортированным: сказать рецензенту «выгружено»,
    // когда файл не скачался, значит соврать ровно в том месте, ради которого
    // сделана FR-25.
    log.warn('экспорт не состоялся', { файлОбмена: false })
    return false
  }

  /*
   * Условие «и вторая загрузка тоже встала» отсюда УШЛО вместе со вторым
   * файлом, и это не механическое упрощение.
   *
   * Раньше сорванная вторая загрузка отменяла пометку «выгружено», хотя файл
   * обмена уже лежал на диске: виджет говорил «не выгружено» про выгруженное.
   * Теперь файл ровно один, и его успех — это и есть успех выгрузки.
   * Печать отчёта на эту дорожку не влияет вовсе: файл обмена скачивается
   * сам по себе, и сбой отчёта его не отменяет.
   */
  entryStore.markExported(iso)
  // Ни адрес сайта, ни имя автора, ни тексты правок в лог не уходят.
  log.info('экспорт выполнен', { записей: entries.length })
  return true
}
