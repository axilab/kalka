import { plainNow, styleWords, toolOf } from 'entities/entry'
import type { Entry } from 'shared/model/format'
import type { Tool } from 'shared/model/ui'
import { TOOL_LABELS } from 'shared/model/ui'

/*
 * Содержание ОДНОЙ строки описи правок.
 *
 * ── Почему вид правки называется инструментом ───────────────────────────────
 *
 * Прежний документ называл вид правки по адресату («требует решения», «правки
 * текста») и тем самым распределял работу между людьми. Опись ничего никому
 * не поручает: она называет вид правки тем инструментом, которым рецензент её
 * сделал, — «Текст», «Область», «Указатель». Это ровно то слово, которое стоит
 * у той же записи в списке разбора на экране, и второго словаря заводить нельзя:
 * раскладка уже посчитана в `toolOf()`, слова уже названы в `TOOL_LABELS`.
 *
 * Пожелание по размеру и цвету (`style-wish`) попадает в «Текст», потому что
 * создаёт его тот же редактор. Это не упрощение, а факт: инструмент один.
 *
 * ── Три части содержания, а не две ──────────────────────────────────────────
 *
 * `was`, `now` и пожелание по размеру и цвету — ТРИ независимых факта записи,
 * и запись может нести любые два из них сразу. Правка текста бывает с
 * пожеланием, пожелание бывает с пояснением рецензента. Склеить пожелание
 * со «стало» значит потерять один факт из двух: читатель увидит либо новый
 * текст, либо просьбу сделать его крупнее, но не обе.
 *
 * Поэтому раскладка ОДНА на все три типа записи, без ветвления по слотам.
 * У пожелания без пояснения `now` выходит пустым, и на бумаге строка «размер
 * 44px, цвет #1a3d7c» встаёт ровно туда, где у правки текста стоит «стало», —
 * то есть нужный вид получается сам, общим правилом, а не отдельной веткой.
 *
 * ── Почему `now` разбирается не у всех ──────────────────────────────────────
 *
 * `text-override` и `style-wish` несут в `now` разметку редактора, и снятие
 * тегов в проекте живёт в одном месте — `plainNow`. У записи типа `comment`
 * в `now` лежит текст рецензента КАК ЕСТЬ (`entities/entry/model/draft.ts`):
 * разметки редактора там нет вовсе. Пропусти мы его через тот же разбор — он
 * не «снял бы теги», а съел бы написанное: текст «нужно <b>жирным</b>» приехал
 * бы на бумагу как «нужно жирным», то есть потерялось бы ровно то, что рецензент
 * и показывал. Двух путей разбора здесь нет: есть один разбор для разметки
 * и его отсутствие у сырого текста.
 *
 * ── Разметки здесь нет ──────────────────────────────────────────────────────
 *
 * Функция отдаёт ТЕКСТ. Экранирование и вёрстка — дело сборщика документа:
 * так строку можно проверить тестом без разбора разметки, а правила
 * экранирования остаются в одном месте.
 */

/** Готовые к печати части одной строки описи. Пустая строка — части нет. */
export interface ReportLine {
  /**
   * Инструмент записи. `null` — определить не удалось.
   *
   * Лежит рядом со словом намеренно и вторую истину не заводит: `toolOf()`
   * зовётся ОДИН раз, а показывается результат в двух видах — значком на бирке
   * и словом в строке. Считать инструмент второй раз в сборщике документа
   * значило бы развести два вычисления одного и того же.
   */
  tool: Tool | null
  /** Вид правки словом: инструмент, которым она сделана. */
  kind: string
  /** Маршрут страницы, на которой сделана правка. */
  route: string
  /** Исходный текст места. */
  was: string
  /** Новый текст или пояснение рецензента. */
  now: string
  /** Пожелание по размеру и цвету человеческими словами. */
  styleWish: string
}

/**
 * Содержание строки описи по записи.
 *
 * `doc` приходит параметром, а не берётся глобальным: функция остаётся
 * проверяемой и не тянет за собой браузер — тот же приём, что у `plainNow`.
 *
 * Вид может выйти ПУСТЫМ. `toolOf()` возвращает `null` у записи, в которой
 * нет ни `rect`, ни `point` при типе `comment`; шапка `entities/entry/model/tool.ts`
 * держит эту ветку явной намеренно и называет её недостижимой по контракту
 * формата. Глушить её приведением значило бы спорить с соседним слайсом,
 * поэтому здесь она даёт пустой вид: маршрут, «было» и «стало» на месте,
 * запись заказчика из документа не пропадает, а выдуманного названия
 * инструмента в нём не появляется. Тот же принцип, что у вырожденного якоря
 * в `mark.ts`: показать нечего — не показываем, а не придумываем.
 */
export function lineOf(entry: Entry, doc: Document): ReportLine {
  const tool = toolOf(entry)

  return {
    tool,
    kind: tool === null ? '' : TOOL_LABELS[tool],
    route: entry.route,
    was: entry.was,
    now: entry.type === 'comment' ? entry.now : plainNow(entry, doc),
    styleWish: styleWords(entry.style),
  }
}
