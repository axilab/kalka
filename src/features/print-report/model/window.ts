import type { Cutout } from 'shared/model/layer'

/*
 * Окно показа вырезки: что из кадра видно в колонке места и в каком масштабе.
 *
 * ── Зачем окно, если у вырезки уже есть полоса ──────────────────────────────
 *
 * `Cutout.band` посчитана под ШИРОКУЮ колонку прежнего документа: запас вокруг
 * якоря 80 px, а у записей типа `comment` — 160 px (`CUTOUT_BAND_PAD_PX` /
 * `CUTOUT_BAND_PAD_WIDE_PX`). В описи колонка места — 240 px, и взяв полосу как
 * вертикаль окна, мы получили бы ленту «якорь + 320 px», в которой место правки
 * становится точкой. Вдобавок полоса режет только по вертикали, а кадр снят
 * во всю ширину страницы: без обрезки по горизонтали масштаб падает с ≈0.45
 * до ≈0.17, и вёрстка в превью превращается в серое пятно.
 *
 * Поэтому опись считает СВОЁ окно, по обеим осям, и `band` не читает вовсе.
 *
 * ── Следствие, которое здесь только называется ──────────────────────────────
 *
 * `band` был единственным читателем — значит вместе с ним перестают на что-либо
 * влиять и `wide` (он с некоторых пор управляет только запасом полосы), и обе
 * константы запаса. Вычистить это отсюда нельзя: `wide` — обязательное поле
 * `MakeCutoutInput`, и проставляют его четыре вызывающих в трёх слайсах,
 * а само поле живёт в `entities/cutout`. Уборка — отдельная работа. Названо
 * здесь, чтобы следующий читатель не считал полосу живой и не решил, что
 * про неё забыли.
 *
 * Само поле `band` из `Cutout` при этом НЕ убирается, и не по инерции: его
 * наличие сторожит проверка схемы при восстановлении вырезки из хранилища
 * (`entities/cutout/model/buffer.ts`). Вырезки уже лежат в `localStorage`
 * у рецензентов, и запись без полосы будет там отброшена как несовместимая.
 *
 * ── Обрезка — дело отчёта, а не съёмки ──────────────────────────────────────
 *
 * Ровно та же причина, по которой ужимание кадра всегда жило здесь: ширину
 * своей колонки знает только документ. `entities/cutout` не трогается.
 */

/**
 * Запас вокруг якоря по каждой стороне, px несжатого кадра.
 *
 * Без запаса превью показывает голый элемент, и вопрос «где это на странице»
 * остаётся без ответа: строка текста, вырезанная из вёрстки, узнаётся не лучше
 * самой строки, которая и так стоит рядом словами. Запас нужен, чтобы в кадр
 * попали соседи — заголовок сверху, кнопка снизу, край колонки сбоку.
 *
 * 120 px — это примерно пара строк текста сверху и снизу при обычной вёрстке
 * прототипа и заметный кусок соседнего блока по бокам. На типичном якоре
 * шириной ≈320 px окно выходит ≈560 px, то есть масштаб ≈0.43 против ≈0.17
 * без обрезки — разница между различимым текстом и серым пятном.
 *
 * Величина настраиваемая и проверяется глазами на живом прототипе: тесты
 * отвечают на вопрос «правильно ли посчитано», а не «читается ли на бумаге».
 */
const WINDOW_PAD_PX = 120

/** Окно показа в пикселях НЕСЖАТОГО кадра плюс масштаб, которым оно ужимается. */
export interface ShowWindow {
  /** Отступ окна от левого края кадра. */
  x: number
  /** Отступ окна от верха кадра. */
  y: number
  /** Ширина окна. */
  w: number
  /** Высота окна. */
  h: number
  /**
   * Во сколько раз окно ужимается под колонку места.
   *
   * Никогда не больше 1: мелкий кадр растягивать нельзя — вырезка это разметка
   * со вкомпилированными стилями, и растянутая она приедет размытой подписью
   * поверх крупного фона, а не увеличенным местом.
   */
  scale: number
}

/**
 * Окно показа вокруг якоря и масштаб под колонку места.
 *
 * `placePx` приходит ПАРАМЕТРОМ, а не берётся из соседнего модуля. Ширина
 * колонки выведена из полей `@page` печатного документа и меняется вместе
 * с ними, поэтому живёт там же, где эти поля, — в сборке документа. Тянуть её
 * оттуда сюда значило бы завести круговой импорт между документом и его
 * арифметикой; отдать параметром — заодно сделать функцию проверяемой на любой
 * ширине, а не только на текущей.
 *
 * Возвращаемые координаты — в пикселях НЕСЖАТОГО кадра, в тех же, в которых
 * посчитан `anchorBox`. Так окно и метка остаются в одной системе координат,
 * и масштаб применяется ровно один раз — при показе.
 */
export function windowOf(cutout: Cutout, placePx: number): ShowWindow {
  const { anchorBox, width, height } = cutout

  // Окно упирается в края кадра, а не выходит за них: за краем ничего нет,
  // и пустое поле в превью читалось бы как часть вёрстки.
  const x = Math.max(0, anchorBox.x - WINDOW_PAD_PX)
  const y = Math.max(0, anchorBox.y - WINDOW_PAD_PX)
  const right = Math.min(width, anchorBox.x + anchorBox.w + WINDOW_PAD_PX)
  const bottom = Math.min(height, anchorBox.y + anchorBox.h + WINDOW_PAD_PX)

  // У широкого якоря окно совпадает с кадром — это нормальный предел, а не сбой:
  // место занимает всю ширину страницы, и показать его уже некуда.
  const w = Math.max(0, right - x)
  const h = Math.max(0, bottom - y)

  // Вырожденный кадр нулевой ширины дал бы деление на ноль и `Infinity`
  // в атрибуте `transform`. Масштаб 1 у пустого окна ничего не показывает
  // и ничего не ломает.
  const scale = w === 0 ? 1 : Math.min(1, placePx / w)

  return { x, y, w, h, scale }
}
