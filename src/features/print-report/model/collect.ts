import { cutoutBuffer, makeCutout } from 'entities/cutout'
import { entryStore, sanitizeHtml } from 'entities/entry'
import { usesTextPath } from 'shared/lib/dom'
import { createLogger } from 'shared/lib/log'
import type { Entry } from 'shared/model/format'
import type { Cutout } from 'shared/model/layer'

const log = createLogger('report:collect')

/*
 * Откуда отчёт берёт картинку места правки.
 *
 * ── Почему источников два ───────────────────────────────────────────────────
 *
 * Съёмка в момент правки одна не справляется. Правки, сделанные до появления
 * снимков, остались бы без картинок навсегда; то же и с правками, чьи вырезки
 * снялись, ушли в напечатанный документ и были сняты очисткой. Отчёт из шести
 * записей без единой картинки читается как сломанный — проверено на живом
 * человеке, он решил, что кнопка не работает.
 *
 * Запрет снимать позже был лишним, и это видно по коду. Записи типов `comment`
 * и `style-wish` в DOM не применяются НИКОГДА — их элемент нетронут, и вырезка,
 * снятая позже, побайтово та же. У `text-override` элемент несёт «стало»,
 * но оригинал лежит в `wasHtml`, и код его подстановки давно написан
 * и работает: на нём держится тумблер «показать оригинал».
 *
 * ── Порядок источников: буфер, потом живой элемент ──────────────────────────
 *
 * У буфера приоритет, и это не вкусовщина. Снятое в момент правки заведомо
 * показывает ИСХОДНОЕ состояние места: элемент тогда ещё не был тронут слоем,
 * догадок не потребовалось, и вырезка уже прошла самопроверку. Съёмка на месте
 * восстанавливает «было» подстановкой и потому чуть менее точна (оговорки —
 * в шапке `build.ts`). Точное лучше восстановленного.
 *
 * ── Почему снятое на месте НЕ пишется в буфер ───────────────────────────────
 *
 * Буфер существует ради записей с ДРУГИХ страниц: их места в текущем DOM нет,
 * и другого источника у них не будет. Место, найденное на текущей странице,
 * доступно всё время, пока страница открыта, — писать его в буфер значило бы
 * раздувать хранилище тем, что и так под рукой, и ускорять вытеснение по
 * потолку ровно тех вырезок, ради которых буфер и заведён.
 */

/**
 * Картинка места правки или `null`, если места на этой странице нет.
 *
 * `null` — это штатный ответ, а не сбой: запись с другой страницы снять нечем,
 * и отчёт покажет её текстом с явной пометкой.
 */
export function cutoutFor(entry: Entry, doc: Document): Cutout | null {
  const stored = cutoutBuffer.get(entry.id)
  if (stored !== null) {
    log.debug('вырезка взята из буфера', { id: entry.id, тип: entry.type })
    return stored
  }

  const element = entryStore.statusOf(entry.id)?.element

  // `isConnected` обязателен, а не «на всякий случай»: хранилище прямо
  // предупреждает, что носитель мог перерисовать блок между проходом
  // наложения и печатью. Оторванный узел размеров не имеет, и вырезка вышла бы
  // пустой — то есть картинкой, которая врёт.
  if (element === undefined || !element.isConnected) {
    log.debug('вырезки нет: места этой правки на текущей странице не найдено', {
      id: entry.id,
      тип: entry.type,
    })
    return null
  }

  /*
   * Элемент правки текста несёт «стало», а на картинке должно быть «было».
   * Подмена идёт в ОТСОЕДИНЁННОМ клоне — страница носителя не трогается вовсе.
   *
   * Пустой `wasHtml` подстановкой не считается: у записи, снятой до вехи
   * машиночитаемости, он может быть пуст, и подстановка стёрла бы содержимое
   * кадра, оставив пустую картинку вместо честной. Пустой `was` — то же самое
   * и по той же причине.
   *
   * Путь выбирается по `usesTextPath(element, entry.wasHtml)`. Второй аргумент
   * обязателен и здесь: элемент в момент печати несёт «стало», то есть уже
   * наложенное, и спрашивать структуру у него значило бы получать разные
   * ответы на разных проходах.
   */
  const подменяем = entry.type === 'text-override'
  const текстовыйПуть = подменяем && usesTextPath(element, entry.wasHtml)

  const replaceText = текстовыйПуть && entry.was !== '' ? entry.was : undefined
  const replaceContent =
    !текстовыйПуть && подменяем && entry.wasHtml !== ''
      ? sanitizeHtml(entry.wasHtml, doc)
      : undefined

  const cutout = makeCutout({
    anchor: element,
    // Та же высота полосы, что при съёмке в момент правки: у замечаний
    // окрестности вдвое больше, «это убрать» без окружающего блока не значит
    // ничего. Ширину кадра `wide` не решает с тех пор, как он берётся во всю
    // ширину страницы у любой записи.
    wide: entry.type === 'comment',
    replaceContent,
    replaceText,
  })

  log.debug(cutout === null ? 'вырезку на месте снять не удалось' : 'вырезка снята на месте', {
    id: entry.id,
    тип: entry.type,
    подмена: replaceContent !== undefined || replaceText !== undefined,
    путь: текстовыйПуть ? 'текст' : 'разметка',
  })

  return cutout
}

/**
 * Собирает картинки для всего набора РАЗОМ, по одной съёмке на запись.
 *
 * ── Почему карта, а не функция, отданная в сборку документа ─────────────────
 *
 * Сборка документа спрашивает вырезку записи не один раз, а трижды: в блоке
 * самой записи, в счётчике «сколько записей с картинкой» и при сборе шрифтовых
 * правил. Пока за вопросом стояло чтение из буфера, это были три обращения
 * к памяти. Со съёмкой на месте каждая запись клонировалась бы и обходилась
 * `getComputedStyle` трижды, у замечаний ещё и по расширенному кадру, — всё
 * синхронно, на главном такте чужой страницы и прямо перед открытием диалога
 * печати. Виджет — гость, и подтормаживать носителя он не имеет права.
 * Вдобавок три съёмки дали бы три разных момента съёмки у одной картинки.
 *
 * Ни текстов правок, ни адреса сайта, ни разметки вырезки в журнал не уходит —
 * только количества и признаки.
 */
export function collectCutouts(
  entries: readonly Entry[],
  doc: Document,
): ReadonlyMap<string, Cutout> {
  const shots = new Map<string, Cutout>()
  let fromBuffer = 0

  for (const entry of entries) {
    const buffered = cutoutBuffer.has(entry.id)
    const cutout = cutoutFor(entry, doc)
    if (cutout === null) continue

    shots.set(entry.id, cutout)
    if (buffered) fromBuffer += 1
  }

  log.info('картинки мест собраны', {
    записей: entries.length,
    изБуфера: fromBuffer,
    снятоНаМесте: shots.size - fromBuffer,
    безКартинки: entries.length - shots.size,
  })

  return shots
}
