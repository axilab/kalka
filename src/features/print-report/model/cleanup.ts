import { cutoutBuffer } from 'entities/cutout'
import { entryStore } from 'entities/entry'
import { createLogger } from 'shared/lib/log'

const log = createLogger('report:cleanup')

/*
 * Срок жизни чернового буфера вырезок.
 *
 * ── Почему очистка НЕ в момент постановки печати ────────────────────────────
 *
 * «Стираются сразу после печати» — так это звучит на словах, и буквальная
 * реализация ставит ловушку. Печать средствами браузера о своём исходе
 * не сообщает вовсе: успехом пришлось бы считать открытие диалога. А человек,
 * отменивший диалог, чтобы что-нибудь проверить, при повторной печати получил
 * бы отчёт уже без картинок — и не понял бы, почему.
 *
 * Поэтому буфер очищается при ПЕРВОМ ИЗМЕНЕНИИ набора правок после печати.
 * Отчёт можно перепечатать сколько угодно раз, пока рецензент не вернулся
 * к правке; смысл «после формирования отчёта вырезки не нужны» при этом
 * сохраняется полностью. Замер снял срочность очистки: разбор весит порядка
 * 12 КБ, а не мегабайты, и лишний круг хранения ничему не мешает.
 *
 * ── Почему сбор сирот отдельно от очистки ───────────────────────────────────
 *
 * Съёмка идёт в точке создания ЧЕРНОВИКА, а черновик записью становится
 * не всегда: инструмент «Текст» захватывает элемент на каждый клик, правка,
 * сведённая к оригиналу, записи не создаёт, а замечание не сохраняется,
 * пока не введён комментарий. Значит в буфере копятся вырезки под
 * идентификаторами, которых в наборе нет.
 *
 * Собирать их на КАЖДОЕ изменение набора нельзя — и это не осторожность,
 * а прямой запрет: вырезка замечания пишется отложенно, а сама запись
 * появляется в хранилище только после ввода комментария. Проход «оставить
 * только то, что в наборе» между этими двумя моментами снял бы вырезку
 * живой правки. Поэтому сбор идёт в момент ПЕЧАТИ, когда набор уже устоялся.
 *
 * ── Почему эти две функции живут здесь ──────────────────────────────────────
 *
 * Им нужны сразу `entities/entry` и `entities/cutout` — соседние слайсы одного
 * слоя, друг друга они не видят. Общая точка сборки лежит слоем выше, и это
 * тот же приём, которым `features/edit-text` собирает якорь и контекст.
 */

/** Снятая подписка ожидания правки после печати. `null` — не взведено. */
let disarm: (() => void) | null = null

/**
 * Идентификаторы вырезок, снятых К МОМЕНТУ ПЕЧАТИ.
 *
 * Именно они и устарели после печати — только они. Список запоминается при
 * взведении, а не пересчитывается при срабатывании: разбор причины в шапке
 * `armCutoutCleanupAfterPrint`.
 */
let printed: string[] = []

/**
 * Снимает вырезки, которым не соответствует ни одна запись. Возвращает число
 * снятых.
 *
 * Зовётся ПЕРЕД сборкой отчёта: буфер к этому моменту может нести мусор
 * от разведочных кликов, а вытеснение по потолку выбрасывало бы ради него
 * настоящие картинки.
 */
export function sweepOrphanCutouts(): number {
  const alive = entryStore.list().map((entry) => entry.id)
  const dropped = cutoutBuffer.keep(alive)

  if (dropped > 0) log.debug('сняты вырезки без записей', { снято: dropped, записей: alive.length })
  return dropped
}

/**
 * Взводит очистку буфера: она сработает при первом изменении набора правок.
 *
 * ── Почему снимаются НАЗВАННЫЕ вырезки, а не весь буфер ─────────────────────
 *
 * Очистка срабатывает на первом изменении набора, а первое изменение — это,
 * как правило, СОХРАНЕНИЕ СЛЕДУЮЩЕЙ ПРАВКИ. К этому моменту вырезка для неё
 * уже снята и лежит в буфере (съёмка идёт при создании черновика, отложенно
 * на десятки миллисекунд). Позови здесь `clear()` — и он снёс бы вместе
 * с устаревшими вырезку той самой правки, которая его и разбудила.
 *
 * Ошибка была бы тихой и повторялась бы на каждом круге: после любой печати
 * следующая правка выходила бы в отчёт без картинки, показанная текстом
 * с пометкой «показать это место картинкой не удалось». Отчёт выглядел бы
 * недоделанным ровно там, где всё исправно.
 *
 * Поэтому список снимаемого фиксируется В МОМЕНТ ВЗВЕДЕНИЯ: устарели ровно те
 * вырезки, которые попали в напечатанный документ, и никакие другие.
 * Найдено ручным прогоном на стенде 2026-09-06.
 *
 * Повторный вызов ничего не ломает и второй подписки не заводит: печатать
 * отчёт можно сколько угодно раз подряд. Список при этом обновляется — печатали
 * ведь заново, и устарело то, что ушло в последний документ.
 *
 * Возвращает снятие — на случай размонтирования виджета до того, как рецензент
 * вернулся к правке.
 */
export function armCutoutCleanupAfterPrint(): () => void {
  // Список обновляется и при повторной печати: во второй документ могли уйти
  // вырезки, которых в первом не было.
  printed = entryStore
    .list()
    .map((entry) => entry.id)
    .filter((id) => cutoutBuffer.has(id))

  if (disarm !== null) {
    log.debug('очистка буфера уже взведена, обновлён только список', { вырезок: printed.length })
    return disarm
  }

  const stop = entryStore.subscribe(() => {
    // Снимаем подписку ДО очистки: буфер пишет в своё хранилище, а не в набор
    // правок, но порядок «сперва разоружиться» избавляет от вопроса, может ли
    // очистка позвать этот же обработчик повторно.
    stop()
    disarm = null

    for (const id of printed) cutoutBuffer.drop(id)
    log.info('сняты вырезки напечатанного отчёта: набор правок изменился', {
      снято: printed.length,
    })
    printed = []
  })

  disarm = (): void => {
    stop()
    disarm = null
    printed = []
  }

  log.debug('очистка буфера взведена до первой правки', { вырезок: printed.length })
  return disarm
}
