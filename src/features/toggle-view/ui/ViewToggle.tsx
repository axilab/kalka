import type { JSX } from 'preact'
import { useEffect, useState } from 'preact/hooks'
import { entryStore } from 'entities/entry'
import { createLogger } from 'shared/lib/log'
import { Button } from 'shared/ui/Button'
import { IconEdited, IconOriginal } from 'shared/ui/icons'

const log = createLogger('toggle-view')

/**
 * Вид страницы: два состояния одной кнопки (FR-21, FR-22).
 *
 * ── Два состояния, и это решение ────────────────────────────────────────────
 *
 * «С правками» — текст правок и ВСЕ метки; «оригинал» — текст носителя и ни
 * одной метки. Третьего состояния, «с правками, но без пометок», нет намеренно:
 * оно оправдывало себя только у правок текста, а у области и указателя было
 * неотличимо от соседнего — кнопка меняла подпись, экран не менялся. Полный
 * разбор с отвергнутыми альтернативами — в `docs/adr/0001`.
 *
 * ── Один флаг хранилища ─────────────────────────────────────────────────────
 *
 * Прежде за кнопкой стояли два независимых флага, дававшие четыре комбинации
 * при трёх осмысленных. Остался ОДИН — `showOriginal`, и он же единственный
 * описатель вида. Отсюда и один сеттер на нажатие: прежняя проверка «пишем
 * только то, что меняется» берегла от двух проходов движка наложения подряд,
 * а у одного флага беречь не от чего.
 *
 * Цикл замкнут двумя нажатиями: любое состояние достижимо из любого.
 *
 * ── Почему подпись называет ТЕКУЩЕЕ состояние, а не действие ────────────────
 *
 * Подпись «Показать оригинал» называет действие и молчит о том, что на экране
 * сейчас, — а вид взводит не только эта кнопка (см. ниже), и рецензент может
 * прийти к ней уже в «оригинале». Поэтому и подпись, и рисунок говорят, что
 * показано СЕЙЧАС, а другое состояние открывается нажатием.
 *
 * ── Почему кнопка гаснет в режиме проверки ──────────────────────────────────
 *
 * У флага `showOriginal` ДВА писателя: эта кнопка и вход в режим проверки
 * после передеплоя, который держит вид сам. Оставь кнопку доступной — и в
 * проверке человек получил бы исправленный текст рядом со строкой «не доехало»,
 * то есть ровно то сочетание, ради различения которого режим и заведён.
 * Признак недоступности приходит пропом сверху (`app/ui/Root`), а не читается
 * здесь: решение о том, когда правка и смена вида запрещены, принимается
 * в одном месте.
 *
 * ── Переприменение ──────────────────────────────────────────────────────────
 *
 * Отсюда не вызывается и вызвано быть не может: движок наложения живёт в `app`,
 * слой выше `features`. Он подписан на то же хранилище и переприменит слой
 * сам — это и есть общение слайсов через хранилище (ARCHITECTURE.md).
 */

/** Что показано на странице. Производная от единственного флага хранилища. */
type View = 'edited' | 'original'

const NEXT: Readonly<Record<View, View>> = {
  edited: 'original',
  original: 'edited',
}

/**
 * Подписи и рисунки по состояниям.
 *
 * Текст по-русски и без технических терминов (FR-36): рецензент читает про
 * страницу и правки, а не про слой, наложение и подсветку атрибутов.
 */
const VIEWS: Readonly<Record<View, { label: string; icon: JSX.Element }>> = {
  edited: { label: 'Вид: с правками', icon: <IconEdited /> },
  original: { label: 'Вид: оригинал', icon: <IconOriginal /> },
}

function currentView(): View {
  return entryStore.showOriginal() ? 'original' : 'edited'
}

export interface ViewToggleProps {
  /**
   * Компактный вид для рейки: одна иконка вместо фразы.
   *
   * Фраза при этом никуда не девается — она остаётся доступным именем кнопки
   * и всплывающей подписью. Убрать видимый текст с рейки в 48px можно,
   * отобрать имя у программы чтения с экрана — нет.
   */
  compact?: boolean

  /**
   * Смена вида сейчас недоступна — идёт режим проверки после передеплоя.
   *
   * Признак приходит СВЕРХУ, а не читается из хранилища здесь: разбор — в шапке
   * компонента. Кнопка при этом остаётся на рейке и гаснет, а не исчезает.
   */
  disabled?: boolean
}

export function ViewToggle({ compact, disabled }: ViewToggleProps): JSX.Element {
  const [view, setView] = useState<View>(currentView)

  useEffect(() => {
    // Снимок берётся и при подписке: между первым рендером и эффектом флаг
    // мог измениться, и компонент остался бы с устаревшим значением. Путь
    // не теоретический — вид взводит ещё и вход в режим проверки.
    setView(currentView())
    return entryStore.subscribe(() => setView(currentView()))
  }, [])

  function step(): void {
    const next = NEXT[view]
    // `источник` отличает нажатие кнопки от входа в режим проверки, который
    // ставит тот же флаг мимо неё.
    log.debug('смена вида страницы', { было: view, стало: next, источник: 'кнопка' })
    entryStore.setShowOriginal(next === 'original')
  }

  const { label, icon } = VIEWS[view]

  /*
   * Состояние несут ИМЯ и РИСУНОК, а не `aria-pressed`: имя уже меняется
   * вместе с состоянием, а нажатость сказала бы неправду — «вид: оригинал»
   * не «нажатое с правками». Разбор — в шапке `shared/ui/Button`.
   */
  if (compact) {
    return <Button onClick={step} icon={icon} label={label} tip={label} disabled={disabled} />
  }

  return (
    <Button onClick={step} disabled={disabled}>
      {label}
    </Button>
  )
}
