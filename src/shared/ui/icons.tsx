/*
 * ── Пара состояний у переключателей вида ────────────────────────────────────
 *
 * У «оригинала» и «подсветки изменений» ДВЕ иконки на переключатель, а не одна
 * с `pressed`. Причина не в оформлении: подпись обеих кнопок называет то, что
 * произойдёт по нажатию («Показать оригинал» → «Показать с правками»),
 * то есть доступное имя УЖЕ меняется вместе с состоянием. Добавить к меняющемуся
 * имени ещё и `aria-pressed` значило бы сказать состояние дважды и в разных
 * направлениях: программа чтения с экрана прочла бы «Показать с правками,
 * нажато» — фразу, из которой не следует ничего.
 *
 * Поэтому состояние здесь несут имя и рисунок, а `pressed` остаётся кнопкам
 * с постоянной подписью — инструментам и форматированию.
 */

