import type { JSX } from 'preact'

/*
 * Иконный набор интерфейса.
 *
 * ── Почему инлайновый SVG, а не шрифт и не спрайт ───────────────────────────
 *
 * Внешних адресов у виджета нет вовсе (NFR-03): ни шрифта с иконками, ни файла
 * спрайта загрузить неоткуда. Спрайт внутри теневого корня тоже не годится —
 * `<use href="#id">` ищет цель в том же дереве, а слой меток живёт отдельным
 * поддеревом. Остаётся разметка на месте.
 *
 * ── Без атрибута xmlns ──────────────────────────────────────────────────────
 *
 * Пространство имён Preact ставит сам, а лишний атрибут повторяется на каждой
 * иконке и расходует бюджет в 100 КБ gzip (NFR-01). То же требование записано
 * в шапке `shared/ui/Button`.
 *
 * ── Цена набора ─────────────────────────────────────────────────────────────
 *
 * Четырнадцать иконок стоят 0,7 КБ gzip: 29,2 → 29,9 КБ из 100. Замерено
 * сборкой с принудительным импортом всего набора и без него. Цифра названа
 * здесь, а не оставлена на догадку: всё, что растит бандл, обязано себя
 * называть.
 *
 * ── Штрих, а не заливка, и currentColor ─────────────────────────────────────
 *
 * Иконка не имеет собственного цвета: она берёт `currentColor` кнопки. Тогда
 * состояние («выбран», «главная кнопка») красит и подпись, и иконку одним
 * правилом, и второго набора правил под иконки не появляется вовсе.
 *
 * Ширина штриха 1.6 при поле 16 — тот же вес, что у подписи хрома (500):
 * иконка стоит в ряду с текстом и не имеет права выглядеть жирнее его.
 *
 * ── aria-hidden на каждой ───────────────────────────────────────────────────
 *
 * Доступное имя даёт кнопка (`label` у `Button` обязателен, когда текста нет).
 * Иконка, оставленная видимой для программы чтения с экрана, добавила бы
 * к этому имени пустой графический узел.
 */

