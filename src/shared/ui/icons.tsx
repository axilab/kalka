/*
 * ── Пара состояний у переключателя вида ─────────────────────────────────────
 *
 * Переключатель вида один, состояний у него два, и иконок поэтому тоже ДВЕ —
 * а не одна с `pressed`. Причина не в оформлении: подпись кнопки называет
 * текущее состояние («Вид: с правками» → «Вид: оригинал»), то есть доступное
 * имя УЖЕ меняется вместе с ним. Добавить к меняющемуся имени ещё
 * и `aria-pressed` значило бы сказать состояние дважды и в разных
 * направлениях: программа чтения с экрана прочла бы «Вид: оригинал, нажато» —
 * фразу, из которой не следует ничего.
 *
 * Поэтому состояние здесь несут имя и рисунок, а `pressed` остаётся кнопкам
 * с постоянной подписью — инструментам и форматированию.
 */

