import type { ComponentChildren, JSX } from 'preact'

/*
 * Кнопка интерфейса.
 *
 * Иконки лежат рядом, в `shared/ui/icons`, и пишутся инлайновым SVG БЕЗ
 * атрибута xmlns — Preact ставит пространство имён сам, а лишний атрибут
 * только расходует бюджет бандла (NFR-01).
 *
 * В проекте используется `class`, а не `className`: Preact принимает оба.
 */

interface ButtonCommonProps {
  onClick: () => void
  /** Главная кнопка на экране. Такая ровно одна: две главные — ни одной. */
  primary?: boolean
  /**
   * Действие уничтожает работу.
   *
   * Признак ЗРИТЕЛЬНЫЙ и работает только под курсором и под фокусом: в покое
   * такая кнопка ничем не отличается от соседей. Кричать в покое ей незачем —
   * она не главная и не опасна, пока на неё не нажали.
   *
   * Одного цвета для этого мало, и он тут не первый признак: что именно
   * произойдёт, называет подпись кнопки, а от промаха бережёт откат.
   */
  danger?: boolean
  /**
   * Выбранный инструмент палитры — ВИЗУАЛЬНЫЙ признак.
   *
   * Один он ничего не сообщает программе чтения с экрана, поэтому у иконных
   * кнопок идёт в паре с `pressed`, а не вместо него (см. ниже).
   */
  selected?: boolean
  /**
   * Состояние нажатия → `aria-pressed`.
   *
   * ── Почему `aria-pressed`, а не radiogroup ────────────────────────────────
   *
   * Инструменты выбираются взаимоисключающе, и напрашивается `role="radio"`.
   * Но переключатель радиокнопок нельзя выключить повторным нажатием, а
   * инструмент — можно, и подсказка палитры именно это и обещает («нажмите
   * ещё раз, чтобы выключить»). Кнопка-выключатель — это и есть `aria-pressed`;
   * радиогруппа сказала бы про поведение неправду и потребовала бы вдобавок
   * перемещения стрелками с одной точкой табуляции.
   *
   * Отсюда правило: постоянная подпись + меняющееся состояние → `pressed`;
   * меняющаяся подпись (переключатели вида) состояние несёт именем и рисунком,
   * и `pressed` там не ставится — иначе состояние сказано дважды.
   */
  pressed?: boolean
  /**
   * Нажать нельзя. Кнопка при этом остаётся на экране: «Экспорт» при пустом
   * наборе исчезающая означала бы, что такой возможности вовсе нет, тогда как
   * она есть — просто выгружать пока нечего.
   */
  disabled?: boolean
  /**
   * Счётчик поверх кнопки: сколько правок сделано ЭТИМ инструментом.
   *
   * Ноль и `undefined` не рисуют ничего: пустой значок сообщает не «нисколько»,
   * а «здесь что-то есть», и на рейке из трёх инструментов это был бы шум
   * в состоянии, с которого начинает каждый.
   *
   * ⚠ В доступное имя число НЕ попадает само: `aria-label` заменяет содержимое
   * кнопки целиком, и значок внутри неё программа чтения с экрана не прочтёт.
   * Вписывать число в `label` обязан вызывающий — иначе счётчик существует
   * только для зрячих.
   */
  badge?: number
  /**
   * Видимая расшифровка иконки: короткая подпись, всплывающая рядом с кнопкой
   * по наведению и по `focus-visible`.
   *
   * Доступного имени для этого мало. Имя слышит тот, кто пользуется программой
   * чтения с экрана; человеку, который просто смотрит на рейку в первый раз,
   * три незнакомых значка не говорят ничего, а узнать их он может только
   * нажав — то есть перехватив клики на чужой странице наугад. Подпись
   * появляется ДО выбора и снимает это.
   *
   * Разметкой, а не `content: attr(aria-label)`: сгенерированный текст часть
   * браузеров кладёт в дерево доступности, и имя кнопки прочиталось бы дважды.
   * Здесь подпись помечена `aria-hidden` и остаётся чисто зрительной.
   */
  tip?: string
  /**
   * Кнопка раскрывает или прячет блок → `aria-expanded` и `aria-controls`.
   *
   * Это НЕ то же, что `pressed`, и путать их нельзя. `aria-pressed` говорит
   * «выключатель включён», `aria-expanded` — «то, чем управляет эта кнопка,
   * сейчас раскрыто». У входа в разбор верно второе: кнопка не включает
   * режим, а открывает ящик, и человеку с программой чтения с экрана нужно
   * знать, куда именно он попадёт. Объявлять оба — сказать одно состояние
   * двумя разными словами.
   */
  expanded?: boolean
  /** Идентификатор раскрываемого блока. Имеет смысл только вместе с `expanded`. */
  controls?: string
}

/**
 * Кнопка с текстом. Иконка при нём необязательна, доступное имя — тоже:
 * его даёт сам текст.
 */
interface ButtonWithTextProps extends ButtonCommonProps {
  children: ComponentChildren
  icon?: JSX.Element
  /** Подпись для программ чтения с экрана, если текста кнопки мало. */
  label?: string
}

/**
 * Кнопка из одной иконки.
 *
 * `label` здесь ОБЯЗАТЕЛЕН, и это не строгость ради строгости: иконка без
 * доступного имени не читается программой чтения с экрана вовсе — такой кнопки
 * для человека, который её не видит, просто не существует. Рейка шириной 48px
 * подписей не вмещает, значит имя остаётся единственным, чем кнопка себя
 * называет, и терять его нельзя ни на одной.
 *
 * Тип разводит эти два случая, чтобы забыть `label` было невозможно, а не
 * стыдно.
 */
interface ButtonIconOnlyProps extends ButtonCommonProps {
  children?: never
  icon: JSX.Element
  label: string
}

export type ButtonProps = ButtonWithTextProps | ButtonIconOnlyProps

export function Button(props: ButtonProps): JSX.Element {
  const {
    onClick,
    primary,
    danger,
    badge,
    selected,
    pressed,
    disabled,
    icon,
    label,
    tip,
    expanded,
    controls,
  } = props
  const children = 'children' in props ? props.children : undefined

  const className = [
    'kalka-button',
    primary ? 'kalka-button--primary' : '',
    danger ? 'kalka-button--danger' : '',
    selected ? 'kalka-button--selected' : '',
    // Квадратные поля вместо вытянутых: под несуществующий текст кнопке
    // растягиваться не за чем.
    children === undefined ? 'kalka-button--icon' : '',
  ]
    .filter(Boolean)
    .join(' ')

  const button = (
    <button
      type="button"
      class={className}
      aria-label={label}
      aria-pressed={pressed}
      aria-expanded={expanded}
      aria-controls={controls}
      disabled={disabled}
      onClick={onClick}
    >
      {icon}
      {children}
      {/* `aria-hidden`: число уже сказано в `aria-label` вызывающим, и второй
          раз произносить его незачем. */}
      {badge !== undefined && badge > 0 && (
        <span class="kalka-button__badge" aria-hidden="true">
          {badge}
        </span>
      )}
    </button>
  )

  if (tip === undefined) return button

  // Обёртка появляется ТОЛЬКО вместе с подписью: без неё кнопка остаётся
  // кнопкой и ничего вокруг себя не заводит. Подпись — соседний элемент,
  // а не потомок: показывает её правило `.kalka-button:hover + .kalka-tip`,
  // которому не нужен ни :has(), ни второй класс на самой кнопке.
  return (
    <span class="kalka-tipped">
      {button}
      <span class="kalka-tip" aria-hidden="true">
        {tip}
      </span>
    </span>
  )
}
