/*
 * Понятия слоя правок, существующие только в рантайме виджета.
 *
 * В файл обмена они не попадают: статус пересчитывается на каждой странице
 * заново, а найденный `Element` вообще не сериализуем.
 *
 * Почему отдельный файл в `shared`, а не внутри `entities/anchor`: `EntryStatus`
 * нужен и `entities/anchor` (он его вычисляет), и `entities/entry` (оно его
 * хранит), а соседние слайсы одного слоя импортировать друг друга не могут
 * (ARCHITECTURE.md). Общий словарь обязан лежать слоем ниже.
 */

import type { Entry } from 'shared/model/format'

/** Уровень, которым найден элемент. Порядок фиксирован и совпадает с откатом. */
export type AnchorMethod = 'selector' | 'xpath' | 'snippet'

/** Успешная находка. */
export interface Resolution {
  element: Element
  method: AnchorMethod
  /**
   * `false` для находки по фрагменту текста: она не сверялась с `was`
   * и считается догадкой, а не подтверждённым попаданием.
   */
  exact: boolean
}

/** Результат трёхуровневого поиска: либо находка, либо честное «не найдено». */
export type ResolveResult = Resolution | { status: 'lost' }

/**
 * Три исхода наложения, а не два (FR-20, цель Ц4).
 *
 * `drifted` — «вероятно, вот это место, проверьте глазами».
 * `lost` — «ищите руками, вот исходный текст». Разработчику это разные задачи.
 */
export type EntryStatus = 'applied' | 'drifted' | 'lost'

/**
 * Запись вместе с результатом наложения на текущую страницу.
 *
 * Найденный `Element` публикуется теперь не только здесь, но и в состоянии
 * записи внутри хранилища (`EntryState.element` в `entities/entry/model/store.ts`):
 * список разбора прокручивает страницу к месту правки по тому элементу, который
 * УЖЕ нашёл движок наложения. Искать элемент заново на каждый клик значило бы
 * завести третий проход поиска рядом с двумя существующими — и получить разные
 * ответы у списка и у слоя на одной и той же странице.
 */
export interface AppliedEntry {
  entry: Entry
  status: EntryStatus
  /** Отсутствует при `lost`. */
  element?: Element
  /** Отсутствует при `lost`. */
  method?: AnchorMethod
}

/**
 * Три исхода проверки после передеплоя (FR-35).
 *
 * Читаются из статуса наложения, а НЕ из повторного сравнения страницы с файлом:
 * на странице с уже наложенным слоем `was` не находится никогда (мы сами его
 * заменили), а `now` находится всегда (мы сами его написали). Полная таблица
 * и её обоснование — в шапке `entities/entry/model/verify.ts`; здесь только
 * словарь:
 *
 * | Статус наложения | Текст `now` на странице | Исход        |
 * |------------------|-------------------------|--------------|
 * | `applied`        | не спрашиваем           | `not-arrived`|
 * | `lost`           | найден                  | `arrived`    |
 * | `lost`           | не найден               | `unclear`    |
 * | `drifted`        | не спрашиваем           | `unclear`    |
 *
 * Исхода ТРИ, а не два, и свести `unclear` с `not-arrived` нельзя: «правка
 * не доехала» — это задача агенту доделать работу, а «непонятно» — задача
 * человеку посмотреть глазами. Склеенные в один красный цвет, они заставили бы
 * человека перепроверять руками всё подряд, то есть отменили бы смысл FR-35.
 */
export type VerifyStatus = 'arrived' | 'not-arrived' | 'unclear'

/**
 * Происхождение импортированной записи: из чьего файла она пришла и когда.
 *
 * Записи, созданные локально, `EntryOrigin` НЕ ИМЕЮТ ВОВСЕ — отсутствие записи
 * о происхождении и означает «своя». Отдельного флага `isLocal` нет: два
 * источника правды об одном и том же обязаны разойтись.
 *
 * Почему автор — не поле `Entry` (решение 5 плана вехи). В `ExchangeFile` поле
 * `author` уже есть, и второй экземпляр того же значения внутри каждой записи
 * дал бы два источника правды, которые разъедутся при первом же реэкспорте
 * объединённого набора. Кроме того, `Entry` — это контракт `format: 1`, и
 * раздувать его полями, которые нужны только виджету, значит нарушать
 * разделение «двух потребителей формата» (ARCHITECTURE.md). Происхождение —
 * понятие СЛОЯ, а не файла, поэтому оно живёт здесь, рядом с `EntryStatus`
 * и `AppliedEntry`, и по той же причине.
 *
 * Пара (`author`, `sourceId`) — ключ дедупликации при накопительном импорте
 * (решение 4). Голый `id` ключом быть не может: восемь шестнадцатеричных
 * символов (`shared/lib/id.ts`) уникальны лишь ВНУТРИ одного файла, и два
 * рецензента, правившие каждый у себя, могут прислать записи с одинаковым `id`.
 * Дедупликация по голому `id` молча потеряла бы правку второго. При пустом
 * имени автора пара вырождается в `id` — это честный предел формата: двух
 * анонимных рецензентов с одинаковым `id` он различить не может.
 */
export interface EntryOrigin {
  /** Имя рецензента из шапки файла обмена. Пустая строка — имя не вводили. */
  author: string
  /**
   * `id`, с которым запись пришла В ФАЙЛЕ.
   *
   * Может отличаться от `id` записи в хранилище (решение 7): если входящий `id`
   * уже занят записью другого происхождения, импорт выдаёт записи новый
   * локальный `id` через `createId()`, а исходный сохраняется здесь и служит
   * ключом дедупликации. Иначе ключом хранилища пришлось бы сделать пару, а её
   * не понимают ни движок наложения, ни метка `data-kalka-applied` в чужом DOM.
   */
  sourceId: string
  /** Момент загрузки файла, ISO 8601. */
  importedAt: string
}

/**
 * Положение элемента-якоря ВНУТРИ кадра вырезки, в пикселях кадра.
 *
 * Не доли: доли уже есть в `RectAnchor`/`PointAnchor` формата обмена, и они
 * отсчитываются от bounding box ЯКОРЯ. Здесь величина другого рода — где сам
 * якорь стоит в кадре, — и смешивать их в одном типе значило бы однажды
 * подставить одно вместо другого молча.
 */
export interface AnchorBox {
  x: number
  y: number
  w: number
  h: number
}

/**
 * Видимая полоса кадра: что из него показывает отчёт.
 *
 * Только по вертикали. По горизонтали кадр показывается целиком — он и берётся
 * во всю ширину страницы ради того, чтобы читатель узнал место.
 */
export interface Band {
  /** Отступ от верха кадра до верха полосы, px кадра. Не меньше нуля. */
  y: number
  /** Высота полосы, px кадра. Не больше остатка кадра ниже `y`. */
  h: number
}

/**
 * Снимок места правки: клон элемента с вкомпилированными стилями, вклеенный
 * в отчёт как вёрстка, а не как растр.
 *
 * ── Почему это понятие СЛОЯ, а не формата обмена ────────────────────────────
 *
 * Вырезка не поле записи и в файл обмена не попадает никогда: агент читает
 * описание изменений контента, а картинка ему не нужна и мешала бы (FR-46).
 * Поэтому тип лежит здесь, рядом с `EntryStatus` и `EntryOrigin`, а не
 * в `shared/model/format.ts`. Транспорт для картинок — сам напечатанный
 * документ, а не файл.
 *
 * ── Почему `anchorBox` отдельным полем ──────────────────────────────────────
 *
 * `captureRect`/`capturePoint` (`shared/lib/geometry.ts`) хранят доли от
 * bounding box ЭЛЕМЕНТА-ЯКОРЯ, а кадр записи `comment` — широкий, с окрестностью:
 * без окрестности «это убрать» не значит ничего. То есть кадр снят с большего
 * элемента, чем якорь, и подставить доли прямо в `width`/`height` значит
 * промахнуться меткой ровно у того типа записи, весь смысл которого «вот это
 * здесь». Совпадение кадра с якорем — частный случай (у узких кадров правок
 * текста `anchorBox` равен всему кадру), а не правило.
 */
export interface Cutout {
  /** Разметка клона со вкомпилированными вычисленными стилями. */
  html: string
  /** Ширина кадра в px на момент съёмки. */
  width: number
  /** Высота кадра в px на момент съёмки. */
  height: number
  /**
   * Видимая ПОЛОСА внутри кадра: отступ от верха кадра и высота, в px кадра.
   *
   * Кадр берётся во всю ширину страницы, чтобы читатель узнал место, — а такой
   * кадр почти всегда высокий: это секция целиком. Показывать её целиком незачем
   * и вредно, поэтому отчёт показывает полосу вокруг якоря с небольшим запасом
   * сверху и снизу, а остальное обрезает.
   *
   * Полоса хранится ОТДЕЛЬНО от `width`/`height`, а не подменяет их: разметка
   * клона раскладывается по полной высоте кадра, и подмени мы высоту — вёрстка
   * внутри поехала бы. Обрезка это дело отчёта, а не съёмки.
   */
  band: Band
  /** Где стоит элемент-якорь внутри кадра. */
  anchorBox: AnchorBox
  /**
   * Правила `@font-face` носителя.
   *
   * Без них объявленное семейство молча подменяется системным: в изолированном
   * документе `document.fonts` пуст, метрики расходятся, и перенос строки
   * уезжает. Для отчёта, где «было/стало» должно выглядеть как на сайте,
   * подмена шрифта недопустима.
   */
  fontFaces: string[]
  /** Момент съёмки, ISO 8601. */
  at: string
}
