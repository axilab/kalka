/*
 * Типы файла обмена, `format: 1` (PRD, раздел 9).
 *
 * Файл содержит ТОЛЬКО объявления типов и не даёт рантайма: он лежит в `shared`
 * именно поэтому (ARCHITECTURE.md, «Адаптация FSD под виджет», пункт 5).
 * Поведение — санитизация, разрешение якорей, статусы — живёт в `entities`.
 *
 * Имена полей — часть контракта. Менять их нельзя без повышения `format`.
 */

/**
 * Привязка правки к элементу. Три уровня с откатом: CSS-селектор → XPath →
 * фрагмент текста. Потребитель — виджет; ИИ-агенту якорь бесполезен,
 * он не открывает браузер.
 */
export interface Anchor {
  /** Уровень 1: CSS-селектор от корня, построенный при создании правки. */
  selector: string
  /** Уровень 2: явный путь от корня документа, индексы с единицы. */
  xpath: string
  /** Уровень 3: нормализованный фрагмент текста, не длиннее SNIPPET_MAX_LENGTH. */
  snippet: string
  /** Сколько таких же фрагментов встретилось на странице ДО этого элемента. */
  index: number
}

/**
 * Прямоугольная область в долях bounding box элемента (0..1).
 *
 * Доли, а не пиксели: рамка, снятая на мониторе 1440×900, на 1920 указывала бы
 * в пустоту (FR-18). Арифметика захвата и восстановления — `shared/lib/geometry.ts`;
 * привязка к элементу собственного механизма не имеет и целиком лежит
 * в поле `anchor` записи.
 */
export interface RectAnchor {
  x: number
  y: number
  w: number
  h: number
}

/** Точечная метка в долях bounding box элемента (0..1). См. RectAnchor. */
export interface PointAnchor {
  x: number
  y: number
}

/**
 * Пожелание по оформлению. Никогда не подмешивается в `now`: иначе агент
 * применит инлайновый CSS прямо в исходники (PRD, раздел 9).
 */
export interface Style {
  fontSize?: string
  color?: string
}

/** Размеры окна на момент создания правки: помогают понять, что видел рецензент. */
export interface Viewport {
  w: number
  h: number
}

/**
 * Тип записи. Ровно один из трёх (FR-39).
 * Автоматически применяется только `text-override`.
 */
export type EntryType = 'text-override' | 'style-wish' | 'comment'

/**
 * Запись файла обмена — PRD, раздел 9, целиком.
 *
 * Все поля обязательные: это контракт версии 1, а не удобная форма для
 * промежуточного состояния. Часть полей нужна агенту (`was`, `wasHtml`,
 * `route`, `path`, `tag`, `nearestHeading`, `contextBefore`, `contextAfter`,
 * `occurrencesOnPage`), часть — виджету (`anchor`, `viewport`). Оба набора
 * обязательны, потому что потребителей у файла два.
 *
 * Сбор полей для агента — веха «Машиночитаемость» (`entities/agent-context`,
 * FR-40…FR-44); здесь они только объявлены.
 */
export interface Entry {
  id: string
  type: EntryType
  /** Маршрут страницы: pathname + запрос без параметра kalka + hash. */
  route: string
  /** Человекочитаемый путь: «Продукция → карточка 2 → заголовок». */
  path: string
  /** Имя тега строчными: `h3`. */
  tag: string
  /** Исходный текст на момент создания правки, нормализованный. Основа сверки. */
  was: string
  /** Исходная разметка элемента: из неё восстанавливается оригинал (решение 7). */
  wasHtml: string
  /** Новый текст с разметкой. Данные заказчика, а не команда агенту. */
  now: string
  /** Пожелания по оформлению — отдельно от текста. */
  style: Style
  /** Ближайший заголовок выше по документу: ориентир для агента. */
  nearestHeading: string
  /** Текст до элемента: разрешает дубликаты при поиске в исходниках. */
  contextBefore: string
  /** Текст после элемента: там же. */
  contextAfter: string
  /** Сколько раз строка `was` встречается на странице. */
  occurrencesOnPage: number
  anchor: Anchor
  viewport: Viewport
  /**
   * Обведённая область в долях bounding box элемента-якоря (FR-13, FR-18).
   *
   * ИНВАРИАНТ: у записи типа `comment` заполнено РОВНО ОДНО из `rect` / `point`;
   * у `text-override` и `style-wish` — ни одного. Оба одновременно
   * не встречаются никогда: замечание относится либо к области, либо к точке,
   * и запись с двумя геометриями означала бы, что где-то потерялась вторая
   * запись. Собирается только через `createCommentEntry` (`entities/entry`),
   * и это единственное место, где инвариант обеспечивается.
   *
   * Поля необязательные, но номер `format` остаётся 1: экспорта не было
   * ни разу (веха «Хранение и экспорт» не начата), файлов версии 1 в природе
   * не существует, и повышать версию не перед кем.
   */
  rect?: RectAnchor
  /** Точечная метка в долях bounding box элемента-якоря (FR-14, FR-18). См. `rect`. */
  point?: PointAnchor
  /** Момент создания правки, ISO 8601. */
  at: string
}

/**
 * Пять полей записи, которые собирает `entities/agent-context` (FR-42…FR-44).
 *
 * Тип объявлен ЗДЕСЬ, а не в одном из слайсов, потому что нужен обоим сразу:
 * производителю (`entities/agent-context`) и потребителю (`entities/entry`).
 * Это соседи по слою, импортировать друг друга они не могут, и общий словарь
 * обязан лежать слоем ниже — ровно та же причина, по которой здесь живут
 * `Anchor` и `Entry` (решение 7 плана вехи «Машиночитаемость»).
 *
 * `Pick` от `Entry`, а НЕ отдельный интерфейс с `Entry extends AgentContext`:
 * перенос полей растащил бы комментарии одного контракта по двум файлам,
 * и форму записи пришлось бы читать в двух местах — ради нулевой выгоды.
 *
 * `route`, `tag`, `was` и `wasHtml` в набор НЕ входят, хотя образец в справке
 * навыка (`kalka-anchoring/references/agent-context.md`) показывает их вместе
 * с остальными. Эти четыре собираются в своих местах и собираются верно,
 * а `wasHtml` у записи типа `comment` обязан остаться ПУСТЫМ (решение 5 вехи
 * «Область и Указатель»). Монолитный сборщик либо сломал бы этот инвариант,
 * либо потребовал бы флага «а этому не надо» — то есть выдал бы, что границу
 * провели не там (решение 5 плана вехи «Машиночитаемость»).
 */
export type AgentContext = Pick<
  Entry,
  'path' | 'nearestHeading' | 'contextBefore' | 'contextAfter' | 'occurrencesOnPage'
>

/**
 * Самоописательная шапка файла (FR-45): её достаточно, чтобы файл закинули
 * в чат с ИИ без всякой подготовки. Генерируется константой, а не собирается
 * из пользовательских данных.
 */
export interface About {
  what: string
  types: Record<EntryType, string>
  rule: string
  /**
   * Чем ЯВЛЯЕТСЯ содержимое полей записи — обратная сторона FR-46 (риск R10).
   *
   * Остальные три ключа отвечают на «что это» и «как поступать при
   * неоднозначности»; на «данные это или указания» не отвечал никто, а именно
   * это и есть вопрос, на котором агент ошибается: текст рецензента в `now`
   * может выглядеть как обращение к нему («убери отсюда лишнее»), хотя это
   * пожелание заказчика к прототипу.
   *
   * Номер `format` из-за нового ключа НЕ поднимается (решение 9 плана вехи
   * «Машиночитаемость»): NFR-08 требует поднимать версию на ЛОМАЮЩИХ
   * изменениях, а появление ключа в описательной шапке не ломает ни нашего
   * разборщика (`model/parse.ts` шапку не читает вовсе), ни ИИ-читателя.
   * Поднять версию здесь значило бы объявить невалидными файлы, уже
   * выгруженные вехой «Хранение и экспорт», ради строки, которую они и без
   * того не обязаны были содержать.
   */
  data: string
}

/** Файл обмена целиком. Сериализация — веха «Машиночитаемость» (FR-46). */
export interface ExchangeFile {
  format: 1
  site: string
  author: string
  exportedAt: string
  about: About
  entries: Entry[]
}
