/**
 * Состояние виджета.
 *
 * Значений по-прежнему три, но означают они не три взаимоисключающие панели,
 * а три положения одной раскладки «рейка + ящик». Рейка видна во всех трёх:
 * инструменты, счётчик и тумблеры вида доступны всегда (FR-21, FR-25).
 *
 * У каждого значения ровно один проверяемый инвариант:
 * - `view` — ящик закрыт, инструмент не выбран;
 * - `edit` — ящик закрыт, инструмент выбран;
 * - `review` — ящик открыт; выбранный инструмент сохраняется и продолжает
 *   работать на странице.
 *
 * Переходы:
 * - выбор инструмента вне разбора → `edit`; снятие последнего → `view`;
 * - открытие разбора → `review`; закрытие ящика → `edit` при выбранном
 *   инструменте и `view` без него.
 *
 * ── Открытость ящика — ПРОИЗВОДНАЯ ──────────────────────────────────────────
 *
 * Отдельного `drawerOpen` рядом с `Mode` нет и заводить его нельзя: два
 * булевых состояния об одной раскладке рано или поздно разойдутся, и тогда
 * «ящик открыт, но режим не review» станет достижимым состоянием, о котором
 * никто не думал. Ящик открыт тогда и только тогда, когда `mode === 'review'`.
 *
 * Режим «Просмотр» из PRD при этом не исчезает, а становится состоянием
 * «инструмент не выбран, ящик закрыт»: свёрнутой в кнопку «Кальки» больше нет,
 * рейка видна всегда. Это осознанное отклонение от буквы FR-02 — правка
 * формулировки вынесена в PRD отдельно.
 */
export type Mode = 'view' | 'edit' | 'review'

/** Инструмент палитры (FR-05…FR-14). Поведение подключается на этапе 3 PRD. */
export type Tool = 'text' | 'area' | 'point'

