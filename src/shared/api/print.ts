import { createLogger } from 'shared/lib/log'

const log = createLogger('print')

/*
 * Третья внешняя граница сегмента `shared/api` рядом со `storage.ts` и
 * `files.ts`: печать.
 *
 * ── Печатается СВОЙ документ, а не страница-носитель ────────────────────────
 *
 * `window.print()` напечатал бы прототип с его собственными правилами
 * `@media print` — то есть чужой замысел о том, как этот сайт выглядит
 * на бумаге, вместо нашего отчёта. Хуже того, метки уехали бы: печатная вёрстка
 * пересчитывается на бумажную ширину, а слой меток позиционируется нашим кодом
 * по экранным координатам и при печати не пересчитывается. Поэтому отчёт
 * собирается отдельным документом и печатается из `<iframe>`.
 *
 * ── Почему `parent` приходит ПАРАМЕТРОМ ─────────────────────────────────────
 *
 * Ровно те же две причины, что в шапке `files.ts`. Первая: обещание «страница
 * после демонтажа неотличима от исходной» держится с первой вехи и исключений
 * не имеет — узлы в `document.body` носителя мы не добавляем. Вторая: вставка
 * узла в тело носителя разбудила бы наш собственный наблюдатель мутаций
 * и вызвала лишний проход наложения слоя. Вызывающий передаёт узел из Shadow
 * DOM «Кальки», который в дереве документа лежит.
 *
 * ── Почему НЕ `display: none` ───────────────────────────────────────────────
 *
 * Safari исторически отказывался печатать из скрытого узла: `contentWindow`
 * у него мог быть не готов, а печать уходила пустым листом. Поэтому iframe
 * остаётся видимым для движка и убирается с глаз нулевым размером и выносом
 * за экран. Это не перестраховка «на всякий случай», а известный отступной
 * путь — при его отказе остаётся отдать отчёт файлом на скачивание тем же
 * `downloadText`.
 */

/** Сколько ждать снятия узла после постановки печати, мс. */
const CLEANUP_DELAY_MS = 60_000

export interface PrintInput {
  /** Самодостаточный HTML документа отчёта: стили внутри, внешних адресов нет. */
  html: string
  /** Узел-родитель временного `<iframe>`: теневой корень «Кальки», не `body`. */
  parent: Element
}

/**
 * Ставит документ на печать. Возвращает `false` при любом сбое, наружу
 * не бросая ничего (NFR-06): неудавшаяся печать не имеет права уронить
 * ни виджет, ни сайт-носитель.
 *
 * `true` означает «печать ПОСТАВЛЕНА», а не «документ напечатан». Средства
 * браузера о своём исходе не сообщают вовсе: диалог мог быть отменён, файл мог
 * быть не сохранён, и узнать об этом неоткуда. Всё, что зависит от успеха
 * печати, обязано считаться с этим пределом — в частности, буфер вырезок
 * очищается не по факту печати, а при следующем изменении набора правок.
 *
 * Содержимое документа не логируется никогда: это текст правок заказчика.
 */
export function printDocument({ html, parent }: PrintInput): boolean {
  let frame: HTMLIFrameElement | null = null

  try {
    const doc = parent.ownerDocument
    frame = doc.createElement('iframe')

    // Не `display: none` — см. шапку. Нулевой размер и вынос за экран убирают
    // узел с глаз, оставляя его «видимым» для движка печати.
    frame.setAttribute(
      'style',
      'position:absolute;width:0;height:0;border:0;left:-9999px;top:0;opacity:0',
    )
    frame.setAttribute('aria-hidden', 'true')
    // Пустой `sandbox` не годится: он отнял бы у документа право печататься.
    // Скрипты в документе отчёта не нужны и в него не попадают вовсе.
    frame.setAttribute('srcdoc', html)

    // Печать ставится только ПОСЛЕ `onload`. Вызов до загрузки `srcdoc` даёт
    // пустой лист: документа в `contentWindow` ещё нет, а печатать браузер
    // начинает немедленно.
    frame.onload = (): void => {
      try {
        const view = frame?.contentWindow
        if (!view) {
          log.warn('печать не поставлена: документ отчёта недоступен')
          return
        }

        // `focus()` перед печатью: часть браузеров печатает активный документ,
        // а не тот, у которого позвали `print()`.
        view.focus()
        view.print()
        log.debug('печать поставлена')
      } catch (error) {
        log.warn('сбой при постановке печати', { ошибка: error })
      }
    }

    parent.appendChild(frame)
    log.debug('документ отчёта передан на печать', { байт: html.length })
    return true
  } catch (error) {
    log.warn('не удалось передать документ на печать', { ошибка: error })
    frame?.remove()
    return false
  } finally {
    /*
     * Узел снимается ОТЛОЖЕННО, а не в этом же такте.
     *
     * `print()` в части браузеров возвращается не дождавшись, пока диалог
     * закончит читать документ, и снятый узел оставил бы человека с пустым
     * предпросмотром. Отсрочка щедрая по той же причине, по которой щедра
     * `REVOKE_DELAY_MS` в `files.ts`: человек читает свой отчёт в диалоге
     * печати, а не жмёт «Сохранить» вслепую.
     */
    const doomed = frame
    if (doomed !== null) {
      window.setTimeout(() => doomed.remove(), CLEANUP_DELAY_MS)
    }
  }
}
