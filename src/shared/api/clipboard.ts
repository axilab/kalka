import { createLogger } from 'shared/lib/log'

const log = createLogger('clipboard')

/*
 * Третья внешняя граница сегмента `shared/api` рядом с `storage.ts` и `files.ts`:
 * буфер обмена (FR-34).
 *
 * КЛЮЧЕВОЕ: копирование ОБЯЗАНО иметь запасной путь, и живёт он в интерфейсе,
 * а не здесь. `navigator.clipboard` требует безопасного контекста, а прототипы
 * из PRD стоят на внутренних стендах по `http://` — то есть ровно там, где его
 * нет. Кнопка, которая молча не работает, хуже отсутствующей кнопки: человек
 * решит, что текст скопирован, и вставит в поиск по коду пустоту.
 *
 * Отсюда контракт: эта функция возвращает `false` и НИЧЕГО не бросает, а
 * вызывающий обязан показать текст полем, выделенным целиком, чтобы рецензент
 * скопировал его сам (`widgets/entry-list/ui/CopyButton.tsx`).
 *
 * `document.execCommand('copy')` не используется и не появится. Он объявлен
 * устаревшим, требует вставки узла в документ — то есть нарушения обещания
 * «страница после демонтажа неотличима от исходной» — и на части браузеров
 * молча не работает. Это третий путь с тем же дефектом, что и первый, а не
 * страховка.
 *
 * В лог не уходит копируемый текст: это текст правки заказчика (решение 22).
 * Только его длина и причина отказа.
 */

export async function copyText(text: string): Promise<boolean> {
  try {
    // Проверка перед вызовом, а не только try/catch: на небезопасном контексте
    // `navigator.clipboard` отсутствует как свойство, и обращение к `writeText`
    // упало бы TypeError — исход тот же, но по логу неотличимый от отказа
    // в разрешении.
    const target = navigator.clipboard
    if (!target || typeof target.writeText !== 'function') {
      log.warn('копирование недоступно', {
        знаков: text.length,
        причина: 'буфер обмена недоступен на этой странице',
      })
      return false
    }

    await target.writeText(text)
    log.debug('текст скопирован', { знаков: text.length })
    return true
  } catch (error) {
    // Сюда приходит отказ в разрешении и отказ браузера копировать вне жеста
    // пользователя. Различать их незачем: рецензенту в обоих случаях нужен
    // один и тот же запасной путь.
    log.warn('копирование не удалось', { знаков: text.length, ошибка: error })
    return false
  }
}
