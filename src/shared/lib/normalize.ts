/**
 * Единая нормализация текста.
 *
 * Применяется ровно в трёх местах, и это важнее самой функции:
 *   1. запись `snippet` при создании якоря (`entities/anchor/model/build.ts`);
 *   2. поиск по фрагменту текста, уровень 3 (`entities/anchor/model/resolve.ts`);
 *   3. сверка `was` с текущим текстом элемента (`entities/anchor/model/drift.ts`).
 *
 * Разные нормализации в этих трёх точках дают неуловимые расхождения: фрагмент
 * записан одним способом, ищется другим, сверяется третьим. Поэтому правится
 * функция ЗДЕСЬ, а не заплаткой на месте применения.
 *
 * Чего она намеренно НЕ делает: не удаляет мягкий перенос (U+00AD) и прочие
 * невидимые символы. Такой случай на прототипах ещё не встречался; если
 * встретится — правка идёт сюда, разом во все три точки.
 */

/*
 * NBSP (U+00A0) отдельной заменой НЕ обрабатывается, хотя в вёрстке встречается
 * постоянно: класс `\s` в регулярных выражениях JavaScript уже включает его —
 * наравне с узким неразрывным пробелом (U+202F) и остальными пробельными
 * символами Unicode. Их схлопывает та же `\s+`, а краевые снимает `trim()`.
 *
 * Отдельная замена литеральным символом (как в образце навыка
 * kalka-anchoring/references/anchor-strategy.md) здесь была бы и лишней,
 * и вредной: литеральный NBSP в исходнике неотличим от пробела при чтении,
 * и линтер справедливо его запрещает (no-irregular-whitespace).
 */
export function normalize(s: string): string {
  return s.replace(/\s+/g, ' ').trim()
}
