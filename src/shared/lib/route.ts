import { ACTIVATION_PARAM } from 'shared/config/constants'

/**
 * Маршрут страницы: то, чем записи привязаны к странице носителя.
 *
 * Состав: `pathname` + строка запроса БЕЗ параметра активации + непустой `hash`.
 *
 * Параметр `kalka` вычёркивается намеренно: он включает виджет и не имеет права
 * влиять на тождество маршрута — иначе `?kalka` и `?kalka=1` дали бы две разные
 * страницы, и правки одной не наложились бы на другую.
 *
 * Остальные параметры запроса в маршрут ВХОДЯТ: дев-стенд `dev/spa.html`
 * навигирует именно ими, и на реальных прототипах такой роутинг встречается.
 * Пустая строка запроса не даёт хвостового `?`.
 *
 * Функция живёт в `shared`, а не рядом с перехватом навигации: маршрут нужен
 * и движку наложения (слой `app`), и сборке записи (слой `features`), а
 * импортировать из `app` слой ниже не может. Две реализации разбора адреса —
 * это тихо разъезжающееся тождество страницы, поэтому она здесь одна.
 */
export function currentRoute(loc: Location = location): string {
  const params = new URLSearchParams(loc.search)
  params.delete(ACTIVATION_PARAM)
  const query = params.toString()
  return `${loc.pathname}${query ? `?${query}` : ''}${loc.hash}`
}
