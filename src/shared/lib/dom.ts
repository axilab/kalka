/**
 * Теги, на которых подъём к цели правки ОСТАНАВЛИВАЕТСЯ.
 *
 * Интерактивный элемент — самостоятельная вещь на странице: у кнопки и ссылки
 * свой текст, и правится он целиком, а не куском абзаца вокруг. До вехи
 * «правка текста в кнопках и ссылках» такие элементы были недостижимы:
 * `isTextElement` отсекал кнопку с `<svg>` внутри (значок — собственный бокс),
 * а `climbToOutermost` уводил ссылку внутри абзаца к абзацу.
 *
 * Список ОТКРЫТЫЙ, как и `INLINE_TAGS` выше: встретили прототип, где граница
 * промахивается, — тег дописывается сюда, в одно место.
 *
 * `INPUT` в набор НЕ входит намеренно: его текст живёт в атрибутах
 * (`placeholder`, `value`), а правка атрибутов вынесена отдельной вехой.
 */
const EDIT_BOUNDARY_TAGS = new Set(['A', 'BUTTON', 'LABEL', 'SUMMARY'])

/**
 * Значения атрибута `role`, дающие ту же границу без «правильного» тега.
 *
 * `<div role="button">` на живых страницах встречается не реже настоящей
 * кнопки. Список открыт по той же причине и правится там же, что и
 * `EDIT_BOUNDARY_TAGS`.
 */
const EDIT_BOUNDARY_ROLES = new Set(['button', 'link'])

/**
 * Граница правки: интерактивный элемент, дальше которого подъём не идёт.
 *
 * Проверка стоит из двух сравнений строк и зовётся на каждом движении
 * указателя — вычисленные стили здесь не спрашиваются вовсе.
 */
export function isEditBoundary(el: Element): boolean {
  if (EDIT_BOUNDARY_TAGS.has(el.tagName)) return true
  const role = el.getAttribute('role')
  return role !== null && EDIT_BOUNDARY_ROLES.has(role)
}

/**
 * Идёт ли правка этого элемента ТЕКСТОМ, а не разметкой.
 *
 * Два условия, и второе считается по `wasHtml`, а НЕ по живому элементу.
 * Это не удобство подписи, а условие обратимости.
 *
 * `<button>Купить <span class="count">3</span></button>` идёт путём разметки —
 * счётчик непустой. Белый список санитайзера `<span>` не пропускает, поэтому
 * после первой же записи в DOM остаётся `<button>Купить 3</button>` БЕЗ
 * детей-элементов. Спроси предикат у живого элемента на следующем проходе —
 * он ответит «текстовый путь», восстановление уйдёт в `writeTextNodes` вместо
 * возврата исходной разметки, и `<span class="count">` не вернётся ни при
 * переприменении, ни при снятии слоя. Страница после снятия виджета отличалась
 * бы от исходной — прямое нарушение NFR-06.
 *
 * `wasHtml` разбирается в отсоединённый `<template>` БЕЗ санитайзера:
 * санитайзер снял бы и `<svg>`, и `<span>`, и два разных случая слились бы
 * в один ложно-текстовый. Разбор идёт только на чтение структуры, в страницу
 * не попадает ничего.
 *
 * Дешевизна обязательна: `isEditBoundary` — сравнение строк — проверяется
 * первым и отсекает почти всё даром; разбор `wasHtml` идёт только после него.
 */
export function usesTextPath(el: Element, wasHtml: string): boolean {
  return isEditBoundary(el) && hasNoTextChildren(wasHtml, el.ownerDocument)
}

/**
 * Второе условие текстового пути отдельно: у КАЖДОГО элемента-ребёнка исходной
 * разметки пустой нормализованный текст.
 *
 * `<svg>` и `<img>` в `textContent` не дают ничего, поэтому у кнопки со значком
 * условие выполняется. У кнопки со счётчиком в `<span>` — нет.
 */
function hasNoTextChildren(wasHtml: string, doc: Document): boolean {
  const template = doc.createElement('template')
  template.innerHTML = wasHtml

  for (const child of template.content.children) {
    if (normalize(child.textContent ?? '')) return false
  }
  return true
}

/**
 * Тот же вывод, но ПО ЗАПИСИ, когда живого элемента уже нет.
 *
 * Нужен ровно двум местам — строке «стало» печатного отчёта и проверке после
 * передеплоя: обе читают `now` спустя время, элемента у них на руках нет,
 * а знать, разметка перед ними или текст, обязаны.
 *
 * ── Предел, принятый сознательно ────────────────────────────────────────────
 *
 * Границы, заданные АТРИБУТОМ `role` (`<div role="button">`), из записи
 * невосстановимы: `role` в формате обмена не хранится, а поднимать `format`
 * ради него веха не стала. Такие записи в этих двух местах читаются как
 * разметка — то есть так же, как читались до вехи. Последствие узкое
 * и записано в «Известные пределы» плана.
 */
export function usesTextPathByTag(tag: string, wasHtml: string, doc: Document): boolean {
  return EDIT_BOUNDARY_TAGS.has(tag.toUpperCase()) && hasNoTextChildren(wasHtml, doc)
}

/**
 * Кладёт строку в текстовые узлы элемента, не трогая детей-элементов.
 *
 * Живёт ЗДЕСЬ, а не в движке наложения (`app/lib/overlay/engine.ts`), хотя
 * первый потребитель именно он. Причина жёсткая: та же операция нужна сборке
 * вырезки в `entities/cutout`, а `entities` лежит ниже `app` и импортировать
 * движок не может — `npm run lint` уронит сборку правилом
 * `no-restricted-imports` (ARCHITECTURE.md, «Правила зависимостей»).
 * `shared` видят оба потребителя. Унесёте обратно в движок — сломаете сборку.
 *
 * Строка кладётся в ПЕРВЫЙ прямой текстовый узел, остальные прямые текстовые
 * узлы очищаются, элементы-дети не трогаются вовсе: значок на кнопке обязан
 * пережить правку её текста. Прямых текстовых узлов нет — добавляется новый
 * последним.
 *
 * Санитайзер не участвует: пишется текст, а `createTextNode` разметку
 * не разбирает.
 *
 * Узел создаётся через `el.ownerDocument`, а не через глобальный `document`:
 * у сборки вырезки на руках отсоединённый клон, и слайсы `entities`
 * к глобали не обращаются (ARCHITECTURE.md).
 */
export function writeTextNodes(el: Element, text: string): void {
  let first: Text | null = null

  for (const node of el.childNodes) {
    if (node.nodeType !== Node.TEXT_NODE) continue
    const textNode = node as Text
    if (first === null) {
      first = textNode
      textNode.data = text
    } else {
      textNode.data = ''
    }
  }

  if (first === null) {
    // Кнопка из одного значка либо элемент, чей текст лежит глубже: свой узел
    // приходится завести. Само содержимое в лог не пишется — это текст
    // страницы заказчика.
    log.warn('текстовых узлов нет, добавлен новый', {
      тег: el.tagName.toLowerCase(),
      знаков: text.length,
    })
    el.appendChild(el.ownerDocument.createTextNode(text))
  }
}

/** Атрибут собственного элемента `<style>` с подсветкой: по нему он и снимается. */
const HOVER_STYLE_ATTRIBUTE = 'data-kalka-hover-style'

/*
 * Подсветка цели — `outline` собственным элементом `<style>`, ровно тот же приём,
 * что и у подсветки цели прокрутки (app/lib/overlay/engine.ts): правило носителя
 * не трогается, `outline` не занимает места и не сдвигает вёрстку, а элемент
 * `<style>` живёт в `<head>`, куда наблюдатель мутаций не смотрит, — собственная
 * подсветка не будит переприменение слоя (решение 5).
 *
 * ── Цвет ────────────────────────────────────────────────────────────────────
 *
 * Литерал, а не переменная: правило живёт в <head> НОСИТЕЛЯ, за пределами
 * теневого корня, куда переменные :host не приходят по устройству. Источник
 * значения — --kalka-redline (#c8362a) из app/ui/host.css; менять их надо парой.
 *
 * Красный, а не приглушённый: обводка под курсором — ПЕРВОЕ, что видит
 * человек, взяв инструмент «Текст», и она обязана читаться тем же цветом,
 * каким виджет метит своё.
 *
 * От подсветки цели прокрутки (FR-31) её отличает не толщина линии,
 * а отсутствие заливки: контур означает «это возьмётся, если нажать»,
 * заливка — «вот оно, я привёл». Полное объяснение — рядом с TARGET_CSS
 * в app/lib/overlay/engine.ts.
 */
const HOVER_CSS = `[${HOVER_ATTRIBUTE}]{outline:2px solid rgba(200,54,42,.85);outline-offset:2px;cursor:pointer}`

/**
 * Годится ли элемент в цель правки: есть непустой текст и нет блочных детей.
 *
 * Эвристика открытая (решение 4): встретили прототип, где она промахивается, —
 * правится здесь, в одном месте, а не заплаткой на месте вызова.
 */
/**
 * Раскладки, превращающие детей в самостоятельные боксы независимо от тега.
 *
 * Флекс- и грид-контейнер БЛОКИФИЦИРУЮТ своих детей: `<span>` внутри них
 * получает вычисленный `display: block`, хотя тегом остаётся строчным.
 * Проверено в браузере на разметке боевого прототипа заказчика (example.com).
 */
const BLOCKIFYING_DISPLAY = new Set(['flex', 'inline-flex', 'grid', 'inline-grid'])

/**
 * Вычисленный `display` элемента либо `null`, если спросить не у кого.
 *
 * `null` — не «неизвестно, считаем блоком», а «признака нет»: вызывающие
 * при нём откатываются к прежнему поведению по тегам. Иначе оторванный
 * от окна документ выключил бы инструмент «Текст» целиком.
 */
function displayOf(el: Element): string | null {
  const view = el.ownerDocument.defaultView
  if (!view) return null
  try {
    // Пустая строка — тоже «признака нет»: так отвечают реализации с неполной
    // таблицей стилей по умолчанию (jsdom не знает строчных вовсе) и
    // оторванные от документа узлы. Считать её блоком нельзя.
    return view.getComputedStyle(el).display || null
  } catch {
    return null
  }
}

/**
 * Строчный ли ребёнок НА САМОМ ДЕЛЕ, а не по имени тега.
 *
 * Тег проверяется первым и отсекает почти всё даром: спрашивать вычисленный
 * стиль у каждого `<div>` внутри каждого предка на каждом движении указателя
 * значило бы пересчитывать стили чужой страницы десятки раз в секунду.
 */
function isInlineChild(child: Element): boolean {
  if (!INLINE_TAGS.has(child.tagName)) return false

  const display = displayOf(child)
  if (display === null) return true

  /*
   * Ребёнок, не создающий бокса, раскладке не мешает и абзац не разрывает.
   *
   * Это не педантизм: подпись для программы чтения с экрана — обычно
   * `<span hidden>` или `span` со скрывающим классом, и таких внутри текста
   * на живых страницах полно. Посчитай их блоками — и абзац с одной такой
   * подписью перестал бы быть правимым, а подъём ушёл бы к предку, забрав
   * половину страницы. Ровно та поломка, которую эта правка и чинит,
   * только с другой стороны.
   */
  if (display === 'none' || display === 'contents') return true

  // Ровно `inline`: `inline-block` и `inline-flex` — собственные боксы,
  // и значок, вставленный в строку, правится отдельно от неё.
  return display === 'inline'
}

/**
 * Текстовый ли элемент: есть текст, и все дети — строчные.
 *
 * ── Почему одного тега мало ─────────────────────────────────────────────────
 *
 * Прежде «строчность» ребёнка определялась ИМЕНЕМ ТЕГА, и этого хватало ровно
 * до первой страницы, где `<span>` используют как плашку. На карточке товара
 * боевого прототипа заказчика ряд чипов размечен так:
 *
 *     <div class="flex flex-wrap gap-2"><span>10 Мбит/с</span><span>…</span></div>
 *
 * Четыре отдельные плашки на экране, четыре `<span>` в разметке — и контейнер
 * выглядел как абзац с разметкой. Подъём до самого внешнего текстового элемента
 * забирал его целиком, и в окне правки оказывалась строка
 * «10 Мбит/сДомашнийОфисныйПромышленный»: текст четырёх соседей
 * встык, без пробелов, потому что `textContent` их и не ставит.
 *
 * Отличает одно от другого РАСКЛАДКА, а не разметка, поэтому проверок две:
 * сам элемент не должен раскладывать детей боксами, и каждый ребёнок должен
 * быть строчным по вычисленному стилю. Второй проверки хватило бы и одной
 * (блокификация видна на самих детях), но первая стоит один вызов вместо
 * N и отсекает случай целиком.
 */
export function isTextElement(el: Element): boolean {
  if (!normalize(el.textContent ?? '')) return false

  const display = displayOf(el)
  if (display !== null && BLOCKIFYING_DISPLAY.has(display)) return false

  for (const child of el.children) {
    if (!isInlineChild(child)) return false
  }
  return true
}

/** Находка вместе с числом шагов подъёма: шаги нужны только логу. */
interface Pick {
  element: Element | null
  steps: number
}

/**
 * Чистое ядро выбора цели: от стартового узла вверх до цели правки.
 *
 * Экспортируется РАДИ ТЕСТОВ, а не ради потребителей: `pickFrom` требует
 * события с рабочим `composedPath()`, которое jsdom синтезирует криво, и без
 * этого шва правило выбора цели непроверяемо. Потребители на странице зовут
 * `findTextTarget`/`watchPicking`, как и раньше.
 *
 * Порядок проверок внутри цикла обязателен: граница спрашивается ПЕРВОЙ, и
 * `isTextElement` для неё не спрашивается вовсе. Иначе `display: inline-flex`
 * и дети-`<svg>` снова отсекут кнопку — ровно то, что веха и чинит.
 */
export function pickTarget(start: Element): Pick {
  let node: Element | null = start
  let steps = 0

  while (node && steps <= PICK_MAX_DEPTH) {
    // Граница правки останавливает подъём: у кнопки и ссылки свой текст,
    // и правится он целиком. Пустая граница (кнопка из одного значка) целью
    // не становится — подъём продолжается.
    if (isEditBoundary(node) && normalize(node.textContent ?? '')) {
      return { element: node, steps }
    }
    if (isTextElement(node)) return climbToOutermost(node, steps)
    node = node.parentElement
    steps += 1
  }

  // Подходящего элемента нет: под курсором контейнер с блочными детьми либо
  // пустое место. Клик по такому месту игнорируется, подсветки нет.
  return { element: null, steps }
}

function pickFrom(event: Event): Pick {
  // Событие собственного интерфейса целью не является никогда: рецензент
  // нажимает кнопку виджета, а не правит его текст.
  if (isInsideKalka(event)) return { element: null, steps: 0 }

  const start = event.composedPath()[0]
  const node: Element | null =
    start instanceof Element ? start : start instanceof Node ? start.parentElement : null

  if (!node) return { element: null, steps: 0 }
  return pickTarget(node)
}

/**
 * Поднимается до САМОГО ВНЕШНЕГО текстового элемента подряд идущей цепочки.
 *
 * Первый попавшийся не годится: `<strong>` внутри абзаца сам по себе текстовый
 * элемент, и остановка на нём дала бы правку одного слова с якорем на слово —
 * ровно тот случай, который решение 4 называет проблемой («под курсором может
 * оказаться `<span>` внутри абзаца»). Подъём прекращается на первом родителе,
 * который текстовым элементом уже не является: `<section>` с половиной страницы
 * целью не станет.
 *
 * ── Граница останавливает подъём НА СЕБЕ, а не перед собой ──────────────────
 *
 * Порядок внутри цикла обязателен: сначала проверяется, не является ли родитель
 * границей, и если да — подъём делает в неё ПОСЛЕДНИЙ шаг и прекращается.
 * Обратная формулировка («остановиться, если родитель — граница») дала бы
 * конкретный промах: клик по `<b>` внутри `<a>Перейти <b>к прайсу</b></a>`
 * в главный цикл `pickTarget` не попадает вовсе (`isTextElement(<b>)` истинен
 * сразу), подъём оборвался бы перед ссылкой, и целью стал бы `<b>`.
 */
function climbToOutermost(found: Element, foundAt: number): Pick {
  let element = found
  let steps = foundAt

  while (steps < PICK_MAX_DEPTH) {
    const parent = element.parentElement
    if (!parent) break
    if (isEditBoundary(parent)) {
      element = parent
      steps += 1
      break
    }
    if (!isTextElement(parent)) break
    element = parent
    steps += 1
  }

  return { element, steps }
}

/**
 * Ближайший вверх по дереву текстовый элемент под указателем события.
 * `null` — событие внутри виджета либо подходящего элемента не нашлось.
 */
export function findTextTarget(event: Event): Element | null {
  return pickFrom(event).element
}

/**
 * Включает режим выбора элемента на странице носителя.
 * Возвращает ПОЛНОЕ снятие: слушатели сняты, атрибут снят, `<style>` удалён.
 *
 * Обработчики обёрнуты `safely`: исключение виджета не имеет права уйти
 * в код носителя (NFR-06).
 */
export function watchPicking(onPick: (el: Element) => void): () => void {
  let current: Element | null = null

  const style = document.createElement('style')
  style.setAttribute(HOVER_STYLE_ATTRIBUTE, '')
  style.textContent = HOVER_CSS
  // head может отсутствовать на экзотической странице — тогда подсветки просто
  // не будет, и ронять из-за неё выбор элемента нельзя.
  document.head?.appendChild(style)

  function highlight(next: Element | null): void {
    if (next === current) return
    current?.removeAttribute(HOVER_ATTRIBUTE)
    current = next
    current?.setAttribute(HOVER_ATTRIBUTE, '')
  }

  const onPointerMove = safely(log, 'ведение по странице', (event: Event) => {
    highlight(pickFrom(event).element)
  })

  const onClick = safely(log, 'выбор элемента', (event: Event) => {
    // Клик по собственному интерфейсу не гасится и целью не считается:
    // перехват в фазе погружения срабатывает РАНЬШЕ гашения на точке
    // монтирования, и без этой проверки кнопки виджета перестали бы работать.
    if (isInsideKalka(event)) return

    // Гашение намеренное и действует только пока инструмент включён (решение 3):
    // иначе клик по правленому заголовку внутри ссылки увёл бы со страницы
    // вместо открытия редактора. Выключили инструмент — перехват снят целиком.
    event.preventDefault()
    event.stopPropagation()

    const { element, steps } = pickFrom(event)
    if (!element) {
      // Тег стартового узла обязателен: без него отладка промаха на чужом
      // прототипе сводится к угадыванию.
      const start = event.composedPath()[0]
      const from = start instanceof Element ? start : (start as Node | undefined)?.parentElement
      log.debug('под курсором нет цели', {
        тег: from?.tagName.toLowerCase() ?? '—',
        шаговВверх: steps,
      })
      return
    }

    // Текст элемента в лог не пишется: это содержимое страницы заказчика.
    // Элемент здесь ещё нетронут, поэтому `innerHTML` — это и есть `wasHtml`.
    log.debug('элемент выбран', {
      тег: element.tagName.toLowerCase(),
      шаговВверх: steps,
      путь: isEditBoundary(element) ? 'граница' : 'подъём',
      текстовыйПуть: usesTextPath(element, element.innerHTML),
    })
    onPick(element)
  })

  document.addEventListener('pointermove', onPointerMove, true)
  document.addEventListener('click', onClick, true)
  log.debug('режим выбора элемента включён')

  return (): void => {
    document.removeEventListener('pointermove', onPointerMove, true)
    document.removeEventListener('click', onClick, true)
    // Страница обязана вернуться к исходному виду: ни атрибута, ни своего
    // элемента <style> после снятия не остаётся.
    highlight(null)
    style.remove()
    log.debug('режим выбора элемента снят')
  }
}

/*
 * Заморозка движения на время съёмки вырезки.
 *
 * ── Что она НЕ обещает ──────────────────────────────────────────────────────
 *
 * Вырезка — не растровый снимок, а клон DOM с перенесёнными вычисленными
 * стилями. Пауза анимации не переводит её в конечное состояние и «правильной»
 * картинки не даёт; обещать этого не надо.
 *
 * ── Ради чего она заведена ──────────────────────────────────────────────────
 *
 * Геометрия и стили снимаются РАЗНЫМИ проходами, и на движущемся элементе они
 * приезжают из разных мгновений, отчего клон выходит рассогласованным сам
 * с собой. Критерий приёмки — не «анимация выглядит правильно», а «геометрия
 * и стили клона сняты из одного мгновения».
 *
 * ── Почему ЗДЕСЬ, а не в слайсе вырезки ─────────────────────────────────────
 *
 * ARCHITECTURE.md перечисляет ровно четыре места, которым разрешено трогать DOM
 * носителя: `app/index.ts`, `app/lib/mount.ts`, `app/lib/overlay`
 * и `shared/lib/dom.ts`. `entities/cutout` в списке нет, и весь слайс сегодня
 * только ЧИТАЕТ страницу — это записано в его шапках трижды. Заморозка была бы
 * первой мутацией носителя из `entities`.
 *
 * Приём тут уже стоит: собственный `<style>` подсветки наведения выше. Третий
 * такой элемент встаёт рядом со вторым, а импорт `entities → shared` правилам
 * зависимостей не противоречит.
 *
 * ── Границу проводим здесь и записываем ─────────────────────────────────────
 *
 * `setTimeout`, `setInterval` и `requestAnimationFrame` НЕ патчатся. Приём
 * из репозитория agentation работает у них потому, что тулбар живёт внутри
 * своего приложения; «Калька» — ГОСТЬ на чужой странице, и подмена таймеров
 * носителя нарушает NFR-06.
 */

/** Атрибут собственного `<style>` заморозки: по нему он и снимается. */
const FREEZE_STYLE_ATTRIBUTE = 'data-kalka-freeze-style'

/*
 * Поддерево собственного интерфейса из-под правила выведено: замораживать надо
 * страницу носителя, а не свои же переходы. `transition: none` без этого
 * оборвал бы анимацию открытия окна правки прямо под рукой у рецензента.
 */
const FREEZE_CSS =
  `*:not([${ROOT_ATTRIBUTE}]):not([${ROOT_ATTRIBUTE}] *)` +
  `{animation-play-state:paused!important;transition:none!important}`

const freeze = log.child('freeze')

/**
 * Останавливает движение на странице. Возвращает ПОЛНОЕ снятие — ровно как
 * `watchPicking` и `syncStyle`.
 *
 * Возобновляется только то, что шло: правило профилактики «проверять не только
 * остановленное, но и уцелевшее» работает и в самой реализации, а не только
 * в её тестах. Запусти всё подряд — и пауза, поставленная носителем, снялась бы
 * нашими руками.
 */
export function freezeMotion(root: Document): () => void {
  const style = root.createElement('style')
  style.setAttribute(FREEZE_STYLE_ATTRIBUTE, '')
  style.textContent = FREEZE_CSS
  // head может отсутствовать на экзотической странице — тогда правило просто
  // не встанет, и ронять из-за него съёмку нельзя.
  root.head?.appendChild(style)

  // Только те, что РЕАЛЬНО шли: `getAnimations` отдаёт и завершённые,
  // и поставленные на паузу самим носителем.
  const running: Animation[] = []
  try {
    for (const animation of root.getAnimations()) {
      if (animation.playState !== 'running') continue
      animation.pause()
      running.push(animation)
    }
  } catch {
    // Экзотический носитель мог не знать `getAnimations`. Правило в `<style>`
    // уже стоит, и съёмку из-за этого ронять незачем.
    freeze.debug('список анимаций получить не удалось')
  }

  const playing: HTMLVideoElement[] = []
  for (const video of root.querySelectorAll('video')) {
    if (video.paused) continue
    video.pause()
    playing.push(video)
  }

  freeze.debug('движение заморожено', { анимаций: running.length, видео: playing.length })

  return (): void => {
    // Снятие обязано быть ПОЛНЫМ и отработать даже при исключении в съёмке:
    // страница обязана вернуться к исходному виду (NFR-06).
    style.remove()
    for (const animation of running) safely(freeze, 'возобновление анимации', () => animation.play())()
    for (const video of playing) safely(freeze, 'возобновление видео', () => void video.play())()
    freeze.debug('движение восстановлено')
  }
}

/*
 * Рисование области и постановка указателя на чужой странице (FR-13, FR-14).
 *
 * Живёт здесь по той же причине, что и выбор текстового элемента выше: список
 * мест, которым разрешено трогать DOM носителя, состоит из четырёх пунктов
 * (ARCHITECTURE.md), и `shared/lib/dom` — один из них. Слайсы `features/draw-area`
 * и `features/place-point` эту механику только включают и выключают.
 *
 * Вся геометрия ниже — во ВЬЮПОРТНОЙ системе координат: `clientX/clientY`
 * и `getBoundingClientRect()` уже в ней, и `scrollX/scrollY` не появляется
 * нигде (решение 9 плана вехи, `shared/lib/geometry.ts`).
 */

const marks = log.child('marks')

/**
 * Допуск на дробные пиксели при проверке «рамка помещается в элемент».
 *
 * `getBoundingClientRect()` возвращает дробные значения, и рамка, обведённая
 * ровно по краю блока, промахивалась бы мимо него на сотые доли пикселя —
 * якорем стал бы предок, а не сам блок.
 */
const CONTAIN_TOLERANCE_PX = 1

/**
 * Элемент носителя в точке вьюпорта.
 *
 * Собственные узлы отбрасываются: `elementFromPoint` вернёт host-элемент
 * «Кальки», если точка попала под её панель или под уже поставленную метку.
 * Без этой проверки якорем правки стал бы сам виджет, и запись пережила бы
 * его демонтаж, указывая в никуда (решение 11 плана вехи).
 */
export function elementAtPoint(x: number, y: number): Element | null {
  const found = document.elementFromPoint(x, y)
  if (!found || found.closest(ROOT_SELECTOR)) return null
  return found
}

/** Помещается ли `inner` целиком в `outer` с точностью до дробных пикселей. */
function contains(outer: DOMRectReadOnly, inner: DOMRectReadOnly): boolean {
  return (
    outer.left - CONTAIN_TOLERANCE_PX <= inner.left &&
    outer.top - CONTAIN_TOLERANCE_PX <= inner.top &&
    outer.right + CONTAIN_TOLERANCE_PX >= inner.right &&
    outer.bottom + CONTAIN_TOLERANCE_PX >= inner.bottom
  )
}

/**
 * Элемент-якорь для нарисованной рамки: наименьший предок, в который она
 * помещается целиком.
 *
 * Правило — эвристика, и открытая (решение 11 плана вехи). Обводят обычно
 * карточку или блок, и «наименьший предок, в который рамка помещается» — это
 * он и есть. Не нашли за `RECT_ANCHOR_MAX_DEPTH` шагов — берём последний
 * рассмотренный: якорь предположительный лучше, чем его отсутствие, потому что
 * доли всё равно считаются от чьего-то bounding box.
 *
 * От выбора элемента под курсором (`findTextTarget`) правило отличается
 * намеренно: там ищется текст, здесь — контейнер.
 */
export function pickRectAnchor(drawn: DOMRectReadOnly): Element | null {
  const start = elementAtPoint(drawn.left + drawn.width / 2, drawn.top + drawn.height / 2)
  if (!start) {
    marks.debug('под центром рамки нет элемента носителя')
    return null
  }

  let node: Element = start
  let steps = 0

  while (steps <= RECT_ANCHOR_MAX_DEPTH) {
    if (contains(node.getBoundingClientRect(), drawn)) {
      marks.debug('якорь рамки найден', { тег: node.tagName.toLowerCase(), шаговВверх: steps })
      return node
    }
    const parent = node.parentElement
    if (!parent) break
    node = parent
    steps += 1
  }

  marks.debug('якорь рамки взят последним рассмотренным', {
    тег: node.tagName.toLowerCase(),
    шаговВверх: steps,
  })
  return node
}

/** Прямоугольник по двум углам: рисовать можно в любую сторону. */
function fromCorners(ax: number, ay: number, bx: number, by: number): DOMRect {
  return new DOMRect(Math.min(ax, bx), Math.min(ay, by), Math.abs(bx - ax), Math.abs(by - ay))
}

/*
 * Полное гашение события носителя.
 *
 * Это ОСОЗНАННОЕ исключение из правила `app/lib/mount.ts` («stopPropagation — да,
 * preventDefault — нет»): там речь про события внутри интерфейса виджета, где
 * preventDefault сломал бы фокус и ввод с клавиатуры, здесь — про перехват
 * на чужой странице и только пока инструмент выбран. Без preventDefault
 * рисование рамки превращается в выделение текста и перетаскивание картинок,
 * без stopPropagation клик по ссылке уводит со страницы вместо постановки
 * метки. Выключили инструмент — перехват снят целиком (решение 16 плана вехи).
 */
function swallow(event: Event): void {
  event.preventDefault()
  event.stopPropagation()
}

/**
 * Режим рисования области (FR-13).
 *
 * `onPreview` получает текущую рамку на каждом движении указателя и `null`
 * при завершении или отмене — рисует её слой меток. `onDrawn` вызывается
 * только для рамки, у которой обе стороны не меньше `MARK_MIN_SIZE_PX`:
 * меньшая рамка — промах мыши, а не область (решение 17 плана вехи).
 *
 * Возвращает ПОЛНОЕ снятие: слушатели сняты, предпросмотр погашен.
 *
 * ── Пауза, а не снятие ──────────────────────────────────────────────────────
 *
 * `isPaused` спрашивается В МОМЕНТ нажатия и означает «рамку не начинать»:
 * пока открыто окно замечания, новая рамка молча выбрасывала бы недописанный
 * текст. Гашение при этом остаётся: снять слушателей на время окна нельзя —
 * ожили бы ссылки носителя ровно тогда, когда рецензент печатает рядом с ними,
 * и промах мимо окна уводил бы со страницы вместе с черновиком.
 *
 * Предикат, а не флаг и не пара «пауза/продолжить»: режим НЕ ПОМНИТ состояние,
 * а спрашивает у вызывающего, поэтому залипнуть ему негде. Источник правды
 * один и тот же — черновик в `features/draw-area`, — и он же управляет курсором.
 *
 * Аргумент обязательный намеренно: забыть его — ровно та поломка проводки,
 * которую тесты механики не видят, а система типов ловит даром.
 */
export function watchAreaDrawing(
  onDrawn: (rect: DOMRectReadOnly) => void,
  onPreview: (rect: DOMRectReadOnly | null) => void,
  isPaused: () => boolean,
): () => void {
  let startX = 0
  let startY = 0
  let drawing = false

  function stopDrawing(): void {
    drawing = false
    onPreview(null)
  }

  const onPointerDown = safely(marks, 'начало рисования области', (event: Event) => {
    // Нажатие по собственному интерфейсу не гасится и рисованием не считается:
    // перехват в фазе погружения срабатывает РАНЬШЕ гашения на точке
    // монтирования, и без этой проверки кнопки виджета перестали бы работать.
    if (isInsideKalka(event)) return
    swallow(event)

    // Гашение выше, проверка паузы здесь: клик по странице при открытом окне
    // замечания обязан остаться проглоченным, а рамку начинать нельзя.
    if (isPaused()) {
      marks.debug('нажатие проглочено, рамка не начата', { причина: 'пауза' })
      return
    }

    const pointer = event as PointerEvent
    startX = pointer.clientX
    startY = pointer.clientY
    drawing = true
    onPreview(fromCorners(startX, startY, startX, startY))
  })

  const onPointerMove = safely(marks, 'ведение рамки', (event: Event) => {
    if (!drawing) return
    swallow(event)
    const pointer = event as PointerEvent
    onPreview(fromCorners(startX, startY, pointer.clientX, pointer.clientY))
  })

  const onPointerUp = safely(marks, 'завершение рисования области', (event: Event) => {
    if (!drawing) return
    swallow(event)

    const pointer = event as PointerEvent
    const rect = fromCorners(startX, startY, pointer.clientX, pointer.clientY)
    stopDrawing()

    if (rect.width < MARK_MIN_SIZE_PX || rect.height < MARK_MIN_SIZE_PX) {
      marks.debug('рисование отменено', {
        причина: 'мало',
        ширина: Math.round(rect.width),
        высота: Math.round(rect.height),
      })
      return
    }

    // Координаты в лог писать можно: это не текст заказчика.
    marks.debug('рамка нарисована', {
      ширина: Math.round(rect.width),
      высота: Math.round(rect.height),
    })
    onDrawn(rect)
  })

  // Клик приходит после pointerup и гасится отдельно: без него отпускание
  // кнопки над ссылкой увело бы со страницы уже после того, как рамка снята.
  const onClick = safely(marks, 'клик во время рисования', (event: Event) => {
    if (isInsideKalka(event)) return
    swallow(event)
  })

  const onKeyDown = safely(marks, 'отмена рисования', (event: Event) => {
    if (!drawing || (event as KeyboardEvent).key !== 'Escape') return
    event.stopPropagation()
    stopDrawing()
    marks.debug('рисование отменено', { причина: 'Escape' })
  })

  document.addEventListener('pointerdown', onPointerDown, true)
  document.addEventListener('pointermove', onPointerMove, true)
  document.addEventListener('pointerup', onPointerUp, true)
  document.addEventListener('click', onClick, true)
  document.addEventListener('keydown', onKeyDown, true)
  marks.debug('режим рисования области включён')

  return (): void => {
    document.removeEventListener('pointerdown', onPointerDown, true)
    document.removeEventListener('pointermove', onPointerMove, true)
    document.removeEventListener('pointerup', onPointerUp, true)
    document.removeEventListener('click', onClick, true)
    document.removeEventListener('keydown', onKeyDown, true)
    // Незаконченная рамка не переживает выключение инструмента: висящий
    // предпросмотр без режима рисования — состояние, из которого нет выхода.
    stopDrawing()
    marks.debug('режим рисования области снят')
  }
}

/**
 * Режим постановки указателя (FR-14).
 *
 * Одного `click` достаточно: у точки нет ни начала, ни ведения — рецензент
 * просто тыкает в место. Гашение то же и по той же причине: клик по ссылке
 * обязан поставить метку, а не увести со страницы.
 *
 * `isPaused` — то же, что у рисования области: клик глотаем всегда, точку при
 * открытом окне замечания не ставим. Разбор — в шапке `watchAreaDrawing`.
 */
export function watchPointPicking(
  onPicked: (x: number, y: number) => void,
  isPaused: () => boolean,
): () => void {
  const onClick = safely(marks, 'постановка указателя', (event: Event) => {
    // События внутри виджета игнорируются целиком: рецензент нажимает кнопку
    // «Кальки», а не ставит метку на её панели.
    if (isInsideKalka(event)) return
    swallow(event)

    if (isPaused()) {
      marks.debug('клик проглочен, указатель не поставлен', { причина: 'пауза' })
      return
    }

    const pointer = event as MouseEvent
    marks.debug('указатель поставлен', {
      x: Math.round(pointer.clientX),
      y: Math.round(pointer.clientY),
    })
    onPicked(pointer.clientX, pointer.clientY)
  })

  document.addEventListener('click', onClick, true)
  marks.debug('режим постановки указателя включён')

  return (): void => {
    document.removeEventListener('click', onClick, true)
    marks.debug('режим постановки указателя снят')
  }
}

/*
 * ── Курсор режима (FR-13, FR-14) ────────────────────────────────────────────
 *
 * Третье собственное правило в чужом `<head>` — после подсветки наведения
 * (`HOVER_CSS`) и заморозки движения (`FREEZE_CSS`), тем же приёмом и с тем же
 * обещанием: снимается целиком, следа не остаётся.
 *
 * ── Почему `!important` на всю страницу ─────────────────────────────────────
 *
 * Пока инструмент выбран, клики по носителю ПРОГЛАТЫВАЮТСЯ (`swallow`), то есть
 * ссылки и кнопки не работают — а курсоры у них свои, `pointer`, и палец над
 * неработающей ссылкой обещает переход, которого не будет. Мягкое правило без
 * `!important` оставило бы это враньё ровно в самых заметных местах страницы.
 * Курсор здесь не украшение, а единственный признак того, что страница сейчас
 * принадлежит «Кальке».
 *
 * ── Почему вырез под собственный интерфейс ──────────────────────────────────
 *
 * `cursor` НАСЛЕДУЕТСЯ, а интерфейс живёт в теневом корне под точкой
 * монтирования: правило на странице протекло бы внутрь виджета на всё, чему
 * курсор не задан явно (кнопкам задан, ящику и полям — нет). Вырез тот же,
 * что у `FREEZE_CSS`, и по той же причине.
 *
 * ── Почему `default`, а не снятие правила ───────────────────────────────────
 *
 * Пока открыто окно замечания, жеста от рецензента не ждут — но страница
 * по-прежнему перехвачена. Снять правило значило бы вернуть палец над ссылками,
 * то есть то самое враньё; `default` не обещает ничего.
 *
 * Инструмент «Текст» этим правилом НЕ пользуется намеренно: там курсор стоит
 * на элементе под указателем (`HOVER_CSS`) и означает «эта строка возьмётся,
 * если нажать», а не «режим включён». Общестраничный крест этот сигнал стёр бы.
 */

/** Атрибут собственного `<style>` с курсором: по нему он и снимается. */
const CURSOR_STYLE_ATTRIBUTE = 'data-kalka-cursor-style'

/**
 * Что показывает курсор на странице носителя.
 *
 * `crosshair` — «целься»: и угол рамки, и точка ставятся ТОЧНО, а обычная
 * стрелка про точность врёт (её горячая точка в вершине, а глазом читается
 * вся стрелка). `default` — «жеста сейчас не жду».
 */
export type PageCursor = 'crosshair' | 'default'

function cursorRule(kind: PageCursor): string {
  return `*:not([${ROOT_ATTRIBUTE}]):not([${ROOT_ATTRIBUTE}] *){cursor:${kind}!important}`
}

/**
 * Ставит курсор на всю страницу носителя. Возвращает ПОЛНОЕ снятие — ровно как
 * `watchPicking`, `freezeMotion` и режимы рисования.
 *
 * Повторный вызов ПЕРЕПИСЫВАЕТ правило, а не добавляет второй `<style>`:
 * смена вида курсора — обычное дело (черновик открылся и закрылся), и копить
 * элементы в чужом `<head>` на каждой такой смене нельзя.
 */
export function setPageCursor(kind: PageCursor): () => void {
  const existing = document.head?.querySelector(`style[${CURSOR_STYLE_ATTRIBUTE}]`)
  const style = existing instanceof HTMLStyleElement ? existing : document.createElement('style')

  style.setAttribute(CURSOR_STYLE_ATTRIBUTE, '')
  style.textContent = cursorRule(kind)
  // head может отсутствовать на экзотической странице — тогда курсора просто
  // не будет, и ронять из-за него инструмент нельзя (то же, что у подсветки).
  if (!existing) document.head?.appendChild(style)

  marks.debug('курсор режима', { вид: kind })

  return (): void => {
    style.remove()
    marks.debug('курсор режима снят')
  }
}

/**
 * Escape на странице носителя, пока открыто окно замечания.
 *
 * Живёт ЗДЕСЬ, а не в самом окне: событие надо поймать независимо от того, где
 * фокус (после проглоченного нажатия по странице он остаётся там, где был),
 * и не пустить в носителя — чужая страница вправе иметь на Escape собственный
 * обработчик и закрыть им своё модальное окно за компанию. Перехват событий
 * носителя — работа этого модуля, а не слоя `widgets` (ARCHITECTURE.md).
 *
 * Возвращает ПОЛНОЕ снятие. Соседний обработчик Escape в `watchAreaDrawing`
 * этому не мешает: тот срабатывает, только пока рамка ВЕДЁТСЯ, а окно замечания
 * к этому времени ещё не открыто.
 */
export function watchEscape(onEscape: () => void): () => void {
  const onKeyDown = safely(marks, 'Escape при открытом окне', (event: Event) => {
    if ((event as KeyboardEvent).key !== 'Escape') return

    event.preventDefault()
    event.stopPropagation()
    marks.debug('Escape перехвачен')
    onEscape()
  })

  document.addEventListener('keydown', onKeyDown, true)
  marks.debug('перехват Escape включён')

  return (): void => {
    document.removeEventListener('keydown', onKeyDown, true)
    marks.debug('перехват Escape снят')
  }
}
