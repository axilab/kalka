/**
 * Русское склонение после числа: 1 правка, 2 правки, 5 правок.
 *
 * Без него интерфейс говорит «Загружено 2 правок», и это читается как
 * небрежность ровно там, где человек оценивает, можно ли доверять цифрам
 * вообще.
 *
 * ── Почему в `shared/lib`, а не в слайсе ────────────────────────────────────
 *
 * Потребителей стало два — список разбора и строка счётчика, — и лежат они
 * в разных слайсах одного слоя, которые друг друга не импортируют. Правило
 * проекта на этот случай названо прямо: захотелось скопировать кусок — значит,
 * он обязан уехать сюда, а не задвоиться.
 */
export function plural(count: number, one: string, few: string, many: string): string {
  const mod100 = count % 100
  if (mod100 >= 11 && mod100 <= 14) return many
  const mod10 = count % 10
  if (mod10 === 1) return one
  if (mod10 >= 2 && mod10 <= 4) return few
  return many
}
