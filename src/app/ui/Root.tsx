import type { JSX } from 'preact'
import { useEffect, useRef, useState } from 'preact/hooks'
import { ReviewMode } from 'pages/review-mode'
import { ExportSummary } from 'widgets/export-summary'
import { MarkLayer } from 'widgets/mark-layer'
import { TextEditor } from 'widgets/text-editor'
import { ToolPalette } from 'widgets/tool-palette'
import { exportEntries, exportFileName } from 'features/export-entries'
import {
  armCutoutCleanupAfterPrint,
  buildReport,
  collectCutouts,
  sweepOrphanCutouts,
} from 'features/print-report'
import { ViewToggle } from 'features/toggle-view'
import { entryStore, numbering } from 'entities/entry'
import type { Mode, Tool } from 'shared/model/ui'
import { printDocument } from 'shared/api/print'
import { createLogger } from 'shared/lib/log'
import { safely } from 'shared/lib/safe'
import { Button } from 'shared/ui/Button'
import { IconReview } from 'shared/ui/icons'

const log = createLogger('root')

/**
 * Идентификатор ящика для `aria-controls` у входа в разбор.
 *
 * Постоянный, а не сгенерированный: виджет на странице ровно один (монтирование
 * проверяет это в `app/lib/mount`), а идентификаторы внутри теневого корня
 * не сталкиваются с идентификаторами носителя.
 */
const DRAWER_ID = 'kalka-drawer'

export function Root(): JSX.Element {
  // Состояние держится хуками, а не сигналами: в этапе 1 состояний два, потребитель
  // у них один. Сигналы вводятся вместе с хранилищем правок (этап 4 PRD), где
  // подписчиков действительно несколько.
  const [mode, setMode] = useState<Mode>('view')
  // Выбранный инструмент живёт здесь, а не в панели: иначе он терялся бы
  // при уходе в Разбор и обратно.
  const [tool, setTool] = useState<Tool | null>(null)
  // Подвал рейки: через него закрытие ящика возвращает фокус на вход в разбор.
  const railFoot = useRef<HTMLDivElement | null>(null)
  const railRef = useRef<HTMLDivElement | null>(null)
  const drawerRef = useRef<HTMLDivElement | null>(null)

  /**
   * Сколько пикселей у правого края занято интерфейсом.
   *
   * ИЗМЕРЯЕТСЯ, а не берётся константой: рейка занимает крайние пиксели всегда,
   * ящик добавляет свои только когда открыт, а на узком экране раскладка
   * меняется целиком. Литерал `408` был бы верен ровно для одной раскладки
   * из трёх.
   *
   * Живёт здесь, а не в виджете: рейка и ящик — разметка `app`, и только тут
   * известно, что сейчас на экране. Выноска окна правки получает эту функцию
   * пропом и зовёт её в момент замера.
   */
  function reservedRight(): number {
    const rail = railRef.current?.getBoundingClientRect().width ?? 0
    const drawer = drawerRef.current
    // Закрытый ящик спрятан через `hidden` и даёт нулевой прямоугольник сам —
    // отдельной проверки состояния не нужно.
    const box = drawer?.getBoundingClientRect().width ?? 0
    return rail + box
  }

  function go(next: Mode): void {
    log.debug('смена режима', { было: mode, стало: next, правок: entryStore.list().length })
    setMode(next)
  }

  // ── Ящик разбора ────────────────────────────────────────────────────────
  //
  // Открытость ящика — ПРОИЗВОДНАЯ от режима, а не второе состояние рядом
  // с ним: инварианты записаны у объявления `Mode` (shared/model/ui). Второй
  // булев флаг про ту же раскладку рано или поздно разошёлся бы с режимом,
  // и «ящик открыт, но режим не review» стало бы достижимым.
  const drawerOpen = mode === 'review'

  function openDrawer(): void {
    log.debug('ящик разбора открыт', { было: mode, инструмент: tool ?? 'нет' })
    go('review')
  }

  // Закрытие возвращает в `edit` при выбранном инструменте и в `view` без него:
  // инструмент переживает разбор и продолжает работать на странице.
  function closeDrawer(): void {
    const next: Mode = tool === null ? 'view' : 'edit'
    log.debug('ящик разбора закрыт', { было: mode, стало: next, инструмент: tool ?? 'нет' })
    go(next)

    // Фокус возвращается на кнопку, которой ящик открывали. Закрыть его можно
    // и изнутри — крестиком в шапке, — и тогда фокусированный элемент только
    // что перестал существовать для клавиатуры: без возврата человек оказался
    // бы в начале страницы носителя и искал бы, откуда он пришёл.
    railFoot.current?.querySelector('button')?.focus()
  }

  // Нажатие по уже выбранному инструменту его выключает. Без этого инструмент
  // «Текст» нельзя было бы снять вовсе: пока он включён, клики по странице
  // перехватываются, и рецензент не смог бы ни перейти по ссылке носителя,
  // ни просто пользоваться прототипом.
  function choose(next: Tool): void {
    const chosen = tool === next ? null : next
    log.debug('выбран инструмент', { было: tool ?? 'нет', стало: chosen ?? 'нет' })
    setTool(chosen)

    // Инвариант из `shared/model/ui`: вне разбора выбранный инструмент — это
    // состояние `edit`, снятый — `view`. В разборе режим не меняется вовсе:
    // ящик остаётся открытым, а инструмент продолжает работать на странице.
    if (mode !== 'review') go(chosen === null ? 'view' : 'edit')
  }

  /*
   * ── Вид «оригинал» снимает инструмент ────────────────────────────────────
   *
   * Словарь обещает про этот вид «править нельзя», и обещание исполняется
   * в двух местах с разными работами: слой меток не включает перехват страницы
   * вовсе (`widgets/mark-layer`), а рейка приводит в порядок ИНТЕРФЕЙС — снимает
   * выбор и гасит палитру, чтобы нажимаемая кнопка не обещала работы, которой
   * не будет (тот же довод, что у отключённого «Экспорта» в `app/ui/host.css`).
   *
   * Решение принимается здесь, в одном месте, — ровно как с тумблером FR-21
   * и слоем меток ниже.
   */
  const [original, setOriginal] = useState(entryStore.showOriginal())
  useEffect(() => {
    setOriginal(entryStore.showOriginal())
    return entryStore.subscribe(() => setOriginal(entryStore.showOriginal()))
  }, [])

  useEffect(() => {
    if (!original || tool === null) return
    log.debug('инструмент снят', { причина: 'оригинал', инструмент: tool })
    setTool(null)
    if (mode !== 'review') go('view')
  }, [original, tool])

  // Вид страницы доступен во всех трёх режимах — это прямые требования FR-21
  // (оригинал / с правками) и FR-22 (где изменения). Решение принимается здесь,
  // в одном месте, а не повторяется в каждом режиме: иначе очередной режим
  // потеряет переключатель по недосмотру, и требование тихо перестанет
  // выполняться.
  //
  // Кнопка ОДНА на три состояния: их всё это время и было три, потому что
  // подсветка в режиме оригинала не показывалась вовсе. Разбор — в шапке
  // `features/toggle-view`. Резервировать место больше не за чем: кнопка
  // не исчезает ни в одном состоянии.
  const toggles = <div class="kalka-rail__group">{<ViewToggle compact />}</div>

  // Слой меток стоит рядом с рейкой и рисуется ВСЕГДА, а не внутри режима:
  // метки видны на странице постоянно (FR-15), и рисует их ВЫБРАННЫЙ
  // ИНСТРУМЕНТ, а не режим. Прежнее `mode === 'edit' ? tool : null` делало
  // «Область» и «Указатель» мёртвыми при закрытом ящике и в разборе: слой
  // получал null, то есть useDrawArea(false) и usePlacePoint(false).
  // Решение принимается здесь, в одном месте, — ровно как с тумблером FR-21, —
  // чтобы очередное состояние не потеряло метки по недосмотру.
  const marks = <MarkLayer tool={tool} reservedRight={reservedRight} />

  // Счётчик правок и состояние «не экспортировано» видны во всех трёх режимах —
  // это прямое требование FR-25. Решение принимается здесь, в одном месте,
  // ровно как с тумблером FR-21 и слоем меток выше: раздай счётчик по режимам —
  // и очередной режим потеряет его по недосмотру, а требование тихо перестанет
  // выполняться.
  /*
   * «Экспорт» СКАЧИВАЕТ ФАЙЛ, а не открывает панель.
   *
   * Панель предпросмотра отсюда убрана целиком. Она показывала список того,
   * что уйдёт в файл, и спрашивала имя рецензента — и обе половины оказались
   * лишними: выбирать в выгрузке нечего, уходит всегда весь набор, а сколько
   * его — уже сказано строкой над самой кнопкой. Имя же не нужно вовсе:
   * правки снимает один человек.
   *
   * Родитель для временного якоря скачивания — ЯЩИК: узел внутри теневого
   * корня, поэтому в чужой DOM при выгрузке не добавляется ничего (см. шапку
   * `shared/api/files.ts`). Прежде его давала панель предпросмотра своим
   * корнем; теперь тем же узлом, что и у печати отчёта ниже.
   */
  function exportNow(): void {
    const parent = drawerRef.current
    if (parent === null) {
      log.warn('выгрузка не начата: ящик разбора не смонтирован')
      return
    }

    const ok = exportEntries(parent)
    log.debug('нажат «Экспорт»', { поставлена: ok, правок: entryStore.list().length })
  }

  /*
   * ── Отчёт о правках ──────────────────────────────────────────────────────
   *
   * Сборка живёт ЗДЕСЬ, а не в `features/print-report`, по той же причине,
   * по которой здесь раздаются тумблер и счётчик: отчёту нужны сведения из
   * ДВУХ слайсов слоя `features` — имя автора и имя файла обмена лежат
   * в `export-entries`, а собирает документ `print-report`. Соседние слайсы
   * одного слоя друг друга не импортируют, и видит их обоих только слой выше.
   * Тот же приём, которым `features/edit-text` передаёт готовый якорь
   * в `entities/entry`.
   */
  function buildAndPrint(): void {
    const parent = drawerRef.current
    if (parent === null) {
      log.warn('отчёт не напечатан: ящик разбора не смонтирован')
      return
    }

    // Сбор сирот ПЕРЕД сборкой: буфер мог набрать вырезок от разведочных
    // кликов, а вытеснение по потолку выбрасывало бы ради них настоящие
    // картинки. К моменту печати набор устоялся, и снимать безопасно.
    sweepOrphanCutouts()

    const entries = entryStore.list()

    /*
     * Имя файла обмена берётся из момента РЕАЛЬНОЙ выгрузки, а не собирается
     * заново на текущее время.
     *
     * `exportFileName` кладёт в имя дату и время до минуты, а отчёт печатают
     * не в ту же минуту, что жали «Экспорт»: собранное заново имя указывало бы
     * на файл, которого на диске нет. Момент выгрузки уже хранится и переживает
     * перезагрузку, поэтому имя восстанавливается из него однозначно.
     *
     * `null` — набор ещё не выгружали. Имя тогда НЕ выдумывается: документ
     * скажет об этом словами. Названное имя несуществующего файла хуже
     * отсутствия имени, потому что выглядит достоверно.
     */
    const exportedAt = entryStore.exportedAt()
    const fileName =
      exportedAt === null ? null : exportFileName('json', new Date(exportedAt), location)

    // Картинки собираются РАЗОМ и до сборки документа: сборка спрашивает
    // вырезку записи трижды, а съёмка на месте синхронна и идёт по чужому DOM.
    // Обоснование целиком — в шапке `collectCutouts`.
    const shots = collectCutouts(entries, document)

    const html = buildReport({
      entries,
      numbers: numbering(),
      cutoutOf: (entryId) => shots.get(entryId) ?? null,
      site: location.origin,
      fileName,
      now: new Date(),
      doc: document,
    })

    // Ни адрес сайта, ни имя автора, ни тексты правок в лог не уходят —
    // по образцу выгрузки. Только количества и признаки.
    log.info('отчёт отправлен на печать', {
      записей: entries.length,
      файлНазван: fileName !== null,
    })

    if (!printDocument({ html, parent })) {
      log.warn('печать отчёта не встала')
      return
    }

    // Вырезки нужны, пока отчёт печатают, и не нужны после. Момент «после»
    // определяется возвращением рецензента к правке, а не фактом печати:
    // средства браузера о своём исходе не сообщают, и очистка по открытию
    // диалога отняла бы картинки у всякого, кто диалог отменил.
    armCutoutCleanupAfterPrint()
  }

  /*
   * Печать отчёта — ГРАНИЦА с чужим кодом, и потому она под `safely`.
   *
   * Обработчик нажатия зовётся из кода носителя, и брошенное отсюда исключение
   * улетает в его консоль как чужая ошибка (NFR-06). Стоило это ровно так:
   * после передеплоя в буфере остались вырезки прежней формы, сборка документа
   * упала на поле, которого у них нет, кнопка «Отчёт» перестала работать молча,
   * а на странице прототипа появилось `Cannot read properties of undefined`.
   *
   * Сама причина того случая закрыта проверкой формы в буфере вырезок. Обёртка
   * закрывает КЛАСС: сборка документа читает и хранилище, и чужой DOM, и любая
   * будущая неожиданность в них обязана стать записью в журнале, а не ошибкой
   * на чужой странице.
   */
  const printReport = safely(log, 'печать отчёта', buildAndPrint)

  const summary = <ExportSummary onExport={exportNow} onReport={printReport} />

  // Список разбора здесь НЕ собирается: он живёт внутри `ReviewMode`. Тумблер
  // вида, слой меток и счётчик раздаются отсюда потому, что нужны во ВСЕХ
  // состояниях (FR-21, FR-15, FR-25) и состояние потеряло бы их по недосмотру.
  // У списка потребитель ровно один — разбор (решение 20 плана вехи), —
  // и протаскивать его сверху значило бы завести проп, который всегда приходит
  // с одним и тем же значением.

  /*
   * ── Рейка ───────────────────────────────────────────────────────────────
   *
   * Заменяет свёрнутую кнопку «Калька» и угловую обёртку. Вместе с ними ушло
   * столкновение специфичности, из-за которого единственная точка входа
   * в продукт рисовалась белым по белому: правила `.kalka-corner .kalka-button`
   * больше нет, потому что нет и самой обёртки.
   *
   * Порядок сверху вниз — по частоте обращения: инструменты, вид страницы,
   * счётчик, вход в разбор. Вход стоит внизу отдельно, отделённый упором:
   * это переход, а не инструмент.
   */
  const rail = (
    <div class="kalka-rail" ref={railRef}>
      <ToolPalette selected={tool} disabled={original} onSelect={choose} />
      {toggles}

      {/*
        Счётчика правок на рейке больше нет: сколько правок каким инструментом
        сделано, говорят значки на самих инструментах выше. Общее число
        не показывается нигде — оно и не отвечало ни на один вопрос,
        который человек себе задаёт.

        Здесь осталась ОДНА строка и только на случай поломки: когда правки
        перестали сохраняться, `ExportSummary` в компактном виде рисует
        предупреждение, а в остальное время — ничего. Места оно поэтому
        не занимает и не резервирует.
      */}
      <ExportSummary compact />

      <div class="kalka-rail__foot" ref={railFoot}>
        <Button
          icon={<IconReview />}
          label="Разбор"
          tip="Разбор"
          selected={drawerOpen}
          expanded={drawerOpen}
          controls={DRAWER_ID}
          onClick={drawerOpen ? closeDrawer : openDrawer}
        />
      </div>
    </div>
  )

  /*
   * Окно правки — сосед слоя меток, а НЕ потомок ящика.
   *
   * Оно становится выноской у правимой строки, а у ящика собственная прокрутка
   * содержимого. Оставленное внутри ящика окно обрезалось бы его границами
   * ровно тогда, когда правимая строка далеко от ящика, — то есть почти всегда.
   *
   * Здесь же единственная во всём коде точка монтирования `TextEditor`:
   * раньше она была внутри панели «Правка», и «Текст» существовал ровно
   * столько, сколько на экране эта панель. Теперь окно живёт вместе
   * с ВЫБРАННЫМ ИНСТРУМЕНТОМ и от режима не зависит.
   */
  return (
    <>
      {marks}
      <TextEditor active={tool === 'text'} reservedRight={reservedRight} />
      {rail}

      {/*
        Ящик СМОНТИРОВАН ВСЕГДА и при закрытии только прячется.

        Размонтирование стоило бы дорого и незаметно: вместе со списком уходят
        режим проверки (его снимает cleanup `EntryList`) и отчёт о только что
        загруженном файле, который живёт состоянием того же компонента.
        Рецензент закрывает ящик, чтобы взглянуть на страницу целиком,
        возвращается — и проверки больше нет. Закрытие ящика — действие лёгкое
        и по смыслу обратимое, а последствие было бы тяжёлым.

        Прячется через `hidden`, а не сдвигом или прозрачностью: сдвинутый
        ящик остаётся в обходе с клавиатуры и в дереве доступности, и человек
        табуляцией уходит в невидимый список. `display: none` из правила
        `.kalka-drawer[hidden]` убирает его отовсюду разом.

        Ловушки фокуса здесь нет намеренно: ящик не модальный, прототип слева
        обязан оставаться доступен — в нём и идёт работа.
      */}
      <div class="kalka-drawer" id={DRAWER_ID} hidden={!drawerOpen} ref={drawerRef}>
        <ReviewMode onCollapse={closeDrawer} exportSummary={summary} />
      </div>
    </>
  )
}
