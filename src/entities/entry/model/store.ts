import type { Entry } from 'shared/model/format'
import type { AnchorMethod, EntryOrigin, EntryStatus, VerifyStatus } from 'shared/model/layer'
import { createLogger } from 'shared/lib/log'

const log = createLogger('entry:store')

/*
 * Хранилище правок — своё, без @preact/signals.
 *
 * ARCHITECTURE.md упоминает сигналы, но пакета в зависимостях нет, а каждая
 * зависимость расходует бюджет 100 КБ gzip (NFR-01, и при конфликте с чистотой
 * слоёв побеждает бюджет). Нужны здесь ровно две вещи — подписка и снимок,
 * это два десятка строк. Компоненты подписываются через useState + useEffect.
 *
 * Хранение — в памяти, и о `localStorage` это хранилище по-прежнему не знает
 * (FR-23 реализован, но не здесь). Запись и чтение снимка делает отдельный
 * модуль `model/persist.ts` по подписке. Это не формальность: так хранилище
 * остаётся проверяемым без браузера, а запись получает право фильтровать
 * уведомления по счётчику ревизии — иначе прокрутка чужой страницы
 * превращалась бы в поток записей в хранилище.
 */

/** Как запись легла на текущую страницу. Пересчитывается на каждом наложении. */
export interface EntryState {
  status: EntryStatus
  /** Каким уровнем найдено место. Отсутствует при `lost`. */
  method?: AnchorMethod
  /**
   * Элемент носителя, на который легла запись. Отсутствует при `lost`.
   *
   * Публикуется движком наложения, который его и нашёл: список разбора
   * прокручивает страницу к месту правки по ЭТОМУ элементу, а не ищет его
   * заново (решение 13 плана вехи). Третий проход поиска рядом с двумя
   * существующими давал бы разные ответы у списка и у слоя на одной и той же
   * странице.
   *
   * `Element` здесь законен: `EntryState` — понятие рантайма слоя, в файл
   * обмена оно не попадает никогда. Вызывающий обязан проверить
   * `element.isConnected` перед использованием: носитель мог перерисовать блок
   * между проходом наложения и кликом по строке.
   */
  element?: Element
}

type Listener = () => void

function createEntryStore() {
  // Map, а не массив: доступ по id — самая частая операция движка наложения,
  // а порядок записей сохраняется вставкой (Map его гарантирует).
  const entries = new Map<string, Entry>()
  const states = new Map<string, EntryState>()
  const listeners = new Set<Listener>()

  /*
   * Происхождение импортированных записей: `id` записи В ХРАНИЛИЩЕ → чей файл
   * её принёс и когда.
   *
   * Отдельная карта рядом с `entries`, а не поля внутри `Entry`: автор —
   * свойство ФАЙЛА, а не записи, и второй его экземпляр в каждой записи дал бы
   * два источника правды (решение 5 плана вехи). Записи, созданные локально,
   * в этой карте отсутствуют вовсе — отсутствие и означает «своя».
   *
   * В снимок `localStorage` карта всё-таки уходит, и это не противоречие:
   * импорт накопительный, дедупликация идёт по паре (автор, исходный `id`), —
   * значит после перезагрузки страницы виджет обязан помнить, чей файл он уже
   * видел. Снимок — не файл обмена, рантаймовые свойства набора в нём законны.
   */
  const origins = new Map<string, EntryOrigin>()

  /**
   * Исход проверки после передеплоя по каждой записи (FR-35).
   *
   * Своя карта, а не поле `EntryState`: статус наложения пересчитывается на
   * каждом проходе движка, а исход проверки — только при включённом режиме
   * проверки и только для `text-override` текущего маршрута. Слитые в одну
   * структуру, они заставили бы движок затирать чужой результат на каждой
   * мутации носителя.
   */
  const verifies = new Map<string, VerifyStatus>()

  /**
   * Включён ли режим проверки (FR-35).
   *
   * Состояние ВИДА, как `originalShown` и `highlightShown`, поэтому ревизию
   * набора не трогает: содержимое снимка от него не меняется, и поднимать им
   * запись в хранилище значило бы писать снимок на каждое нажатие кнопки.
   */
  let verifyModeValue = false

  /**
   * Флаг «показывать оригинал» живёт здесь, а не в отдельном слайсе (FR-21):
   * заводить слайс ради одного булева значения — лишний барель против бюджета,
   * а смысла вне записей у флага нет.
   */
  let originalShown = false

  /**
   * Подсветка изменённых мест (FR-22). Отдельная пометка, а не третье состояние
   * переключателя из FR-21: это разные требования с разным приоритетом, и
   * склеенные в один цикл они мешали бы друг другу — «оригинал с подсветкой»
   * состояние бессмысленное, подсвечивать там нечего.
   */
  let highlightShown = false

  /**
   * Маршрут страницы, на которой сейчас находится носитель (решение 12 плана
   * вехи «Область и Указатель»).
   *
   * Живёт здесь по тому же праву, что `originalShown` и `highlightShown`: это
   * состояние вида слоя, общее для всех его потребителей. Слой меток обязан
   * рисовать записи только текущей страницы и обязан узнавать о клиентской
   * навигации, но завести собственный перехват History API он не может —
   * второй патч поверх нашего же был бы источником тонких поломок при снятии, —
   * а импортировать `app/lib/overlay` из `widgets` запрещено направлением
   * зависимостей. Публикует значение движок наложения, у которого маршрут
   * и так вычислен на каждом проходе.
   *
   * Начальное значение — пустая строка, а НЕ `location.pathname`: хранилище
   * не читает глобали и остаётся проверяемым без браузера.
   */
  let currentRoute = ''

  /**
   * Момент последнего успешного экспорта, ISO 8601, либо `null` — «не
   * экспортировано» (FR-25).
   *
   * Живёт здесь, рядом с `originalShown` и `currentRoute`, а не отдельным
   * слайсом и не вторым ключом хранилища: состояние «не экспортировано» —
   * свойство НАБОРА правок, а не самостоятельная сущность. Отдельный слайс
   * ради одного `string | null` стоил бы бареля и второго источника правды.
   *
   * Правило простое: любое изменение набора сбрасывает значение в `null`,
   * успешный экспорт ставит момент времени. В снимок оно уходит вместе
   * с записями, и потому переживает перезагрузку — иначе после перезагрузки
   * виджет бодро сообщал бы, что всё выгружено.
   */
  let exportedAtValue: string | null = null

  /**
   * Счётчик ревизии НАБОРА записей.
   *
   * Увеличивают его только `seed`, `upsert`, `remove` и `markExported` —
   * то есть ровно то, что меняет содержимое снимка. `setStatus`, `setRoute`,
   * `setShowOriginal` и `setHighlightApplied` его НЕ трогают, хотя и уведомляют
   * подписчиков.
   *
   * От этого разделения зависит вся запись в хранилище. Движок наложения
   * вызывает `setStatus` и `setRoute` на каждом проходе, а проходы идут
   * на каждую мутацию носителя и на каждую навигацию: подписка «пиши при любом
   * уведомлении» превратила бы прокрутку страницы в поток сериализаций набора.
   */
  let revisionValue = 0

  /**
   * Правки не сохраняются: либо запись сорвалась (квота, приватное окно,
   * запрет настройками), либо в хранилище лежит снимок незнакомой версии
   * (NFR-08).
   *
   * Флаг существует, чтобы отказ был ВИДЕН РЕЦЕНЗЕНТУ строкой в панели, а не
   * только строкой в логе: FR-23 и FR-24 приоритета M, и тихая работа в режиме
   * «пишем в никуда» — это потерянная работа заказчика, худший из возможных
   * исходов проекта (R3 раздела 12 PRD).
   */
  let persistFailedValue = false

  /**
   * Уведомление синхронное, и каждый мутирующий метод уведомляет ровно один раз.
   * Список слушателей копируется: подписчик имеет право отписаться прямо
   * в обработчике, и мутация Set во время обхода дала бы пропуск.
   */
  function notify(): void {
    for (const listener of [...listeners]) listener()
  }

  /**
   * Набор изменился: ревизия растёт, состояние «экспортировано» сбрасывается.
   *
   * Одно место на все три мутирующих метода: расставленные по ним вручную
   * две строки со временем разъехались бы, и какая-нибудь мутация тихо
   * перестала бы сбрасывать `exportedAt` — то есть виджет соврал бы рецензенту
   * ровно про то, ради чего сделана FR-25.
   */
  function touch(): void {
    revisionValue += 1
    exportedAtValue = null
  }

  return {
    /** Снимок записей в порядке добавления. */
    list(): Entry[] {
      return [...entries.values()]
    },

    get(id: string): Entry | undefined {
      return entries.get(id)
    },

    /**
     * Полная замена набора записей.
     *
     * Два потребителя: восстановление из хранилища при загрузке
     * (`model/persist.ts`) и дев-стенд. Отдельного метода под восстановление
     * не заводится — «положить набор целиком» это и есть `seed`, а второй
     * метод с той же семантикой со временем разошёлся бы с первым.
     */
    seed(next: readonly Entry[]): void {
      entries.clear()
      states.clear()
      // Происхождение и исходы проверки уходят вместе с записями: набор заменён
      // целиком, и сведения о прежних записях указывали бы в никуда. Восстановление
      // из снимка кладёт происхождение обратно следом — `seedOrigins` вызывается
      // ПОСЛЕ `seed` (`model/persist.ts`).
      origins.clear()
      verifies.clear()
      for (const entry of next) entries.set(entry.id, entry)
      touch()
      log.debug('записи заменены', { всего: entries.size })
      notify()
    },

    /**
     * Кладёт пачку импортированных записей вместе с их происхождением
     * ОДНОЙ операцией: одно уведомление, одна ревизия (решение 18 плана вехи).
     *
     * Не цикл из `upsert`: каждый `upsert` уведомляет подписчиков и поднимает
     * ревизию, и импорт сорока правок дал бы сорок проходов наложения и сорок
     * запланированных записей снимка. Дебаунсы это схлопнут, но полагаться
     * на дебаунс там, где вопрос решается одним методом, — плохая сделка.
     *
     * Пустая пачка не делает НИЧЕГО и не уведомляет: импорт файла, все записи
     * которого оказались дубликатами, не имеет права поднять ревизию набора
     * и сбросить состояние «выгружено».
     */
    addMany(items: readonly { entry: Entry; origin: EntryOrigin }[]): void {
      if (items.length === 0) return

      const before = entries.size
      for (const { entry, origin } of items) {
        entries.set(entry.id, entry)
        origins.set(entry.id, origin)
      }
      touch()
      // Ни имён авторов, ни текстов правок: только количества (решение 22).
      log.debug('записи добавлены пачкой', {
        добавлено: items.length,
        былоДо: before,
        всего: entries.size,
      })
      notify()
    },

    upsert(entry: Entry): void {
      const existed = entries.has(entry.id)
      entries.set(entry.id, entry)
      touch()
      log.debug(existed ? 'запись обновлена' : 'запись добавлена', {
        id: entry.id,
        тип: entry.type,
        всего: entries.size,
      })
      notify()
    },

    remove(id: string): void {
      if (!entries.delete(id)) return
      states.delete(id)
      verifies.delete(id)
      // Запись о происхождении уходит вместе с записью ОБЯЗАТЕЛЬНО: осиротевшая,
      // она навсегда пометила бы удалённый `id` как виденный, и повторный импорт
      // того же файла тихо не вернул бы правку (нарушение Ц4).
      origins.delete(id)
      touch()
      log.debug('запись удалена', { id, всего: entries.size })
      notify()
    },

    /**
     * Возвращает запись НА ЕЁ МЕСТО в наборе.
     *
     * ── Почему `upsert` для этого не годится ────────────────────────────────
     *
     * Набор хранится в `Map`, и порядок в нём — порядок вставки. `set` по КЛЮЧУ,
     * которого в карте уже нет, дописывает запись В КОНЕЦ. Значит откат
     * удаления через `upsert` переставил бы правку в хвост списка, а вместе
     * с ней переехали бы номера всех, кто стоял между: `numbering()` считает
     * их из порядка набора, и тот же номер стоит на метке правки на странице.
     *
     * Отмена, меняющая номера трёх соседних правок, — не отмена. Поэтому
     * карта пересобирается: набор здесь — десятки записей, и пересборка стоит
     * долей миллисекунды, а альтернативы у порядка вставки нет.
     *
     * Происхождение возвращается ТЕМ ЖЕ вызовом, а не отдельным: `remove`
     * стирает его вместе с записью (см. выше), и разнеси эти два действия —
     * между ними существовало бы состояние «чужая правка вернулась, автор
     * потерялся», в котором дедупликация повторного импорта уже сломана.
     *
     * Индекс за пределами набора прижимается к его границам: вызывающий берёт
     * его из момента удаления, а набор с тех пор мог измениться.
     */
    insertAt(index: number, entry: Entry, origin?: EntryOrigin): void {
      const items = [...entries.values()].filter((item) => item.id !== entry.id)
      const at = Math.max(0, Math.min(index, items.length))
      items.splice(at, 0, entry)

      entries.clear()
      for (const item of items) entries.set(item.id, item)
      if (origin !== undefined) origins.set(entry.id, origin)

      touch()
      log.debug('запись возвращена', { id: entry.id, место: at, всего: entries.size })
      notify()
    },

    /**
     * Статус записи после очередного наложения вместе с найденным элементом.
     *
     * Не уведомляет, если статус и уровень не изменились: движок вызывает этот
     * метод на каждом переприменении для каждой записи, а подписан на хранилище
     * он сам — уведомление на неизменившемся статусе замкнуло бы цикл.
     *
     * Элемент при этом обновляется ВСЁ РАВНО — молча, без `notify()`. Носитель
     * мог перерисовать блок, и в состоянии остался бы узел, которого больше нет
     * в документе: прокрутка к нему не сработала бы, хотя место на странице
     * есть. Уведомлять на смене узла нельзя — это вернуло бы ровно тот цикл,
     * который ранний выход и закрывает: смена найденного узла не событие
     * для интерфейса.
     */
    setStatus(id: string, status: EntryStatus, method?: AnchorMethod, element?: Element): void {
      const next: EntryState = {
        status,
        ...(method === undefined ? {} : { method }),
        ...(element === undefined ? {} : { element }),
      }

      const previous = states.get(id)
      if (previous && previous.status === status && previous.method === method) {
        if (previous.element !== element) states.set(id, next)
        return
      }

      states.set(id, next)
      log.debug('статус записи', { id, было: previous?.status ?? 'нет', стало: status })
      notify()
    },

    statusOf(id: string): EntryState | undefined {
      return states.get(id)
    },

    /*
     * ── Происхождение импортированных записей (FR-33) ────────────────────────
     */

    /** Откуда пришла запись. `undefined` — запись создана здесь, она своя. */
    originOf(id: string): EntryOrigin | undefined {
      return origins.get(id)
    },

    /**
     * Видел ли виджет запись с этой парой (автор, исходный `id`).
     *
     * Прямая проверка ключа дедупликации из решения 4: голый `id` ключом быть
     * не может — он уникален лишь внутри одного файла, и два рецензента могут
     * прислать записи с одинаковым `id`.
     */
    hasOrigin(author: string, sourceId: string): boolean {
      for (const origin of origins.values()) {
        if (origin.author === author && origin.sourceId === sourceId) return true
      }
      return false
    },

    /**
     * Восстанавливает карту происхождения из снимка. Вызывается ПОСЛЕ `seed`:
     * тот очищает карту вместе с набором.
     *
     * Ни ревизии, ни уведомления: восстановление идёт до первой отрисовки,
     * а `seed` уже и то, и другое сделал.
     */
    seedOrigins(next: ReadonlyMap<string, EntryOrigin> | undefined): void {
      origins.clear()
      if (!next) return
      for (const [id, origin] of next) origins.set(id, origin)
      log.debug('происхождение восстановлено', { записей: origins.size })
    },

    /** Карта происхождения целиком: её пишет в снимок `model/persist.ts`. */
    origins(): ReadonlyMap<string, EntryOrigin> {
      return origins
    },

    /**
     * Сколько в наборе СВОИХ правок — тех, у которых нет происхождения (FR-26).
     *
     * Вопрос браузера при закрытии вкладки опирается на это число, а не на
     * размер набора: импортированные записи уже лежат файлом на диске
     * у разработчика, терять при закрытии нечего (решение 19).
     */
    localCount(): number {
      let count = 0
      for (const id of entries.keys()) {
        if (!origins.has(id)) count += 1
      }
      return count
    },

    /*
     * ── Режим проверки после передеплоя (FR-35) ──────────────────────────────
     */

    /** Включён ли режим проверки. */
    verifyMode(): boolean {
      return verifyModeValue
    },

    /**
     * Включает и выключает режим проверки.
     *
     * Ревизию набора НЕ трогает: это состояние вида, а не содержимое снимка,
     * и поднимать им запись значило бы писать снимок на каждое нажатие кнопки.
     */
    setVerifyMode(flag: boolean): void {
      if (verifyModeValue === flag) return
      verifyModeValue = flag
      log.debug('режим проверки', { включён: flag })
      notify()
    },

    /** Исход проверки по записи. `undefined` — запись ещё не проверялась. */
    verifyOf(id: string): VerifyStatus | undefined {
      return verifies.get(id)
    },

    /**
     * Записывает исход проверки.
     *
     * Уведомляет ТОЛЬКО при фактической смене исхода, и это не оптимизация,
     * а условие работоспособности — ровно как у `setStatus` и `setRoute`.
     * Проход проверки подписан на хранилище: он пересчитывает исходы на каждое
     * уведомление и пишет их обратно, а запись исхода уведомляет снова. Без
     * этого раннего выхода цикл замкнулся бы на первом же проходе.
     *
     * Ревизию не трогает по той же причине, что и `setVerifyMode`: исход
     * проверки пересчитывается на каждой странице заново и в снимок не уходит.
     */
    setVerify(id: string, status: VerifyStatus): void {
      const previous = verifies.get(id)
      if (previous === status) return
      verifies.set(id, status)
      log.debug('исход проверки', { id, было: previous ?? 'нет', стало: status })
      notify()
    },

    /**
     * Стирает все исходы проверки. Вызывается на выходе из режима: оставленные
     * пометки читались бы как результат проверки, которой сейчас нет.
     */
    clearVerify(): void {
      if (verifies.size === 0) return
      log.debug('исходы проверки стёрты', { было: verifies.size })
      verifies.clear()
      notify()
    },

    /** Показывать ли страницу в оригинале, без правок (FR-21). */
    showOriginal(): boolean {
      return originalShown
    },

    setShowOriginal(flag: boolean): void {
      if (originalShown === flag) return
      originalShown = flag
      log.debug('режим отображения', { оригинал: flag })
      notify()
    },

    /** Подсвечивать ли изменённые места на странице (FR-22). */
    highlightApplied(): boolean {
      return highlightShown
    },

    setHighlightApplied(flag: boolean): void {
      if (highlightShown === flag) return
      highlightShown = flag
      log.debug('подсветка изменённых мест', { включена: flag })
      notify()
    },

    /** Маршрут страницы, на которой сейчас находится носитель. */
    route(): string {
      return currentRoute
    },

    /**
     * Публикует текущий маршрут. Уведомляет подписчиков ТОЛЬКО при фактической
     * смене — ровно по той же причине, что и `setStatus`: движок наложения
     * вызывает этот метод в начале каждого прохода и подписан на хранилище сам,
     * и уведомление на неизменившемся значении замкнуло бы цикл.
     */
    setRoute(next: string): void {
      if (currentRoute === next) return
      log.debug('маршрут страницы', { было: currentRoute || 'нет', стало: next })
      currentRoute = next
      notify()
    },

    /** Момент последнего экспорта, либо `null` — «не экспортировано» (FR-25). */
    exportedAt(): string | null {
      return exportedAtValue
    },

    /**
     * Помечает набор выгруженным.
     *
     * Уведомляет подписчиков И увеличивает ревизию: состояние «экспортировано»
     * обязано попасть в снимок хранилища, иначе после перезагрузки виджет
     * соврал бы, что всё выгружено, — или, что не лучше, соврал бы, что не
     * выгружено ничего.
     */
    markExported(at: string): void {
      exportedAtValue = at
      revisionValue += 1
      // В логе нет самого момента времени: секрета в нём нет, но и пользы тоже,
      // а правило «в лог не уходит содержимое снимка» дешевле держать без
      // исключений, чем спорить о каждом отдельном поле.
      log.debug('набор помечен экспортированным', { всего: entries.size })
      notify()
    },

    /**
     * Ревизия набора: растёт только на `seed`, `upsert`, `remove`
     * и `markExported`. Читает её запись в хранилище — см. комментарий
     * у `revisionValue`.
     */
    revision(): number {
      return revisionValue
    },

    /** Правки не сохраняются в этом браузере (решения 4 и 7 плана вехи). */
    persistFailed(): boolean {
      return persistFailedValue
    },

    /**
     * Поднимает и снимает признак отказа хранения.
     *
     * Ревизию НЕ трогает: это состояние окружения, а не набора правок, и
     * поднимать им запись означало бы пытаться записать снимок ещё раз ровно
     * в тот момент, когда запись только что не удалась.
     *
     * Причина нужна логу, а не интерфейсу: рецензенту в обоих случаях говорится
     * одно и то же — «правки не сохраняются, выгрузите их сейчас», — потому что
     * действие от него требуется одно и то же.
     */
    setPersistFailed(flag: boolean, reason: 'write' | 'version'): void {
      if (persistFailedValue === flag) return
      persistFailedValue = flag
      if (flag) log.warn('правки не сохраняются', { причина: reason, всего: entries.size })
      else log.debug('сохранение правок восстановилось', { всего: entries.size })
      notify()
    },

    /** Возвращает отписку: без неё демонтаж виджета оставил бы утечку. */
    subscribe(listener: Listener): () => void {
      listeners.add(listener)
      return () => {
        listeners.delete(listener)
      }
    },
  }
}

