import type { Entry } from 'shared/model/format'
import type { EntryStatus, VerifyStatus } from 'shared/model/layer'
import { sanitizeHtml } from './sanitize'

/*
 * Классификация исхода проверки после передеплоя (FR-35).
 *
 * ── Главное решение вехи, и наивная реализация здесь даёт молча неверный ответ ─
 *
 * Наивно было бы искать на странице `was` и `now` и делать вывод. Но на странице,
 * где слой уже наложен, `was` не находится НИКОГДА (мы сами его заменили),
 * а `now` находится ВСЕГДА (мы сами его написали) — и проверка бодро сообщила бы,
 * что доехало решительно всё, включая правки, которых агент не касался.
 *
 * Это не гипотетическая опасность: первый проход наложения запускается
 * автоматически при загрузке страницы, до того как разработчик успеет нажать
 * хоть что-нибудь. То есть наивная проверка врала бы ВСЕГДА, а не в редком
 * случае, — и врала бы зелёным цветом, которому человек доверяет тем больше,
 * чем меньше хочет сверять руками. Ради того, чтобы не сверять руками, FR-35
 * и написана.
 *
 * ── Правильный ответ уже вычислен движком наложения ───────────────────────────
 *
 * Уровни 1 и 2 поиска считаются успешными ТОЛЬКО при совпадении текста с `was`
 * (`entities/anchor/model/resolve.ts`). Значит:
 *
 *   `applied` — буквально «исходный текст всё ещё на странице». Правка
 *               НЕ ДОЕХАЛА: агент её не применил.
 *   `lost`    — «`was` не нашёлся ни одним уровнем». Либо правка доехала (текст
 *               заменён на `now`), либо место изменилось иначе. Различает эти
 *               два случая поиск текста `now` по странице МИМО наложенного слоя
 *               (`hasTextOnPage`).
 *   `drifted` — находка третьим уровнем без сверки текста, то есть «вероятно,
 *               вот это место». Для проверки это честное «непонятно»
 *               и НИКОГДА не зелёное.
 *
 * ── Итоговая таблица ──────────────────────────────────────────────────────────
 *
 * | Статус наложения | Текст `now` на странице | Исход        | Цвет    |
 * |------------------|-------------------------|--------------|---------|
 * | `applied`        | не спрашиваем           | не доехало   | красный |
 * | `lost`           | найден                  | доехало      | зелёный |
 * | `lost`           | не найден               | непонятно    | серый   |
 * | `drifted`        | не спрашиваем           | непонятно    | серый   |
 *
 * Проход по странице живёт НЕ здесь, а в `features/verify-applied`: ему нужны
 * и `entities/entry`, и `entities/anchor` сразу, а соседние слайсы одного слоя
 * друг друга не видят (ARCHITECTURE.md). Здесь — чистые функции, то самое место,
 * которое обязано быть проверяемо таблицей входов, а не руками на стенде.
 */

/**
 * Текст правки без разметки.
 *
 * Через `sanitizeHtml`, а не регулярным выражением по тегам: разбор HTML
 * регуляркой ошибается на первом же экзотическом вводе, а белый список
 * в проекте уже есть, и второго заводить нельзя.
 *
 * `doc` приходит параметром: слайс `entities` глобальный `document` не берёт —
 * так он остаётся проверяемым без браузера, ровно как `sanitize.ts`
 * и `serialize.ts`.
 *
 * Этим же разбором пользуется печатный отчёт (`features/print-report`), показывая
 * «стало» текстом без разметки: снятие тегов в проекте остаётся в ОДНОМ месте.
 * Раньше потребителем была читаемая таблица выгрузки (`serialize.ts`) — она ушла
 * вместе со вторым файлом, а причина держать разбор единственным не изменилась.
 */
export function plainNow(entry: Entry, doc: Document): string {
  return plainHtml(entry.now, doc)
}

/** То же самое для произвольной строки разметки. Внутренний вход для `serialize.ts`. */
export function plainHtml(html: string, doc: Document): string {
  const holder = doc.createElement('div')
  holder.append(sanitizeHtml(html, doc))
  return holder.textContent ?? ''
}

/**
 * Исход проверки по статусу наложения и наличию текста `now` на странице.
 *
 * Ровно таблица из шапки, и ничего сверх: функция чистая, без DOM и без
 * хранилища. `nowOnPage` вызывающий обязан спрашивать ТОЛЬКО при статусе
 * `lost` — в остальных случаях ответ не влияет на исход, а лишний обход
 * страницы стоит времени на каждой записи в каждом проходе.
 */
export function classifyArrival(status: EntryStatus, nowOnPage: boolean): VerifyStatus {
  // Исходный текст на месте — значит агент до этой правки не дошёл.
  if (status === 'applied') return 'not-arrived'

  // Место найдено предположительно, текстом не сверялось. Зелёным это красить
  // нельзя: «вероятно, вот это место» и «правка доехала» — разные утверждения.
  if (status === 'drifted') return 'unclear'

  // `lost`: `was` со страницы исчез. Если появился `now` — доехало; если нет —
  // место изменилось как-то иначе, и это задача человеку посмотреть глазами,
  // а не агенту доделать работу. Поэтому `unclear`, а не `not-arrived`.
  return nowOnPage ? 'arrived' : 'unclear'
}
