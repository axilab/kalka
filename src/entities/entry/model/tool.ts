import type { Entry } from 'shared/model/format'
import type { Tool } from 'shared/model/ui'

/**
 * Каким инструментом сделана запись.
 *
 * ── Почему это ПРОИЗВОДНАЯ, а не поле записи ────────────────────────────────
 *
 * В файле обмена инструмента нет и не будет: агенту он бесполезен — тот читает
 * `type` и геометрию, а не то, какой кнопкой человек их создал. Заводить поле
 * ради интерфейса значило бы вписать в контракт вторую истину о том же самом.
 *
 * Раскладка держится на инвариантах формата, а не на догадке: пожелание
 * по оформлению создаёт тот же редактор, что и правку текста
 * (`features/edit-text`), а у замечания заполнено РОВНО ОДНО из `rect` / `point`
 * — этот инвариант обеспечивает `createCommentEntry` и объявляет
 * `shared/model/format`.
 *
 * ── Почему функция живёт ЗДЕСЬ ──────────────────────────────────────────────
 *
 * Потребителей два — палитра инструментов и список разбора, — и оба лежат
 * в `widgets`. Слайсы одного слоя друг друга не импортируют (правило проверяет
 * линтер), поэтому вычислить раскладку в одном и «взять её же» в другом
 * нельзя. То же правило называет и решение — общаться через нижний слой.
 * Ровно по этой причине здесь же живёт `numbering()`.
 *
 * `null` быть не должно ни у одной записи набора: тип этого и не допускает.
 * Ветка оставлена явной — она читается честнее, чем невозможное приведение.
 */
export function toolOf(entry: Entry): Tool | null {
  if (entry.type === 'text-override' || entry.type === 'style-wish') return 'text'
  if (entry.rect) return 'area'
  if (entry.point) return 'point'
  return null
}
