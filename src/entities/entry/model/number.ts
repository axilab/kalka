import { entryStore } from './store'

/*
 * Сквозная нумерация записей (веха «Интерфейс и оформление»).
 *
 * Номер показывается и на метке на странице, и в строке списка разбора, так что
 * разработчик находит место по номеру в обе стороны. До этого связи между
 * меткой и записью не было никакой — ни визуальной, ни числовой.
 *
 * ── Почему это ПРОИЗВОДНАЯ, а не поле записи ────────────────────────────────
 *
 * Хранилище не меняется и номера не хранит. `entryStore.list()` уже возвращает
 * записи в порядке добавления, а накопительный импорт дописывает чужие записи
 * в конец, а не вперемешку, — значит порядок уже есть, и второй истины о нём
 * заводить не надо. Номер в файле обмена тоже не появляется: он ничего
 * не добавляет агенту, а при слиянии двух файлов сталкивался бы сам с собой.
 *
 * ── Почему функция живёт ЗДЕСЬ ──────────────────────────────────────────────
 *
 * Потребителей два — список разбора и слой меток, — и оба лежат в `widgets`.
 * Слайсы одного слоя друг друга не импортируют (правило проверяется линтером),
 * поэтому собрать карту в списке и «взять её же» в слое нельзя: `npm run lint`
 * упадёт. То же правило называет и решение — общаться через хранилище. Вывод
 * номера и есть общение через хранилище: чистая функция над `list()`, которую
 * оба виджета зовут сами.
 *
 * Собирать карту на месте отрисовки тоже нельзя: `EntryList` перекладывает
 * записи в группы по страницам и ставит текущую первой, а группа отдаёт строке
 * только саму запись — исходного порядка там нет ни у кого, и нумерация
 * на второй группе началась бы с единицы заново.
 */

/**
 * Карта «идентификатор записи → её номер», нумерация с единицы.
 *
 * Карта, а не поиск по одной записи: у списка и у слоя меток на руках сразу
 * весь набор, и спрашивать номер по одному значило бы обходить набор заново
 * на каждую строку.
 *
 * Записи, которой в наборе нет, в карте нет тоже — и это ровно то поведение,
 * которое нужно ЧЕРНОВИКУ. Слой меток рисует черновик наравне с сохранёнными
 * записями, но в хранилище его ещё нет: номер появился бы пустым местом
 * в тот самый момент, когда человек смотрит на только что поставленную метку.
 * Правило: метка черновика номера не несёт до нажатия «Сохранить»; сразу после
 * записи номер появляется вместе с ней в списке.
 *
 * Уехавшая запись номер сохраняет: она остаётся в наборе и обязана быть
 * найдена в списке.
 */
export function numbering(): ReadonlyMap<string, number> {
  const numbers = new Map<string, number>()
  entryStore.list().forEach((entry, index) => numbers.set(entry.id, index + 1))
  return numbers
}
