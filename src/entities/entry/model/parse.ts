import type { Entry } from 'shared/model/format'
import { createLogger } from 'shared/lib/log'
import { isObject, isString, readEntry } from './read'

const log = createLogger('entry:parse')

/*
 * Разбор файла обмена (FR-30) — симметрично `model/serialize.ts`, который его
 * пишет. Круг из раздела 6 PRD замыкается здесь: тот же `format: 1`, те же
 * записи, тот же валидатор (`model/read.ts`).
 *
 * КЛЮЧЕВОЕ: проверка версии идёт РАНЬШЕ разбора записей, и это порядок,
 * а не стиль. Файл чужой версии отклоняется ЦЕЛИКОМ — ни одна запись из него
 * не загружается. Разобрать записи, а потом передумать, значило бы превратить
 * «отклоняется целиком» в «применили частично» при первой же невнимательной
 * правке: частично применённый импорт — это тихая потеря части правок, то есть
 * прямое нарушение цели Ц4 и в точности тот исход, ради предотвращения которого
 * поле `format` в контракте вообще заведено (NFR-08).
 *
 * Отдельные негодные записи внутри ГОДНОГО файла — другое дело: они
 * отбрасываются, но их число возвращается вызывающему в `skipped` и называется
 * человеку вслух. Молчаливое исчезновение двух строк — то же нарушение Ц4,
 * только меньшего масштаба.
 *
 * В лог не уходит ни содержимое файла, ни имя автора: только количества,
 * длины и версия формата.
 */

/**
 * Почему файл не загружен. Три причины, различимые для человека:
 *
 * - `unreadable` — не разобралось как JSON: файл повреждён или это вообще
 *   не он;
 * - `not-a-file` — разобралось, но это не файл обмена: нет массива записей;
 * - `foreign-version` — файл обмена, но чужой версии формата.
 *
 * Различать их обязательно: рецензенту в трёх случаях говорятся три разные
 * фразы, и от них зависят три разных действия. Слить их в одно «не получилось»
 * значило бы оставить человека гадать, что делать дальше.
 */
export type ImportRejection = 'unreadable' | 'foreign-version' | 'not-a-file'

/** Годное содержимое файла обмена плюс число отброшенных негодных записей. */
export interface ImportedFile {
  /** Имя рецензента из шапки. Пустая строка — имя не вводили. */
  author: string
  /** Адрес сайта, с которого сняты правки. */
  site: string
  /** Момент экспорта, ISO 8601. */
  exportedAt: string
  entries: Entry[]
  /**
   * Сколько записей отброшено как негодные. Ноль — норма; всё, что больше,
   * обязано быть названо человеку (решение 1 плана вехи).
   */
  skipped: number
}

/**
 * Разбирает сырое содержимое выбранного файла.
 *
 * Вынесена отдельной чистой функцией намеренно: сюда приходит содержимое чужого
 * файла — то есть что угодно, — и это ровно тот код, который проверяется
 * таблицей входов, а не руками на стенде.
 */
export function parseExchangeFile(raw: string): ImportedFile | ImportRejection {
  let parsed: unknown
  try {
    parsed = JSON.parse(raw)
  } catch {
    log.warn('файл не разобрался', { причина: 'не JSON', длина: raw.length })
    return 'unreadable'
  }

  if (!isObject(parsed) || !Array.isArray(parsed.entries)) {
    log.warn('файл не разобрался', { причина: 'не файл обмена', длина: raw.length })
    return 'not-a-file'
  }

  // ДО разбора записей — см. шапку файла. Строгое неравенство, а не «больше»,
  // как у снимка: снимок старой версии чинится дозаполнением на своей же
  // машине, а чужой файл чинить нечем — он пришёл извне, и что там означает
  // format: 0, неизвестно никому.
  const format = typeof parsed.format === 'number' ? parsed.format : 0
  if (format !== 1) {
    log.warn('файл создан другой версией, не загружен ни одной записи', {
      версияФайла: format,
      длина: raw.length,
    })
    return 'foreign-version'
  }

  const entries: Entry[] = []
  for (const item of parsed.entries) {
    const entry = readEntry(item)
    if (entry) entries.push(entry)
  }
  const skipped = parsed.entries.length - entries.length

  // `author`, `site` и `exportedAt` берутся строками, отсутствующие — пустой
  // строкой. Поля контракта обязательные, но чинить чужой файл ОТКАЗОМ
  // в загрузке нельзя, когда сами правки в нём годные: потеря сорока правок
  // из-за пустой шапки — это Ц4 наизнанку.
  const file: ImportedFile = {
    author: isString(parsed.author) ? parsed.author : '',
    site: isString(parsed.site) ? parsed.site : '',
    exportedAt: isString(parsed.exportedAt) ? parsed.exportedAt : '',
    entries,
    skipped,
  }

  log.info('файл обмена разобран', {
    прочитано: entries.length,
    отброшено: skipped,
    версияФормата: format,
  })

  return file
}
