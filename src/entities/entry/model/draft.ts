import type { AgentContext, Anchor, Entry, PointAnchor, RectAnchor, Viewport } from 'shared/model/format'
import { createId } from 'shared/lib/id'
import { createLogger } from 'shared/lib/log'

const log = createLogger('entry:draft')

/**
 * Нейтральные значения полей для агента у записей, снятых ДО вехи
 * «Машиночитаемость».
 *
 * Это больше НЕ заглушка вехи, а совместимость с прошлым, и единственный
 * вызывающий у неё один — `model/read.ts`, дозаполняющий записи из старого
 * снимка `localStorage` или из чужого файла обмена. Новые записи получают
 * измеренные поля от `entities/agent-context`, и обратной дороги к заглушке
 * у них нет (решение 13 плана вехи «Машиночитаемость»).
 *
 * Из публичного API слайса функция убрана намеренно: оставленный экспорт —
 * это приглашение следующему создателю записи взять заглушку вместо измерения,
 * а создателей за три вехи стало три и станет больше.
 *
 * Строковые поля получают `''`. `occurrencesOnPage` получает **`0`**, и это
 * выбор, а не случайность: ноль читается агентом как «не измерено». У нуля
 * появилось и второе законное значение — «считать было нечего»: у элемента
 * с пустым текстом счёт даёт тот же ноль (решение 12). Различать эти два нуля
 * не для кого — запись с пустым `was` не даёт агенту что искать ни при каком
 * значении счётчика. Значение `1` в обоих случаях было бы ложью: «честно
 * посчитанная уникальность» там, где ничего не считалось.
 */
export function agentFieldsPlaceholder(): AgentContext {
  return {
    path: '',
    nearestHeading: '',
    contextBefore: '',
    contextAfter: '',
    occurrencesOnPage: 0,
  }
}

/**
 * Геометрия замечания: либо область, либо точка, и никогда обе сразу.
 *
 * Инвариант выражен типом, а не проверкой в рантайме: `?: never` не даёт
 * передать оба поля вовсе, и нарушение падает на `npm run typecheck`,
 * а не всплывает кривой записью в файле обмена.
 */
export type CommentGeometry =
  | { rect: RectAnchor; point?: never }
  | { point: PointAnchor; rect?: never }

export type CommentEntryInput = CommentGeometry & {
  /**
   * Готовый якорь элемента.
   *
   * Приходит ПАРАМЕТРОМ и не собирается здесь: `captureAnchor` живёт
   * в `entities/anchor` — соседнем слайсе того же слоя, импорт которого
   * запрещён (ARCHITECTURE.md, решение 2 плана вехи). Якорь передаёт
   * вызывающий: `features/draw-area` или `features/place-point` — слой выше
   * обоих entities, которому оба видны.
   *
   * Следующему читателю: «исправление» этой функции на прямой вызов
   * `captureAnchor` уронит линтер границ, а не сделает код короче.
   */
  anchor: Anchor
  /**
   * Готовые пять полей для ИИ-агента.
   *
   * Приходит ПАРАМЕТРОМ ровно по тому же правилу и по той же причине, что
   * и `anchor` выше: `captureAgentContext` живёт в `entities/agent-context` —
   * соседнем слайсе того же слоя, импорт которого запрещён (ARCHITECTURE.md,
   * решение 6 плана вехи «Машиночитаемость»). Собрать оба может только слой
   * выше обоих — `features`.
   *
   * Следующему читателю: «исправление» на прямой вызов уронит линтер границ,
   * а не сократит код.
   */
  agent: AgentContext
  /** Имя тега элемента-якоря строчными. */
  tag: string
  /** Нормализованный исходный текст элемента: по нему идёт сверка уехавшего якоря. */
  was: string
  /** Замечание рецензента обычным текстом, без разметки. */
  comment: string
  viewport: Viewport
  route: string
}

/**
 * Запись типа `comment` целиком (FR-13, FR-14).
 *
 * `now` получает текст замечания как есть: отдельного поля под комментарий
 * в контракте нет, а `now` для типа `comment` иначе пустует. Разметки
 * в замечании не бывает по определению — это текст человеку, а не текст для
 * подстановки в исходники, — поэтому отрисовывается он текстовым узлом,
 * и `sanitizeHtml` к нему не применяется нигде (решение 4 плана вехи).
 *
 * `wasHtml` остаётся ПУСТЫМ, и это тоже решение (5). Поле существует ради
 * восстановления оригинала после наложения, а запись типа `comment` в DOM
 * не применяется никогда (`app/lib/overlay/engine.ts`, `applyToElement`).
 * Положить туда `innerHTML` карточки значило бы отправить агенту половину
 * страницы разметки без единого потребителя и раздуть файл обмена на пустом
 * месте. `was` при этом заполняется полностью: по нему идёт сверка уехавшего
 * якоря (FR-20), и обрезать его нельзя.
 */
export function createCommentEntry(input: CommentEntryInput): Entry {
  const entry: Entry = {
    id: createId(),
    type: 'comment',
    route: input.route,
    tag: input.tag,
    was: input.was,
    wasHtml: '',
    now: input.comment,
    style: {},
    ...input.agent,
    anchor: input.anchor,
    viewport: input.viewport,
    ...(input.rect ? { rect: input.rect } : { point: input.point }),
    at: new Date().toISOString(),
  }

  // Ни текст замечания, ни `was` в лог не попадают: это то, что написал
  // рецензент, и содержимое чужой страницы (решение 18 плана вехи).
  log.debug('замечание собрано', {
    id: entry.id,
    тип: entry.type,
    тег: entry.tag,
    геометрия: entry.rect ? 'область' : 'точка',
    длинаЗамечания: entry.now.length,
    // Показывает, что контекст реально пришёл измеренным, а не остался
    // заглушкой: у заглушки здесь всегда ноль.
    повторов: entry.occurrencesOnPage,
  })

  return entry
}
