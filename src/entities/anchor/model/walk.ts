import { createTextWalker } from 'shared/lib/dom'
import { createLogger } from 'shared/lib/log'
import { normalize } from 'shared/lib/normalize'

const log = createLogger('anchor:walk')

/*
 * Два входа слайса `anchor` в общий обход текстовых узлов страницы.
 *
 * Модуль внутренний, наружу слайса выходит только `hasTextOnPage`. Он существует
 * потому, что `index` якоря и поиск по фрагменту ОБЯЗАНЫ считать по одному
 * и тому же списку совпадений: если запись считает повторы одним способом,
 * а поиск нумерует их другим, номер повтора перестаёт указывать хоть на что-то,
 * и две одинаковые кнопки «Подробнее» снова неразличимы.
 *
 * Сам построитель обхода уехал в `shared/lib/dom.ts` (решение 3 плана вехи
 * «Машиночитаемость»): у него появился ТРЕТИЙ потребитель — `entities/agent-context`,
 * а соседний слайс того же слоя импортировать нас не может. Здесь остались
 * только два входа с разными правилами отсечения, и объясняются они ниже.
 *
 * ── Почему у одного обхода ДВА входа с разными правилами отсечения ───────────
 *
 * У обхода два потребителя ЗДЕСЬ, и им нужны РАЗНЫЕ правила (решение 9 плана
 * вехи «Слой и якоря»):
 *
 *   `collectSnippetMatches` — уровень 3 поиска якоря. Наложенные элементы
 *   отсекать НЕЛЬЗЯ: переприменение слоя обязано находить и их, иначе исправная
 *   правка при каждом проходе теряла бы своё место.
 *
 *   `hasTextOnPage` — проверка после передеплоя (FR-35). Наложенные элементы
 *   отсекать ОБЯЗАТЕЛЬНО: элемент с меткой `data-kalka-applied` содержит текст,
 *   который написали МЫ, а не носитель. Найдя в нём `now` записи A, проверка
 *   объявила бы доехавшей запись B, чей `now` случайно совпал, — то есть
 *   солгала бы зелёным цветом ровно там, где человек ей доверяет.
 *
 * Свести их к одному правилу нельзя ни в ту, ни в другую сторону: каждое
 * из двух ломает второго потребителя. Поэтому параметр, а не два обхода:
 * два обхода со временем разъехались бы в остальных правилах отсечения —
 * собственном интерфейсе и служебных элементах, — и уровень 3 начал бы искать
 * не там, где проверка.
 *
 * Третий потребитель, `entities/agent-context`, отсекает наложенное, но выводит
 * из-под этого правила сам целевой элемент (`keep`): наш собственный текст
 * не должен попасть в счёт повторов, а текст элемента, рядом с которым уже
 * стоит правка, — должен. Ни один из двух входов ниже `keep` не передаёт,
 * и их поведение переездом не затронуто ни на символ.
 */

/**
 * Элементы, чей СОБСТВЕННЫЙ текстовый узел содержит фрагмент, в порядке документа.
 *
 * Ищутся именно родители текстовых узлов, а не любые предки с подходящим
 * `textContent`: иначе в список попал бы весь путь до `body`, и «первое
 * совпадение» всегда означало бы `body`.
 *
 * Отсюда же известное ограничение уровня 3: фрагмент, разорванный вложенной
 * разметкой (`<h3>Краны <strong>полярные</strong></h3>`), целиком не лежит
 * ни в одном текстовом узле и найден не будет. Это осознанный размен: такая
 * правка честно получит статус «уехала» вместо наложения на чужое место.
 *
 * Поведение НЕ ИЗМЕНИЛОСЬ с появлением второго входа: наложенные элементы этот
 * обход по-прежнему видит (`skipApplied: false`), и обязан их видеть.
 */
export function collectSnippetMatches(snippet: string, root: Document): Element[] {
  const needle = normalize(snippet)
  if (!needle) return []

  const walker = createTextWalker(root)
  if (!walker) return []

  const hits: Element[] = []
  while (walker.nextNode()) {
    const text = normalize(walker.currentNode.textContent ?? '')
    if (!text.includes(needle)) continue
    const parent = (walker.currentNode as Text).parentElement
    // Один элемент не попадает в список дважды: у него может быть несколько
    // текстовых узлов, разделённых вложенной разметкой.
    if (parent && hits[hits.length - 1] !== parent) hits.push(parent)
  }

  return hits
}

/**
 * Есть ли такой текст на странице ПОМИМО того, что наложили мы (FR-35).
 *
 * Ранний выход на первом совпадении: вопрос булев, а полный обход страницы
 * ради него — лишняя работа на каждой записи в каждом проходе проверки.
 *
 * Пустая строка — ВСЕГДА `false`. Пустой текст «находится» где угодно,
 * и вернуть на нём `true` значило бы пометить «доехало» запись, у которой
 * нечему было доезжать.
 *
 * Сам текст в лог не уходит: это содержимое правки заказчика (решение 22).
 */
export function hasTextOnPage(text: string, root: Document): boolean {
  const needle = normalize(text)
  if (!needle) {
    log.debug('поиск текста пропущен: искать нечего')
    return false
  }

  const walker = createTextWalker(root, { skipApplied: true })
  if (!walker) return false

  while (walker.nextNode()) {
    if (!normalize(walker.currentNode.textContent ?? '').includes(needle)) continue
    log.debug('текст найден на странице', { знаков: needle.length })
    return true
  }

  log.debug('текста на странице нет', { знаков: needle.length })
  return false
}
