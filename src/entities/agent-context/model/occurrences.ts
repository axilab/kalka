/*
 * Текст страницы, границы целевого элемента в нём, контекст и счёт повторов —
 * ОДНИМ проходом (FR-42, FR-44).
 *
 * ── Решение 1: один проход, один нормализованный текст ───────────────────────
 *
 * Веха существует ради полей, разрешающих дубликаты, а дубликаты разрешаются
 * только тогда, когда «сколько всего вхождений» и «около какого из них мы стоим»
 * посчитаны СОГЛАСОВАННО. Три независимые реализации одного счёта — верный
 * способ получить рассогласование, и оно уже случалось (см. предупреждение
 * от 2026-09-04 в `kalka-anchoring/references/agent-context.md`). Поэтому текст
 * страницы строится здесь ровно один раз за захват, и из него берутся ОБА
 * ответа. Второго прохода в файле нет и быть не должно.
 *
 * ── Решение 2: смещение берётся у ЭТОГО элемента, а не поиском n-го вхождения ─
 *
 * Образец в справке навыка ищет `occurrenceIndex`-е вхождение строки в тексте
 * страницы и требует, чтобы этот индекс совпадал с `anchor.index`. ТАК ДЕЛАТЬ
 * НЕ НАДО, и это не вкусовщина:
 *
 *   `anchor.index` считает ЭЛЕМЕНТЫ, чей собственный текстовый узел содержит
 *   фрагмент (`countPrecedingMatches` → `collectSnippetMatches`). Смещение
 *   в тексте страницы — это позиция ПОДСТРОКИ. Две разные величины: элемент,
 *   чей текст разорван вложенной разметкой (`<p>Краны <strong>полярные</strong>`),
 *   в первый список не попадает вовсе, а в тексте страницы его подстрока
 *   присутствует. Совпадают они на простых случаях и расходятся ровно там,
 *   где веха нужна.
 *
 * Вместо этого обход, строя текст страницы, ЗАПОМИНАЕТ смещение начала и конца
 * текста целевого элемента. Это не догадка про вхождение, а точный ответ, и он
 * снимает связь с `anchor.index` целиком: сверять больше нечего, потому что
 * второго счёта нет.
 *
 * Следующему читателю: не «приводите код к образцу из справки навыка» —
 * это вернёт ошибку 2026-09-04, при которой три записи по трём разным местам
 * получили одинаковый `contextBefore`.
 */

import { CONTEXT_CHARS } from 'shared/config/constants'
import { createTextWalker } from 'shared/lib/dom'
import { createLogger } from 'shared/lib/log'
import { normalize } from 'shared/lib/normalize'
import type { AgentContext } from 'shared/model/format'

const log = createLogger('agent-context:occurrences')

/**
 * Нормализованный текст страницы и точные границы текста целевого элемента
 * внутри него.
 *
 * `at === -1` означает «текст элемента в обходе не встретился»: элемент вне
 * `body`, полностью отсечён правилами обхода либо просто пуст. Это не ошибка,
 * а честный ответ, и потребители обязаны его различать — выдуманный контекст
 * хуже пустого (решения 12, 15).
 */
export interface PageText {
  /** Весь видимый текст страницы, нормализованный и склеенный пробелами. */
  text: string
  /** Смещение начала текста целевого элемента, либо `-1`. */
  at: number
  /** Смещение конца текста целевого элемента (не включая), либо `-1`. */
  end: number
}

/**
 * Строит текст страницы одним проходом и попутно засекает границы текста `el`.
 *
 * `skipApplied: true` — наложенный нами текст не является текстом носителя,
 * и считать по нему повторы значило бы врать агенту про исходники. `keep: el`
 * выводит из-под этого правила сам целевой элемент: при второй правке рядом
 * с первой он может оказаться ВНУТРИ наложенного поддерева, и без `keep`
 * его собственный текст молча исчез бы, а контекст стал бы пустым (решение 4).
 *
 * Куски склеиваются ОДНИМ ПРОБЕЛОМ, а не встык: текст соседних узлов иначе
 * слипается в одно слово («ценаКраны»), и подстрока начинает находиться там,
 * где её на странице нет.
 */
export function buildPageText(el: Element, root: Document): PageText {
  const walker = createTextWalker(root, { skipApplied: true, keep: el })
  if (!walker) return { text: '', at: -1, end: -1 }

  const parts: string[] = []
  let length = 0
  let at = -1
  let end = -1

  while (walker.nextNode()) {
    const node = walker.currentNode as Text
    const text = normalize(node.textContent ?? '')
    // Обход пустые узлы и так пропускает; проверка здесь — чтобы длина,
    // посчитанная ниже, никогда не разошлась с фактической склейкой.
    if (!text) continue

    // Первый кусок начинается с нуля, каждый следующий — за разделяющим пробелом.
    const start = length === 0 ? 0 : length + 1
    parts.push(text)
    length = start + text.length

    const parent = node.parentElement
    // `contains` истинен и для самого элемента, поэтому отдельной проверки
    // «parent === el» не нужно.
    if (parent && el.contains(parent)) {
      if (at === -1) at = start
      // Конец переписывается на каждом узле элемента: у него их может быть
      // несколько, разделённых вложенной разметкой, и нужен последний.
      end = length
    }
  }

  // Ни текста страницы, ни контекста в лог не идёт — только длины и смещение
  // (решение 16). Это содержимое чужой страницы, и в консоли ему делать нечего.
  log.debug('текст страницы построен', { знаковНаСтранице: length, смещение: at })

  return { text: parts.join(' '), at, end }
}

/**
 * `CONTEXT_CHARS` символов до и после текста целевого элемента.
 *
 * При `at === -1` — две пустые строки, а не выдуманный контекст: контекст
 * от чужого места хуже отсутствующего, потому что выглядит осмысленным
 * и молча уводит агента не туда.
 *
 * Края обрезаются по границам строки (`slice` их и так не переходит) и по краям
 * подрезаются пробелы: висящий пробел в начале `contextAfter` ничего не значит,
 * а место в файле обмена занимает.
 */
export function sliceContext(page: PageText): Pick<AgentContext, 'contextBefore' | 'contextAfter'> {
  if (page.at === -1) return { contextBefore: '', contextAfter: '' }

  return {
    contextBefore: page.text.slice(Math.max(0, page.at - CONTEXT_CHARS), page.at).trim(),
    contextAfter: page.text.slice(page.end, page.end + CONTEXT_CHARS).trim(),
  }
}

/**
 * Сколько раз нормализованный `was` встречается в тексте страницы (FR-44).
 *
 * Пустая строка — ВСЕГДА `0` (решение 12): пустой текст «находится» где угодно,
 * и любое другое число было бы ложью. Ноль при этом продолжает означать
 * «не измерено» у записей, снятых до этой вехи, — два законных значения одного
 * нуля, и различать их не для кого: запись с пустым `was` не даёт агенту что
 * искать ни при каком счётчике.
 *
 * Считаются НЕПЕРЕСЕКАЮЩИЕСЯ вхождения: «ааа» в «аааа» — одно, а не два.
 * Для текста страницы разница умозрительная, но перекрывающийся счёт дал бы
 * число, которого человек на странице не увидит.
 *
 * Поиск идёт по той же строке, что и контекст (`page.text`), — см. решение 1
 * в шапке файла.
 *
 * ── Известный предел, найденный на стенде, и он записан, а не замолчан ───────
 *
 * У элемента, чей текст разорван вложенной разметкой, за которой сразу идёт
 * знак препинания, счётчик даёт `0`:
 *
 *   `<p>Порядок описан в <a>инструкции</a>, приложение к договору.</p>`
 *   textContent элемента: «...в инструкции, приложение...»
 *   текст страницы:       «...в инструкции , приложение...»   ← пробел склейки
 *
 * Это прямое следствие склейки узлов пробелом, и склейка обязана остаться:
 * без неё текст соседних узлов слипается в одно слово, и подстрока начинает
 * находиться там, где её на странице нет, — ошибка того же рода, но хуже,
 * потому что молчаливая и в другую сторону.
 *
 * Ноль здесь безопасен и по устройству, и по назначению поля: ни один вывод
 * в коде на `occurrencesOnPage` не строится (решение 11), а ноль уже читается
 * как «не измерено» (решение 12) — то есть агент не примет его за «строка
 * на странице уникальна». Контекст у такого элемента при этом собирается
 * ВЕРНО: он берётся от смещения самого элемента, а не поиском строки
 * (решение 2), и в этом вся разница между двумя полями.
 *
 * Чинить это вторым проходом с другой склейкой НЕЛЬЗЯ: два текста страницы —
 * это ровно то рассогласование, ради устранения которого веха и затевалась.
 */
export function countOccurrences(was: string, page: PageText): number {
  const needle = normalize(was)
  if (!needle) return 0

  let count = 0
  let from = 0

  for (;;) {
    const found = page.text.indexOf(needle, from)
    if (found === -1) break
    count += 1
    from = found + needle.length
  }

  return count
}
