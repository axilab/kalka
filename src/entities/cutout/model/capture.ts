import {
  CUTOUT_BAND_PAD_PX,
  CUTOUT_BAND_PAD_WIDE_PX,
  CUTOUT_CAPTURE_IDLE_MS,
  CUTOUT_FRAME_FULL_WIDTH_RATIO,
  CUTOUT_FRAME_MAX_DEPTH,
} from 'shared/config/constants'
import { createLogger } from 'shared/lib/log'
import { safely } from 'shared/lib/safe'
import type { Cutout } from 'shared/model/layer'
import { buildCutout } from './build'
import { cutoutBuffer } from './buffer'
import { checkCutout } from './check'
import type { CutoutCheck } from './check'

const log = createLogger('cutout:capture')

/*
 * Съёмка вырезки: проверить, расширить кадр, собрать — и, у отложенной
 * съёмки, положить в буфер.
 *
 * ── Почему порядок живёт здесь, а не в точках вызова ────────────────────────
 *
 * Точек съёмки в момент правки три — правка текста, обведённая область,
 * указатель, — и все они лежат в `features`, где соседние слайсы друг друга
 * не импортируют. Собери порядок на месте вызова, и он оказался бы переписан
 * трижды; разойдись однажды одна копия из трёх — в отчёт попала бы
 * непроверенная картинка, и заметили бы это глазами на бумаге. Все три части
 * (`buildCutout`, `checkCutout`, `cutoutBuffer`) лежат в ЭТОМ слайсе, поэтому
 * и порядок между ними — его дело.
 *
 * ── Два входа: синхронный и отложенный ──────────────────────────────────────
 *
 * `makeCutout` — тот же порядок «проверить → расширить кадр → собрать», но
 * синхронно и с результатом на руки. Её зовёт отчёт, когда доснимает место
 * правки прямо в момент печати: буфера у такой записи нет, а откладывать
 * съёмку некуда — документ собирается здесь и сейчас.
 *
 * `captureCutout` — отложенная обёртка над ней, дописывающая запись в буфер.
 * Снаружи её поведение не изменилось.
 *
 * Правило расширения кадра (`widen`) остаётся в одном экземпляре намеренно.
 * Напиши его второй раз для отчёта — и однажды две копии разойдутся, а разойдясь,
 * дадут на бумаге кадр не того размера, чем был на экране.
 *
 * ── Почему съёмка в момент правки ОТЛОЖЕННАЯ ────────────────────────────────
 *
 * Клонирование с вычислением стилей не имеет права подтормаживать чужую
 * страницу: виджет — гость. Правка сохраняется мгновенно, вырезка догоняет.
 * Замер дал 0.1–0.9 мс на элемент, так что это осторожность про будущие
 * тяжёлые случаи (обведённая секция), а не необходимость на измеренных.
 *
 * ── Что снимается: ИСХОДНОЕ состояние ───────────────────────────────────────
 *
 * Съёмка идёт в точке создания записи, где элемент ещё не тронут слоем, и до
 * наложения. Картинка отвечает на «где это на сайте сейчас» и служит парой
 * к строке «было». При повторной правке уже правленого места вырезка НЕ
 * переснимается: точки съёмки зовутся только для новой записи.
 */

export interface MakeCutoutInput {
  /** Элемент-якорь записи. */
  anchor: Element
  /**
   * Показать БОЛЬШЕ окрестности сверху и снизу.
   *
   * Ширина кадра от этого не зависит: во всю ширину страницы он берётся
   * у любой записи. Управляется высота видимой полосы: `true` у замечаний,
   * где «это убрать» без окружающего блока не значит ничего; `false`
   * у правок текста, которым хватает пары строк сверху и снизу.
   */
  wide: boolean
  /**
   * Чем заменить содержимое ЯКОРЯ в клоне. Живой элемент не трогается.
   *
   * Нужно съёмке в момент отчёта: элемент правки текста несёт «стало», а на
   * картинке должно быть «было». Оговорки — в шапке `build.ts`.
   */
  replaceContent?: Node
}

export interface CaptureInput extends MakeCutoutInput {
  /** Идентификатор записи: под ним вырезка ляжет в буфер. */
  entryId: string
}

/**
 * Съёмка с причиной отказа — для журнала точки съёмки.
 *
 * Наружу выходит только `makeCutout`, отдающая `Cutout | null`: причина отказа
 * зовущему не нужна, у отчёта на все три исхода один ответ — показать текст
 * с пометкой. А вот `captureCutout` записывает в журнал ИМЕННО причину, и без
 * этого поля ей пришлось бы либо звать `checkCutout` вторым разом (два места,
 * принимающих одно решение), либо потерять различие между «не прошло проверку»
 * и «кадр не собрался». Оба хуже одного внутреннего поля.
 */
interface CutoutOutcome {
  cutout: Cutout | null
  check: CutoutCheck
  /** Что не вышло. `null` — вышло. */
  failed: 'контраст' | 'кадр' | null
}

/**
 * Поднимается до предка ВО ВСЮ ШИРИНУ страницы.
 *
 * ── Почему во всю ширину, а не по элементу ──────────────────────────────────
 *
 * Узкий кадр отвечает на вопрос «что исправить» — но это и так написано
 * строками «Было/Стало» под картинкой, причём точнее. На вопрос «ГДЕ это
 * на странице» узкий кадр не отвечает вовсе: строка, вырванная из вёрстки,
 * узнаётся ничуть не лучше, чем тот же текст. Полоса во всю ширину показывает
 * место так, как читатель его и увидит, открыв прототип.
 *
 * Плата названа честно: кадр в ширину окна ужимается в колонку отчёта примерно
 * вдвое, и текст на картинке становится мелким. Прежнее «строка печатается 1:1»
 * не выполняется больше — и не должно: разделение труда между картинкой
 * и строками «Было/Стало» делает его ненужным.
 *
 * ── Почему не сразу `<body>` ────────────────────────────────────────────────
 *
 * `<body>` шире любой обёртки, но тащит в вырезку шапку сайта и подвал —
 * то есть ровно то, что не помогает узнать МЕСТО. Берётся первый предок,
 * дотягивающийся до полной ширины: обычно это секция, внутри которой якорь
 * и лежит.
 */
function pageWide(anchor: Element): Element {
  const doc = anchor.ownerDocument
  // `clientWidth` вернее `innerWidth`: он не считает полосу прокрутки, а она
  // на чужой странице почти всегда есть. Но он же равен нулю там, где раскладки
  // нет вовсе, — и тогда порог обнулился бы, а первый же элемент сошёл бы
  // за полосу во всю ширину. Запасной источник закрывает этот случай.
  const pageWidth = doc.documentElement.clientWidth || doc.defaultView?.innerWidth || 0
  const enough = pageWidth * CUTOUT_FRAME_FULL_WIDTH_RATIO

  let frame = anchor
  if (frame.getBoundingClientRect().width >= enough) return frame

  for (let step = 0; step < CUTOUT_FRAME_MAX_DEPTH; step++) {
    const parent = frame.parentElement
    if (parent === null || parent === doc.body || parent === doc.documentElement) break

    frame = parent
    if (parent.getBoundingClientRect().width >= enough) break
  }

  return frame
}

/** Порядок съёмки в одном экземпляре: проверить → расширить кадр → собрать. */
function shoot({ anchor, wide, replaceContent }: MakeCutoutInput): CutoutOutcome {
  // Проверяется ЯКОРЬ, а не кадр: у замечаний кадр шире якоря, но собственный
  // цвет текста контейнера к правке отношения не имеет.
  const check = checkCutout(anchor)
  if (!check.ok) return { cutout: null, check, failed: 'контраст' }

  // Кадр во всю ширину берётся у ЛЮБОЙ записи: место узнают по окружению,
  // а не по вырванной строке. `wide` управляет теперь не шириной кадра,
  // а высотой видимой полосы — у замечаний окрестности нужно больше.
  const frame = pageWide(anchor)
  const bandPad = wide ? CUTOUT_BAND_PAD_WIDE_PX : CUTOUT_BAND_PAD_PX
  const cutout = buildCutout({ anchor, frame, bandPad, replaceContent })

  return { cutout, check, failed: cutout === null ? 'кадр' : null }
}

/**
 * Снимает вырезку места правки и отдаёт её на руки. `null` — снять не удалось.
 *
 * Синхронная и в буфер НЕ пишет: её зовёт отчёт, доснимающий место правки
 * в момент печати. Откладывать там нечего — документ собирается сейчас, —
 * а буфер существует ради записей с ДРУГИХ страниц; писать туда то, что и так
 * под рукой, значило бы раздувать его без нужды.
 *
 * Своего сообщения в журнал не пишет: это не новое действие, а тот же порядок
 * без отсрочки. Всё нужное уже пишут `cutout:check` и `cutout:build`.
 */
export function makeCutout(input: MakeCutoutInput): Cutout | null {
  return shoot(input).cutout
}

/**
 * Снимает вырезку места правки и кладёт её в черновой буфер.
 *
 * Ничего не возвращает и ничего не бросает: съёмка — вспомогательная работа,
 * и её провал не имеет права ни отменить правку, ни уйти исключением в код
 * носителя (NFR-06). Не снялась — отчёт покажет запись текстом с явной
 * пометкой, что место показать картинкой не удалось.
 *
 * В лог не уходят ни текст правки, ни содержимое вырезки.
 */
export function captureCutout({ entryId, anchor, wide, replaceContent }: CaptureInput): void {
  const run = safely(log, `съёмка вырезки ${entryId}`, () => {
    const { cutout, check, failed } = shoot({ anchor, wide, replaceContent })

    if (failed === 'контраст') {
      log.warn('вырезка не снята: не прошла самопроверку', {
        id: entryId,
        контраст: Math.round(check.contrast * 100) / 100,
      })
      return
    }

    if (cutout === null) {
      log.warn('вырезка не снята: кадр не собрался', { id: entryId, широкий: wide })
      return
    }

    const stored = cutoutBuffer.put(entryId, cutout)
    log.info('вырезка снята', {
      id: entryId,
      широкий: wide,
      контраст: Math.round(check.contrast * 100) / 100,
      байт: cutout.html.length,
      вБуфере: stored,
    })
  })

  window.setTimeout(run, CUTOUT_CAPTURE_IDLE_MS)
}
