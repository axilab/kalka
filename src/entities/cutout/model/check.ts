import { CUTOUT_MIN_CONTRAST } from 'shared/config/constants'
import { createLogger } from 'shared/lib/log'
import { backgroundBehind, contrastOf, parseRgba, toCss } from './color'

const log = createLogger('cutout:check')

/*
 * Самопроверка вырезки: не соврала ли она.
 *
 * ── Почему НЕ сверка размеров и текста ──────────────────────────────────────
 *
 * Так проверять кажется естественным и не работает. Гейт 2026-09-05 на живом
 * прототипе показал: у ЕДИНСТВЕННОЙ провалившейся вырезки размеры и текст
 * совпали с оригиналом идеально — такая сверка пропустила бы её насквозь.
 * Провалилась она иначе: заголовок героя, фон под которым рисуют не предки,
 * а СОСЕДНИЕ абсолютно позиционированные слои (картинка и градиентный div).
 * Приём «фон ближайшего непрозрачного предка» дал там белый, и вырезка вышла
 * белым по белому — текст на месте, размеры на месте, читать нечего.
 *
 * ── Что проверяется вместо этого ────────────────────────────────────────────
 *
 * КОНТРАСТ цвета текста с тем фоном, который вырезка получит В ОТЧЁТЕ — а это
 * фон ближайшего непрозрачного предка, и он же вкомпилировывается в кадр при
 * сборке (`build.ts`). Обе стороны спрашивают его у одной функции (`color.ts`):
 * разойдись они, проверка мерила бы фон страницы, а на бумагу приезжал бы
 * белый — и нечитаемые вырезки проходили бы насквозь.
 * Замеры того же гейта: годные вырезки 5.62, 15.49 и 15.67, провальная — 1.00.
 * Порог назначен в `CUTOUT_MIN_CONTRAST`.
 *
 * ── Предел этого знания ─────────────────────────────────────────────────────
 *
 * Обнаружение подтверждено на ОДНОМ наблюдавшемся провале. Что оно ловит класс
 * «фон рисуют соседние слои» вообще, а не один его экземпляр, — это вывод,
 * а не замер. Починка этого класса не делается и не проверялась вовсе: такие
 * места честно деградируют в текст с пометкой.
 *
 * ── На каком элементе ───────────────────────────────────────────────────────
 *
 * На ЭЛЕМЕНТЕ-ЯКОРЕ, независимо от ширины кадра. У замечаний кадр шире якоря,
 * но проверять контейнер бессмысленно: его собственный цвет текста к правке
 * отношения не имеет.
 */

export interface CutoutCheck {
  ok: boolean
  contrast: number
}

/**
 * Годится ли вырезка этого элемента к печати.
 *
 * При провале вырезка выбрасывается, а запись помечается «место показать
 * картинкой не удалось». Отчёт никогда не показывает кривую картинку — либо
 * верную, либо честные слова.
 *
 * Цвета логировать МОЖНО: это оформление чужой страницы, а не содержимое
 * правок заказчика.
 */
export function checkCutout(el: Element): CutoutCheck {
  const view = el.ownerDocument.defaultView
  if (view === null) return { ok: true, contrast: Number.POSITIVE_INFINITY }

  const color = view.getComputedStyle(el).color
  const text = parseRgba(color)
  const background = backgroundBehind(el)

  // Неразобранный цвет — не повод браковать: посчитать контраст нечем,
  // а выбрасывать годную вырезку из-за незнакомой записи цвета значит
  // терять картинки на ровном месте.
  if (text === null) {
    log.debug('цвет текста не разобран, вырезка пропущена без проверки', { цвет: color })
    return { ok: true, contrast: Number.POSITIVE_INFINITY }
  }

  const contrast = contrastOf(text, background)
  const ok = contrast >= CUTOUT_MIN_CONTRAST

  const fields = {
    контраст: Math.round(contrast * 100) / 100,
    цветТекста: color,
    цветФона: toCss(background),
    порог: CUTOUT_MIN_CONTRAST,
  }

  if (ok) log.debug('вырезка прошла самопроверку', fields)
  else log.warn('вырезка отбракована по контрасту', fields)

  return { ok, contrast }
}
