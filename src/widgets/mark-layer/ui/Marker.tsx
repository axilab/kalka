import type { JSX } from 'preact'

export interface MarkerProps {
  /**
   * Форма метки: уголки области, выноска указателя или подчёркивание правки
   * текста. Выбирается по типу записи — см. `kindOf` в `MarkLayer`.
   */
  kind: 'area' | 'point' | 'text'
  /** Место найдено предположительно: метка обязана отличаться видом (FR-20). */
  drifted?: boolean
  /**
   * Сквозной номер записи. Он же стоит в строке списка разбора — по нему
   * разработчик находит место в обе стороны.
   *
   * `undefined` у черновика и у предпросмотра: записи в наборе ещё нет,
   * и номера у неё тоже.
   */
  number?: number
  /** Рамка, которую рецензент ведёт прямо сейчас: по ней не кликают. */
  preview?: boolean
  /** Подпись для программ чтения с экрана и всплывающая подсказка (FR-36). */
  title?: string
  /** Позиция предпросмотра. У сохранённых меток её пишет слой напрямую в узел. */
  style?: JSX.CSSProperties
  onClick?: () => void
  /** Отдаёт узел слою: позиции пишутся императивно, по ссылке (решение 10). */
  attach?: (node: HTMLElement | null) => void
}

/**
 * Одна метка на странице.
 *
 * Кликабельная метка — это `<button>`, а не `<div>` с обработчиком: по ней
 * ходят с клавиатуры и её читают программы чтения с экрана, а метка размером
 * с точку — единственный способ добраться до своего замечания (FR-15).
 * Предпросмотр рисуемой рамки кликабельным не делается вовсе: он живёт
 * доли секунды и в порядок обхода попадать не должен.
 *
 * Позиция сохранённой метки СЮДА НЕ ПРИХОДИТ: её пишет слой прямо в `style`
 * узла на каждом кадре прокрутки, минуя состояние Preact (решение 10 плана
 * вехи). Проп `style` нужен только предпросмотру, который и так перерисовывается
 * на каждое движение указателя.
 */
export function Marker({
  kind,
  drifted,
  number,
  preview,
  title,
  style,
  onClick,
  attach,
}: MarkerProps): JSX.Element {
  const className = [
    'kalka-mark',
    `kalka-mark--${kind}`,
    drifted ? 'kalka-mark--drifted' : '',
    preview ? 'kalka-mark--preview' : '',
  ]
    .filter(Boolean)
    .join(' ')

  if (preview) return <div class={className} style={style} aria-hidden="true" />

  /*
   * Номер рисуется ВНУТРИ метки, а не рядом: он часть метки, и уехать от неё
   * не имеет права ни при какой прокрутке. Для программы чтения с экрана он
   * уже вошёл в доступное имя (`titleOf`), поэтому сам узел от неё скрыт —
   * иначе номер прозвучал бы дважды.
   */
  const badge =
    number === undefined ? null : (
      <span class="kalka-mark__number" aria-hidden="true">
        {number}
      </span>
    )

  /*
   * Метка без обработчика — НЕИНТЕРАКТИВНАЯ, и это не оптимизация, а защита.
   *
   * Так рисуются подчёркивания правок текста. Кнопкой они не становятся,
   * в обход с клавиатуры не попадают и окна замечания не открывают: почему
   * это уничтожило бы правку, разобрано у места вызова в `MarkLayer`.
   *
   * `role="note"` вместо кнопки: пометка на полях, которую читают, а не
   * нажимают. Доступное имя при этом остаётся — иначе для программы чтения
   * с экрана правки текста на странице не существовало бы вовсе (FR-36).
   */
  if (!onClick) {
    return (
      <div class={className} style={style} role="note" title={title} aria-label={title} ref={attach}>
        {badge}
      </div>
    )
  }

  return (
    <button
      type="button"
      class={className}
      style={style}
      title={title}
      aria-label={title}
      ref={attach}
      onClick={onClick}
    >
      {badge}
    </button>
  )
}
