import type { JSX } from 'preact'
import { useEffect, useState } from 'preact/hooks'
import { entryStore } from 'entities/entry'
import { Button } from 'shared/ui/Button'

/*
 * Строка счётчика правок и состояния выгрузки (FR-25).
 *
 * Подписка на хранилище тем же приёмом, что в `MarkLayer` и `OriginalToggle`:
 * `useState` + `useEffect` + `subscribe`. Пакета `@preact/signals`
 * в зависимостях нет, и заводить его ради одной строки нельзя (NFR-01).
 *
 * Весь текст по-русски и без технических терминов (FR-36): ни «localStorage»,
 * ни «хранилище», ни «JSON» рецензент здесь не видит. Он видит «правки»
 * и «выгрузить».
 */

/** Перерисовка при любом изменении хранилища. */
function useStoreVersion(): number {
  const [version, setVersion] = useState(0)
  useEffect(() => entryStore.subscribe(() => setVersion((value) => value + 1)), [])
  return version
}


export interface ExportSummaryProps {
  /**
   * Компактный вид — только значок с числом, без строки состояния и кнопки.
   * Он нужен там, где ширины под строку целиком нет.
   *
   * При нуле правок не рисуется НИЧЕГО: пустой значок поверх чужой страницы —
   * это шум, а не сведения.
   */
  compact?: boolean
  /**
   * Выгрузить набор файлом. В компактном виде не используется: там счётчик
   * только показывает число, а выгрузка живёт в ящике разбора.
   *
   * СКАЧИВАЕТ СРАЗУ, без панели предпросмотра между нажатием и файлом.
   * Показывать перед выгрузкой список того, что уйдёт, незачем: выбирать
   * в нём нечего — уходит всегда весь набор, — а сколько его, сказано
   * строкой прямо над кнопкой.
   */
  onExport?: () => void
  /**
   * Собрать и напечатать отчёт о правках.
   *
   * Отдельная кнопка рядом с «Экспорт», а не шаг внутри предпросмотра:
   * это разные действия для разных людей. «Экспорт» даёт файл для агента,
   * «Отчёт» — документ для человека, который передаёт задачу.
   */
  onReport?: () => void
}

export function ExportSummary({
  compact,
  onExport,
  onReport,
}: ExportSummaryProps): JSX.Element | null {
  useStoreVersion()

  const total = entryStore.list().length
  const exportedAt = entryStore.exportedAt()
  const failed = entryStore.persistFailed()

  /*
   * ── Компактный вид: только тревога, и больше ничего ─────────────────────────
   *
   * Здесь стоял счётчик правок. Он ушёл: сколько правок каким инструментом
   * сделано, говорят значки на самих инструментах, а общее число не отвечало
   * ни на один вопрос, который человек себе задаёт. Вдобавок круглое число
   * в рамке размером с кнопку читалось как кнопка и звало нажать.
   *
   * Осталось одно — ПРИЗНАК ПОЛОМКИ, и вот почему его нельзя убирать вместе
   * со счётчиком. Развёрнутое место в интерфейсе ровно одно — ящик разбора, —
   * и человек, который просто правит страницу и ящика не открывает, о том, что
   * его работа никуда не сохраняется, не узнал бы вовсе. Полная фраза на рейку
   * в 48px не встаёт, поэтому сюда выносится знак, а объяснение целиком
   * ждёт в ящике.
   *
   * При нормальной работе не рисуется НИЧЕГО: флаг поднимается только после
   * неудавшейся записи в хранилище либо когда там лежит снимок более свежей
   * версии «Кальки» (`entities/entry/model/persist`). Пустой набор при старте
   * не пишется вовсе — проваливаться нечему.
   */
  if (compact) {
    if (!failed) return null

    return (
      <span
        class="kalka-summary kalka-summary--compact"
        title="Правки не сохраняются — выгрузите их"
        aria-label="Правки не сохраняются — выгрузите их"
        role="status"
      >
        !
      </span>
    )
  }

  return (
    <div class="kalka-summary">
      {/* Отказ хранения виден рецензенту строкой, а не только строкой в логе:
          тихая работа в режиме «пишем в никуда» — это потерянная работа
          заказчика. Что именно отказало — сорванная запись или незнакомая
          версия снимка, — ему знать незачем: действие требуется одно и то же. */}
      {failed && (
        <p class="kalka-summary__alert">
          Правки не сохраняются в этом браузере — экспортируйте их сейчас
        </p>
      )}

      {/*
        Две кнопки в ряд, обе текстовые и без иконок.

        Иконки у них нет намеренно: «Экспорт» её никогда не имела, а иконка
        на одной кнопке из двух соседних — это либо рябь, либо необъявленная
        правка второй. Пятнадцатая иконка в наборе стоила бы места в бюджете
        бандла (NFR-01) ради ряда из двух подписанных кнопок, где подписи
        и так всё говорят.

        Обе неактивны при нуле правок: печатать отчёт не из чего ровно так же,
        как нечего выгружать.
      */}
      <div class="kalka-summary__actions">
        {/*
          «Экспорт» — ЕДИНСТВЕННАЯ залитая кнопка ящика.

          Модификатор в проекте был и раньше, но здесь не применялся ни разу:
          выгрузка работы выглядела ровно так же, как «Копировать „стало“»
          в строке списка. Главное действие панели обязано отличаться от всего
          прочего в ней — иначе рецензент закроет вкладку, не нажав его.

          Насыщенного цвета это не добавляет: заливка графитовая, то есть тем же
          тоном, которым набран весь интерфейс. Единственный насыщенный цвет
          остаётся за тем, что нанёс человек.
        */}
        {/* Подпись — «Экспорт», а не «Скачать»: она называет то, что человек
            делает с набором, а не то, что произойдёт с файлом. Отклик даёт
            строка выше — она сменится на «выгружены в 15:16». */}
        <Button primary={exportedAt === null} onClick={() => onExport?.()} disabled={total === 0}>
          Экспорт
        </Button>
        <Button onClick={() => onReport?.()} disabled={total === 0}>
          Отчёт
        </Button>
      </div>
    </div>
  )
}
