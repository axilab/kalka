import type { JSX } from 'preact'

/**
 * Свойства анимации обратного отсчёта, считанные от МЕТКИ ВРЕМЕНИ.
 *
 * ── Почему не остаток и не состояние компонента ─────────────────────────────
 *
 * Отсчёт — чистая функция от времени, и держать его в перерисовках значило бы
 * будить список тридцать раз в секунду ради трёх пикселей. Считает его браузер,
 * одной анимацией; отсюда приходят только её длительность и сдвиг.
 *
 * ── Почему сдвиг отрицательный ──────────────────────────────────────────────
 *
 * Он равен уже прошедшему и ставит анимацию в середину, если полосу
 * перерисовали посреди отсчёта. Список перерисовывается от любого изменения
 * набора — удалили соседнюю правку, и без этого сдвига полоса начала бы
 * шесть секунд заново, обещая время, которого нет.
 *
 * Общая для полосы отмены и отчёта о загрузке: приём один, и повторённый
 * вручную он рано или поздно разойдётся знаком.
 */
/**
 * Тип берётся у Preact, а не объявляется свой: собственный интерфейс из двух
 * строковых полей не подходит под `CSSProperties` — там есть индексная
 * сигнатура, и `style={...}` его не принимает.
 */
export type CountdownStyle = Pick<JSX.CSSProperties, 'animationDuration' | 'animationDelay'>

export function countdownStyle(until: number, total: number): CountdownStyle {
  const left = Math.max(0, until - Date.now())
  return {
    animationDuration: `${total}ms`,
    animationDelay: `${left - total}ms`,
  }
}
