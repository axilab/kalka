import type { JSX } from 'preact'
import { useState } from 'preact/hooks'
import { removeWithUndo } from 'features/remove-entry'
import { entryStore, toolOf } from 'entities/entry'
import type { Entry } from 'shared/model/format'
import type { VerifyStatus } from 'shared/model/layer'
import { TOOL_LABELS } from 'shared/model/ui'
import type { Tool } from 'shared/model/ui'
import { scrollToElement } from 'shared/lib/dom'
import { createLogger } from 'shared/lib/log'
import { Button } from 'shared/ui/Button'
import { IconArea, IconPoint, IconText, IconTrash } from 'shared/ui/icons'
import { CopyButton } from './CopyButton'

const log = createLogger('entry-list:row')

/*
 * Одна правка в списке разбора (FR-31, FR-33, FR-34, FR-35).
 *
 * Текст выводится ТЕКСТОВЫМИ УЗЛАМИ. Поле `now` содержит разметку, и
 * `dangerouslySetInnerHTML` здесь не нужен и не появится — ровно как
 * в предпросмотре выгрузки: список отвечает на вопрос «где на сайте эта правка»,
 * а не «как она будет выглядеть».
 *
 * ── Решение 15 отменено, и вот чем ──────────────────────────────────────────
 *
 * Здесь стоял запрет на кнопку удаления: «удаление чужой правки из своего
 * браузера ничего не меняет в файле у разработчика и создаёт ложное ощущение
 * сделанной работы». Запрет снят целиком, потому что опирался на две вещи,
 * которые оказались неверны.
 *
 * Первая: он говорил про ЧУЖУЮ правку, а запрещал кнопку у всех. Удаление
 * своей, ещё не выгруженной правки продукт разрешал и до этого — `saveEdit`
 * снимает запись, когда текст сводят к оригиналу. Добраться до этого можно
 * было только через страницу и редактор, то есть способ был, а прямого пути
 * не было.
 *
 * Вторая: разбор перестал быть чистым чтением не здесь. Загрузка чужого файла,
 * режим проверки и печать отчёта уже меняют состояние набора; правка,
 * вычеркнутая из своего списка, ничем не выделяется среди них.
 *
 * Ложное ощущение сделанной работы закрывается не запретом, а СЛОВАМИ:
 * полоса отмены у чужой правки говорит, что у автора она осталась
 * (`UndoStrip`). А промах закрывается откатом — `features/remove-entry`.
 */

export interface EntryRowProps {
  entry: Entry
  /** Правка этой страницы: только такие кликаются и прокручиваются. */
  here: boolean
  /**
   * Измеритель полосы, занятой интерфейсом.
   *
   * ФУНКЦИЯ, а не готовый прямоугольник: между отрисовкой списка и нажатием
   * на строку окно могло изменить размер, и снятый заранее прямоугольник
   * увёл бы прокрутку не туда. Мерится в момент перехода.
   *
   * Прямоугольник, а не число и не имя класса: строка ничего не знает
   * про ящик, а `shared/lib/dom` — тем более. Ящик закрыт — приходит `null`,
   * и прокрутка ведёт себя как прежде.
   */
  covered?: () => DOMRectReadOnly | null
  /**
   * Сквозной номер записи — тот же, что на метке этой правки на странице.
   * По нему разработчик находит место в обе стороны: от списка к странице
   * и обратно.
   *
   * `undefined` быть не должно ни у одной записи набора; проп необязателен
   * только затем, чтобы строку можно было отрисовать и без нумерации.
   */
  number?: number
}

/** Что показать в строке. Слов `text-override` и `comment` человек не видит (FR-36). */
function describe(entry: Entry): { was: string; now: string } {
  if (entry.type === 'style-wish') {
    // Пожелание оформления — СЛОВАМИ, а не куском JSON: `{"fontSize":"28px"}`
    // человеку ничего не сообщает.
    const parts: string[] = []
    if (entry.style.fontSize) parts.push(`размер ${entry.style.fontSize}`)
    if (entry.style.color) parts.push(`цвет ${entry.style.color}`)
    return { was: entry.was, now: parts.join(', ') || entry.now }
  }

  // И `text-override`, и `comment`: у обоих «было» — исходный текст, а в «стало»
  // идёт то, что написал рецензент (для замечания это текст замечания).
  return { was: entry.was, now: entry.now }
}

/**
 * Рисунок инструмента, которым сделана запись.
 *
 * Те же три иконки, что на кнопках рейки, и это существенно: человек узнаёт
 * тип по следу, который инструмент оставляет, — и на кнопке, и в списке след
 * обязан быть один. Заведи здесь второй набор рисунков, и связь между рейкой
 * и списком пришлось бы держать в голове.
 */
const TOOL_ICONS: Readonly<Record<Tool, JSX.Element>> = {
  text: <IconText />,
  area: <IconArea />,
  point: <IconPoint />,
}

/** Пометка состояния места правки (FR-31). */
const PLACE_WORDS: Record<'lost' | 'drifted', string> = {
  lost: 'место не найдено',
  drifted: 'место могло сместиться',
}

/** Исход проверки словом. Цвета мало: он не читается ни при дальтонизме, ни на плохом мониторе. */
const VERIFY_WORDS: Record<VerifyStatus, string> = {
  arrived: 'доехало',
  'not-arrived': 'не доехало',
  unclear: 'непонятно',
}

export function EntryRow({ entry, here, covered, number }: EntryRowProps): JSX.Element {
  // Сообщение о неудавшейся прокрутке живёт в строке, а не всплывает: человек
  // нажал именно здесь, и ответ обязан быть здесь же.
  const [missed, setMissed] = useState(false)

  const state = entryStore.statusOf(entry.id)
  const origin = entryStore.originOf(entry.id)
  const row = describe(entry)

  const place = state?.status === 'lost' || state?.status === 'drifted' ? state.status : null
  // Исход проверки получают только записи, которым есть куда доезжать
  // (решение 11): пожелание оформления и замечание агент не применяет вовсе.
  const verdict = entryStore.verifyMode() ? entryStore.verifyOf(entry.id) : undefined

  function go(): void {
    if (!here) return

    const element = state?.element
    const ok = element !== undefined && scrollToElement(element, covered?.())
    setMissed(!ok)
    log.debug('переход к месту правки', { id: entry.id, прокручено: ok })
  }

  /*
   * Текст записи — содержимое цели перехода.
   *
   * Кликается ВЛОЖЕННАЯ КНОПКА, а не вся строка. Сделать `<button>` самой
   * строкой нельзя: внутри неё лежат кнопки копирования, а кнопка в кнопке —
   * невалидная разметка. Браузер разорвал бы дерево, `stopPropagation`
   * на обёртке перестал бы спасать, и обход с клавиатуры сломался бы ровно там,
   * где эта правка его чинит.
   */
  const tool = toolOf(entry)

  /*
   * ── Тип и номер — ОДНА плашка ───────────────────────────────────────────
   *
   * Номер отвечает на «где это на странице», рисунок — на «чем это сделано»,
   * и вместе они образуют бирку, приклеенную к правке. Двумя отдельными
   * значками столбиком запись стала бы двухэтажной: на десяти правках это
   * минус одна видимая строка в ящике.
   *
   * Слово рядом с рисунком — для программы чтения с экрана: иконка помечена
   * `aria-hidden` (см. шапку `shared/ui/icons`), и без слова тип существовал
   * бы только для зрячих.
   */
  const mark =
    number === undefined ? null : (
      <span class="kalka-entry__mark">
        {tool && (
          <>
            <span class="kalka-entry__type">{TOOL_ICONS[tool]}</span>
            <span class="kalka-visually-hidden">{TOOL_LABELS[tool]}, </span>
          </>
        )}
        <span class="kalka-entry__number">{number}</span>
      </span>
    )

  const body = (
    <>
      {/* Номер стоит первым в строке: по нему её и ищут, придя со страницы. */}
      {mark}
      {/* Подписи автора здесь нет: правки снимает один человек, и различать
          авторов незачем. Признак «пришла из файла» у записи остался — он
          нужен удалению, которое у чужой правки означает не то же, что
          у своей, — но в строке он не показывается ничем. */}
      {/* У правки с ненайденным местом текст «было» показывается ВСЕГДА
          и целиком: именно им человек ищет строку в исходниках руками (FR-31). */}
      {row.was && <span class="kalka-entry__was">{row.was}</span>}
      <span class="kalka-entry__now">{row.now}</span>
    </>
  )

  return (
    <div class="kalka-entry">
      {/*
        Правка чужой страницы кнопки не получает вовсе: виджет — гость,
        он не рулит навигацией носителя (решение 14). Переход означал бы полную
        перезагрузку документа и потерю всей открытой работы.

        У настоящей кнопки клавиатура работает сама: ручной обработки Enter
        и пробела здесь больше нет и быть не должно — она повторяла бы то,
        что браузер делает лучше.

        Действие названо скрытой подписью ВНУТРИ кнопки, а не `aria-label`:
        `aria-label` заменил бы имя целиком, и текст правки — единственное,
        по чему запись узнают, — для программы чтения с экрана исчез бы.
      */}
      {here ? (
        <button type="button" class="kalka-entry__go" onClick={go}>
          <span class="kalka-visually-hidden">Показать на странице: </span>
          {body}
        </button>
      ) : (
        /*
         * Своя обёртка, а не голый фрагмент.
         *
         * Раскладка записи — сетка из колонки под номер и колонки под текст,
         * и задаётся она на обёртке. Без неё правка чужой страницы теряла бы
         * поле с номером и вставала бы иначе, чем соседка по списку: список
         * расслоился бы на два вида строк по признаку, который для чтения
         * не значит ничего.
         */
        <div class="kalka-entry__body">{body}</div>
      )}

      {place && (
        <span class={`kalka-entry__badge kalka-entry__badge--${place}`}>
          {PLACE_WORDS[place]}
        </span>
      )}

      {verdict && (
        <span class={`kalka-entry__verify kalka-entry__verify--${verdict}`}>
          {VERIFY_WORDS[verdict]}
        </span>
      )}

      {!here && <span class="kalka-entry__note">правка на другой странице</span>}
      {/* Молчания здесь быть не должно: человек нажал и обязан получить ответ,
          даже если ответ — «не получилось». */}
      {missed && <span class="kalka-entry__note">место на странице не найдено</span>}

      {/*
        Плашка действий стоит РЯДОМ с целью перехода, а не внутри неё: кнопка
        в кнопке — невалидная разметка. Прежняя обёртка с `stopPropagation`
        объясняла себя тем, что вся строка — `role="button"`; строка больше
        не кликается, и обёртка вместе с объяснением стала бы мёртвым кодом,
        утверждающим отменённое поведение.

        Подписей у кнопок нет — только всплывающие, через ту же `.kalka-tip`,
        что расшифровывает иконки рейки. Подписать одну кнопку из трёх нельзя:
        подписанная кнопка вчетверо шире иконки, и плашка, ради узости которой
        она и задумана, снова заняла бы ширину записи.

        Подпись удаления при этом РАЗНАЯ и называет последствие, а не действие:
        у чужой правки удаление означает не то же, что у своей.
      */}
      <div class="kalka-entry__actions">
        <Button
          danger
          icon={<IconTrash />}
          label={origin ? 'Убрать чужую правку' : 'Удалить правку'}
          tip={origin ? 'Убрать чужую правку' : 'Удалить правку'}
          onClick={() => removeWithUndo(entry.id)}
        />
        <CopyButton text={row.now}>Копировать «стало»</CopyButton>
        {/* «Было» копируется там, где оно нужно: у правок, чьё место надо
            искать руками. У найденной правки эта кнопка была бы шумом. */}
        {place && <CopyButton text={row.was}>Копировать «было»</CopyButton>}
      </div>
    </div>
  )
}
