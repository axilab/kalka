import type { JSX } from 'preact'
import { undoRemove } from 'features/remove-entry'
import { UNDO_REMOVE_MS } from 'shared/config/constants'
import { countdownStyle } from '../lib/countdown'

/*
 * Полоса отмены на месте удалённой записи (веха «Быстрые действия»).
 *
 * ── Почему полоса стоит В СПИСКЕ, а не всплывает внизу ящика ─────────────────
 *
 * Всплывающее уведомление отвечает на вопрос «что произошло». Здесь вопрос
 * другой: «что было на этом месте». Полоса занимает место удалённой строки
 * ровно до конца окна отката, и потому список не прыгает в момент нажатия —
 * соседние правки остаются там, где на них смотрели.
 *
 * Своей высоты она держит меньше, чем запись: это след, а не запись.
 */

export interface UndoStripProps {
  /** Идентификатор удалённой записи: по нему её и возвращают. */
  id: string
  /**
   * Правка пришла из чужого файла.
   *
   * Фраза у неё ДРУГАЯ, и это не вежливость. Удалённая чужая правка исчезает
   * только в этом браузере: файл автора виджету недоступен, и молчаливое
   * «Правка удалена» обещало бы человеку работу, которой не было.
   */
  imported: boolean
  /** Момент закрытия окна отката: из него считается остаток на полосе. */
  until: number
}

export function UndoStrip({ id, imported, until }: UndoStripProps): JSX.Element {
  /*
   * ── Обратный отсчёт ─────────────────────────────────────────────────────
   *
   * Окно отката закрывается само, и молчать об этом нельзя: кнопка «Вернуть»,
   * которая просто исчезает под курсором, читается как поломка, а не как
   * истёкший срок. Полоса показывает, сколько его осталось.
   *
   * Длительность и сдвиг приходят разметкой, а не стилями, потому что
   * единственный источник правды о сроке — `UNDO_REMOVE_MS`, и он в TypeScript.
   * Продублируй его в CSS — и однажды полоса досчитает до нуля за секунду
   * до удаления или через секунду после, а заметить это будет нечем.
   *
   * Как это считается и почему сдвиг отрицательный — в шапке `countdownStyle`.
   */

  return (
    <div class="kalka-undo">
      <span class="kalka-undo__text">
        {imported ? 'Чужая правка убрана — у автора она осталась' : 'Правка удалена'}
      </span>
      <button type="button" class="kalka-undo__back" onClick={() => undoRemove(id)}>
        Вернуть
      </button>
      <span class="kalka-countdown" aria-hidden="true" style={countdownStyle(until, UNDO_REMOVE_MS)} />
    </div>
  )
}
